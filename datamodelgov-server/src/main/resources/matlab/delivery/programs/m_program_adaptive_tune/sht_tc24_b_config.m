function cfg=sht_tc24_b_config(user)
% 当前正式B的唯一集中配置；界面、独立Start和估时读取相同默认值。
% V2为正式配置，V1仅是较短计算的可选预算；二者使用同一后验目标和核心。
% 配置查询不加载DLL、不启动计算、不挑选旧结果，也不要求历史计时记录。
if nargin<1,user=struct();end
assert(isstruct(user)&&isscalar(user),'TC24:B:Configuration','配置必须是标量结构体。');
version='V2';
if isfield(user,'bConfiguration'),version=upper(char(user.bConfiguration));end
assert(ismember(version,{'V1','V2'}),'TC24:B:ConfigurationVersion', ...
    'bConfiguration只能选择V2（正式）或V1（较短计算对照）。');
cfg=struct('route','transient_instant','bConfiguration',version, ...
    'bConfigurationVersion',['TC24_B_LEAN_',version,'_20261007'], ...
    'bSamplerProfile','legacy_reference','particleCount',1024, ...
    'bProposalGeometryMode','selected_location', ...
    'pilotReplicateCount',3,'pilotSampleCount',64, ...
    'pilotMoveSweeps',2,'pilotFinalMoveSweeps',4, ...
    'formalMoveSweeps',4,'formalFinalMoveSweeps',64,'finalReferenceMove',true, ...
    'maximumStageCount',70,'smcPilotTargetEssFraction',.55, ...
    'smcFormalTargetEssFraction',.50,'kernelWeights',[.23 .17 .25 .10 .25], ...
    'globalPcnFraction',.80,'globalNullOnlyFraction',.50,'globalNullOnlyScale',.35, ...
    'pcnGeometry','spectral','proposalLocalFraction',.45, ...
    'proposalInformedScaleInflation',1,'freezeFinalPcnScale',true, ...
    'pilotInitialScaleSource','final','initialPcnScale',.5*ones(1,5), ...
    'minimumPcnScale',.08*ones(1,5),'maximumPcnScale',.8*ones(1,5), ...
    'dProposalMode','compute','dProposalMaxIterations',3, ...
    'plotEnabled',false,'syntheticValidationFile','','enableRunControl',true);
if strcmp(version,'V1')
    cfg.formalMoveSweeps=2;cfg.formalFinalMoveSweeps=32;cfg.finalReferenceMove=false;
end
names=fieldnames(user);
for k=1:numel(names),cfg.(names{k})=user.(names{k});end
cfg.bConfiguration=version;
cfg.bConfigurationVersion=['TC24_B_LEAN_',version,'_20261007'];
% 显式外部D来源保留read语义；不自动寻找历史D，不把其区间当B先验。
if ~isfield(user,'dProposalMode')&&isfield(user,'dProposalRunId')&&~isempty(user.dProposalRunId)
    cfg.dProposalMode='read';
end
assert(strcmp(cfg.bSamplerProfile,'legacy_reference'),'TC24:B:SamplerProfile', ...
    '正式B采用V1/V2集中配置；历史quality对照须使用隔离研究入口。');
assert(ismember(cfg.particleCount,[512 1024]),'TC24:B:Particles','粒子数请选择512或1024。');
assert(ismember(cfg.route,{'steady','transient_instant'}),'TC24:B:Route','路径须为steady或transient_instant。');
assert(ismember(cfg.dProposalMode,{'compute','read','none'}),'TC24:B:DMode','D准备方式须为compute/read/none。');
end
