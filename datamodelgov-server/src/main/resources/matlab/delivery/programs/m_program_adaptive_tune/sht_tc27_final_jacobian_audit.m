function audit=sht_tc27_final_jacobian_audit(fun,solve,step,lower,upper)
%SHT_TC27_FINAL_JACOBIAN_AUDIT 在冻结最终参数处重算完整准备的逐参数导数。
% 只审计，不回改已接受参数，不把近似Jacobian用于UQ协方差或驻点声明。
t=tic;x=solve.x(:);step=step(:);lower=lower(:);upper=upper(:);
assert(all([numel(step),numel(lower),numel(upper)]==numel(x))&& ...
    all(isfinite([x;step;lower;upper]))&&all(step>0)&&all(lower<upper)&& ...
    all(x>=lower&x<=upper),'TC27:Audit:Bounds','最终审计参数、差分步长或边界不合法。');
[r,m]=fun(x);r=r(:);assert(m.valid&&all(isfinite(r)));J=zeros(numel(r),numel(x));calls=1;
for j=1:numel(x)
    rows=true(numel(r),1);
    if isfield(m,'jacobianBlocks')
        for b=1:numel(m.jacobianBlocks)
            if ~m.jacobianBlocks(b).support(j),rows(m.jacobianBlocks(b).rows)=false;end
        end
    end
    if ~any(rows),continue;end
    hMagnitude=min(step(j),.49*(upper(j)-lower(j)));valid=false;
    for attempt=1:5
        h=hMagnitude;
        if x(j)+h>upper(j),h=-h;end
        q=x;q(j)=q(j)+h;[rr,mm]=fun(q);calls=calls+1;
        if mm.valid&&all(isfinite(rr(:))),J(rows,j)=(rr(rows)-r(rows))/h;valid=true;break;end
        hMagnitude=hMagnitude/2;
    end
    assert(valid,'TC27:Audit:Jacobian','最终完整差分第%d列无效。',j);
    if mod(j,6)==0||j==numel(x),fprintf('最终完整准备Jacobian审计 %d/%d，%.1fs。\n',j,numel(x),toc(t));end
end
A=J.*solve.priorScale.';z=(x-solve.center)./solve.priorScale;
g=A.'*r+solve.actualRegularizationWeight*solve.normalizedPriorPrecision*z;
g(x<=lower+1e-12&g>0)=0;g(x>=upper-1e-12&g<0)=0;
delta=J-solve.dataJacobian;
% 完整准备重新求导后按同一实际保留维数评价；原接受步的矩阵和
% 当前完整矩阵并不相同。旧TSVD结果缺少实际维数时明确标记未知。
retained=NaN;
if isfield(solve,'conditionDiagnostics'),retained=solve.conditionDiagnostics.tsvdRequestedDiagnosticCount;end
diagnostics=sht_tc27_condition_diagnostics(A,solve.options.method, ...
    solve.actualRegularizationWeight,solve.normalizedPriorPrecision,retained);
audit=struct('policy','full_candidate_local_preparation_forward_difference','dataJacobian',J, ...
    'relativeColumnDifference',sqrt(sum(delta.^2,1))./max(sqrt(sum(J.^2,1)),1e-12), ...
    'relativeScaledFrobeniusDifference',norm(delta.*solve.priorScale.','fro')/max(norm(A,'fro'),1e-12), ...
    'projectedGradient',norm(g,Inf),'firstOrderStationarityPassed',norm(g,Inf)<solve.options.gradientTolerance, ...
    'evaluationCount',calls,'elapsed_s',toc(t),'parameterChanged',false, ...
    'regularizedInformationCondition',diagnostics.regularizedInformationCondition, ...
    'regularizedJacobianCondition',diagnostics.regularizedJacobianCondition, ...
    'normalizedDataJacobianCondition',diagnostics.fullDataJacobianCondition, ...
    'normalizedDataInformationCondition',diagnostics.fullDataInformationCondition, ...
    'regularizedConditionSpace',diagnostics.regularizedConditionSpace, ...
    'conditionDiagnostics',diagnostics,'conditionSummary',diagnostics.summary);
fprintf('完整导数审计：相对矩阵差%.5g，精确梯度%.5g，驻点判据%d（不阻止交付）。\n', ...
    audit.relativeScaledFrobeniusDifference,audit.projectedGradient,audit.firstOrderStationarityPassed);
fprintf('完整导数条件数：完整J=%.6g，完整信息=%.6g；%s：J=%.6g，信息=%.6g，有效维数%g。\n', ...
    diagnostics.fullDataJacobianCondition,diagnostics.fullDataInformationCondition, ...
    diagnostics.regularizedConditionSpace,diagnostics.regularizedJacobianCondition, ...
    diagnostics.regularizedInformationCondition,diagnostics.tsvdEffectiveRetainedCount);
end
