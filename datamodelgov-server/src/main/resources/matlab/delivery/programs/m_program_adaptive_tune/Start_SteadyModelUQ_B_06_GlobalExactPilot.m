function result = Start_SteadyModelUQ_B_06_GlobalExactPilot(userCfg)
%START_STEADYMODELUQ_B_06_GLOBALEXACTPILOT 多种子精确SMC调参先导。
% 各重复只检查高概率区域、核尺度和种子稳定性；其粒子不并入B08正式
% 后验。正式后验始终由B08的一套独立全局总体重新生成。
if nargin < 1, userCfg = struct(); end
timer = tic;
manifest = sht_steady_model_uq_b_io('resolvewritable',userCfg);
step1 = sht_steady_model_uq_b_io('loadstep',manifest,1);
step5 = sht_steady_model_uq_b_io('loadstep',manifest,5);
preparationCodeIdentity=sht_tc24_uq_external_io('b','checkpreparationidentity',step5,'B05');
contract = step1.contract;
prior = step1.prior;
geometry = sht_steady_model_uq_b_common( ...
    'samplinggeometry',contract,step5);
guidedProposal = sht_steady_model_uq_b_proposal( ...
    'build',prior,geometry,struct( ...
    'priorWeight',1-contract.config.proposalLocalFraction, ...
    'informedScaleInflation',local_option(contract.config,'proposalInformedScaleInflation',.75)));
guidedProposal.preparationCodeIdentity=preparationCodeIdentity;
replicateCount = local_positive_integer(userCfg,'pilotReplicateCount', ...
    contract.config.pilotReplicateCount);
particleCount = local_positive_integer(userCfg,'pilotSampleCount', ...
    contract.config.pilotSampleCount);
targetEssFraction = local_fraction(userCfg,'smcPilotTargetEssFraction', ...
    contract.config.smcPilotTargetEssFraction);
maximumStageCount = local_positive_integer(userCfg, ...
    'pilotMaximumStageCount',contract.config.maximumStageCount);
resumePilot = local_logical(userCfg,'resumePilotCheckpoint',true);
replicate = repmat(struct('seed',NaN,'smc',struct(), ...
    'posterior_center',[]),replicateCount,1);
theta = zeros(contract.parameterCount,particleCount*replicateCount);
weights = zeros(1,particleCount*replicateCount);
center = zeros(contract.parameterCount,replicateCount);
for r = 1:replicateCount
    seed = contract.config.randomSeed+6000+r;
    checkpointFile = fullfile(manifest.runDir,sprintf( ...
        'step06_pilot_replicate_%02d.mat',r));
    checkpointSignature = struct('schemaVersion', ...
        'steady_uq_b_pilot_replicate_checkpoint_v2_geometric_bridge', ...
        'contractHash',contract.contractHash,'replicateIndex',r, ...
        'seed',seed,'particleCount',particleCount, ...
        'targetEssFraction',targetEssFraction, ...
        'maximumStageCount',maximumStageCount);
    % 核程序或提议几何变化后，旧先导不能继续冒充本次调参证据。
    checkpointSignature.smcCodeHash=sht_steady_model_uq_common('filehash', ...
        which('sht_steady_model_uq_b_smc'));
    checkpointSignature.proposal=guidedProposal;
    checkpointSignature.proposal=rmfield(checkpointSignature.proposal,'createdAt');
    checkpointSignature.config=contract.config;
    checkpointSignature.likelihood=step5.likelihood;
    if strcmp(contract.config.bSamplerProfile,'quality')
        checkpointSignature.moveReferenceHash=sht_steady_model_uq_common('filehash', ...
            which('sht_tc27_uq_move_reference'));
    end
    smc = local_load_checkpoint(checkpointFile, ...
        checkpointSignature,resumePilot);
    if ~isempty(smc)
        fprintf('[2.4UQ-B.6] 复用先导断点 %d/%d：%s\n', ...
            r,replicateCount,checkpointFile);
    else
        options = struct('particleCount',particleCount,'randomSeed',seed, ...
            'targetEssFraction',targetEssFraction, ...
            'moveSweeps',contract.config.pilotMoveSweeps, ...
            'finalMoveSweeps',contract.config.pilotFinalMoveSweeps, ...
            'maximumStageCount',maximumStageCount, ...
            'initialPcnScale',contract.config.initialPcnScale, ...
            'minimumPcnScale',contract.config.minimumPcnScale, ...
            'maximumPcnScale',contract.config.maximumPcnScale, ...
            'targetAcceptance',contract.config.targetAcceptance, ...
            'kernelWeights',contract.config.kernelWeights, ...
            'blockIndex',{contract.samplingKernelIndex}, ...
            'blockBasis',{geometry.blockBasis}, ...
            'blockInformedRank',geometry.blockInformedRank, ...
            'globalBasis',geometry.globalBasis, ...
            'globalInformedRank',geometry.globalInformedRank, ...
            'blockNullScaleMultiplier', ...
            contract.config.blockNullScaleMultiplier, ...
            'maximumBlockNullScale', ...
            contract.config.maximumBlockNullScale, ...
            'globalNullScaleMultiplier', ...
            contract.config.globalNullScaleMultiplier, ...
            'maximumGlobalNullScale', ...
            contract.config.maximumGlobalNullScale, ...
            'globalPcnFraction',contract.config.globalPcnFraction, ...
            'useCache',contract.config.useCache, ...
            'priorOnlyIndex',step5.structuralPriorOnlyParameterIndex, ...
            'verbose',contract.config.verbose);
        options.pcnGeometry=contract.config.pcnGeometry;
        options.freezeFinalPcnScale=contract.config.freezeFinalPcnScale;
        options.blockSingularValue=geometry.blockSingularValue;
        options.globalSingularValue=geometry.globalSingularValue;
        options.samplerProfile=contract.config.bSamplerProfile;
        names={'conditionalEssFraction','resampleEssFraction', ...
            'referenceShrinkage','referenceEigenvalueFloor'};
        for k=1:numel(names),options.(names{k})=contract.config.(names{k});end
        if isfield(userCfg,'runControl'),options.runControl=userCfg.runControl;end
        smc = sht_steady_model_uq_b_smc( ...
            contract,prior,step5.likelihood,guidedProposal,options);
        checkpoint = struct('signature',checkpointSignature, ...
            'smc',smc,'createdAt',datestr(now,30));
        save(checkpointFile,'checkpoint','-v7.3');
        fprintf('[2.4UQ-B.6] 已保存先导断点 %d/%d：%s\n', ...
            r,replicateCount,checkpointFile);
    end
    index = (r-1)*particleCount+(1:particleCount);
    theta(:,index) = smc.theta;
    weights(index) = smc.weights/replicateCount;
    center(:,r) = smc.theta*smc.weights(:);
    replicate(r).seed = seed;
    replicate(r).smc = smc;
    replicate(r).posterior_center = center(:,r);
end
weights = weights/sum(weights);
centerDistance = zeros(replicateCount);
for i = 1:replicateCount
    for j = i+1:replicateCount
        delta = (center(:,i)-center(:,j))./prior.sigma;
        centerDistance(i,j) = norm(delta)/sqrt(contract.parameterCount);
        centerDistance(j,i) = centerDistance(i,j);
    end
end
diagnostic = sht_steady_model_uq_sampler('diagnostics', ...
    theta,weights,log(max(weights,realmin)),prior);
blockScale = vertcat(replicate.smc);
blockScale = vertcat(blockScale.finalBlockScale);
blockAcceptance = vertcat(replicate.smc);
blockAcceptance = vertcat(blockAcceptance.blockAcceptance);
result = struct('method','multi_seed_geometric_bridge_five_kernel_pilot_smc', ...
    'guidedProposal',guidedProposal,'samplingGeometry',geometry, ...
    'replicate',replicate, ...
    'theta',theta,'weights',weights,'diagnostic',diagnostic, ...
    'replicatePosteriorCenter',center, ...
    'replicateCenterDistancePriorScale',centerDistance, ...
    'maximumReplicateCenterDistancePriorScale',max(centerDistance(:)), ...
    'medianFinalBlockScale',median(blockScale,1), ...
    'medianBlockAcceptance',median(blockAcceptance,1), ...
    'pilotReplicateCount',replicateCount, ...
    'pilotSampleCount',particleCount, ...
    'targetEssFraction',targetEssFraction, ...
    'maximumStageCount',maximumStageCount, ...
    'checkpointEnabled',resumePilot, ...
    'methodAPosteriorUsed',false,'truthRead',false,'testDataRead',false);
result.preparationCodeIdentity=preparationCodeIdentity;
sht_tc24_uq_external_io('b','checkpreparationidentity',result,'新计算的B06');
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_b_io( ...
    'savestep',manifest,6,'global_exact_block_smc_pilot',result,runtime);
fprintf(['[2.4UQ-B.6] 先导完成：%d组x%d粒子，合并ESS=%.1f，' ...
    '中心最大标准化距离=%.3f。\n'],replicateCount,particleCount, ...
    diagnostic.effectiveSampleSize,max(centerDistance(:)));
for r = 1:replicateCount
    fprintf(['  seed=%d: initial ESS=%.1f, stage=%d, ESS=%.1f, block acc=' ...
        '[%.1f %.1f %.1f %.1f %.1f]%%, DLL=%d。\n'],replicate(r).seed, ...
        replicate(r).smc.initialImportanceEss, ...
        replicate(r).smc.stageCount, ...
        replicate(r).smc.diagnostic.effectiveSampleSize, ...
        100*replicate(r).smc.blockAcceptance, ...
        replicate(r).smc.dllEvaluationCount);
end
fprintf('[2.4UQ-B.6] 产物：%s\n',file);
result.manifest = manifest;
end

function smc = local_load_checkpoint(fileName,signature,resumeEnabled)
smc = [];
if exist(fileName,'file') ~= 2
    return;
end
saved = load(fileName,'checkpoint');
if ~isfield(saved,'checkpoint') || ...
        ~isfield(saved.checkpoint,'signature') || ...
        ~isfield(saved.checkpoint,'smc')
    error('TC24:UQ:PilotCheckpointIncomplete', ...
        '先导断点结构不完整，保留文件，不能覆盖：%s。',fileName);
end
assert(isfield(saved.checkpoint.signature,'proposal'), ...
    'TC24:UQ:PreparationIdentityMissing','先导断点缺少提议及准备身份，保留文件：%s。',fileName);
sht_tc24_uq_external_io('b','checkpreparationidentity', ...
    saved.checkpoint.signature.proposal,['先导断点 ',fileName]);
assert(resumeEnabled,'TC24:UQ:PilotCheckpointExists', ...
    '先导断点已存在但未允许恢复，不能覆盖：%s。',fileName);
if ~isequaln(saved.checkpoint.signature,signature)
    error('TC24:UQ:PilotCheckpointSignatureMismatch', ...
        '先导断点配置与当前不同，保留文件，不能覆盖：%s。',fileName);
end
smc = saved.checkpoint.smc;
end

function value = local_positive_integer(options,name,defaultValue)
value = local_option(options,name,defaultValue);
if ~isscalar(value) || ~isnumeric(value) || ~isfinite(value) || ...
        value < 1 || value ~= floor(value)
    error('SHT:SteadyUQB:BadPilotInteger', ...
        '%s必须为正整数。',name);
end
value = double(value);
end

function value = local_fraction(options,name,defaultValue)
value = local_option(options,name,defaultValue);
if ~isscalar(value) || ~isnumeric(value) || ~isfinite(value) || ...
        value <= 0 || value >= 1
    error('SHT:SteadyUQB:BadPilotFraction', ...
        '%s必须严格位于(0,1)。',name);
end
value = double(value);
end

function value = local_logical(options,name,defaultValue)
value = local_option(options,name,defaultValue);
if ~isscalar(value) || (~islogical(value) && ...
        ~(isnumeric(value) && ismember(value,[0,1])))
    error('SHT:SteadyUQB:BadPilotLogical','%s必须为逻辑标量。',name);
end
value = logical(value);
end

function value = local_option(options,name,defaultValue)
value = defaultValue;
if isstruct(options) && isfield(options,name) && ...
        ~isempty(options.(name))
    value = options.(name);
end
end
