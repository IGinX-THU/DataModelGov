function result = sht_steady_model_uq_b_adaptive_branch_replay( ...
        deterministicResult, testData, schedules, baseSeed, ...
        branchPrior, userOptions)
%SHT_STEADY_MODEL_UQ_B_ADAPTIVE_BRANCH_REPLAY 自适应补算稳态合理分支。
%
% 首轮只从分支中心启动全部粒子。仅对首轮失败粒子依次尝试
% 门限内两侧初值、扩展初值和远初值；已经成功的后验粒子不再
% 调用DLL。该策略只减少重复回放并改善非线性初值覆盖，不改变
% 参数、分支判据或后验权重。

if nargin < 6 || isempty(userOptions), userOptions = struct(); end
if ~isstruct(userOptions) || ~isscalar(userOptions)
    error('SHT:SteadyUQBAdaptiveBranch:BadOptions', ...
        'userOptions必须为标量结构体。');
end
halfWidth = branchPrior.relativeHalfWidth;
strictResidual = local_option(userOptions, 'strictResidual', 1e-7);
primaryOffsets = local_option(userOptions, 'primaryOffsets', ...
    0);
nearRetryOffsets = local_option(userOptions, 'nearRetryOffsets', ...
    halfWidth * [-0.75, 0.75]);
retryOffsets = local_option(userOptions, 'retryOffsets', ...
    halfWidth * [-1, 1, -1.5, 1.5, -2, 2, -2.5, 2.5, -3.15, 3.15]);
farRetryOffsets = local_option(userOptions, 'farRetryOffsets', ...
    halfWidth * [-4, 4, -5, 5, -6.3, 6.3]);

result = sht_steady_model_uq_b_branch_constrained_replay( ...
    deterministicResult, testData, schedules, baseSeed, branchPrior, ...
    struct('strictResidual', strictResidual, ...
    'seedRelativeOffsets', primaryOffsets));
result.passSummary = local_tag_summary( ...
    result.passSummary, "primary", numel(schedules));

[result, nearRetry] = local_retry_failed(result, ...
    deterministicResult, testData, schedules, baseSeed, branchPrior, ...
    strictResidual, nearRetryOffsets, "near_retry");
[result, firstRetry] = local_retry_failed(result, ...
    deterministicResult, testData, schedules, baseSeed, branchPrior, ...
    strictResidual, retryOffsets, "adaptive_retry");
[result, farRetry] = local_retry_failed(result, ...
    deterministicResult, testData, schedules, baseSeed, branchPrior, ...
    strictResidual, farRetryOffsets, "far_retry");

result.schemaVersion = 'steady_uq_b_adaptive_branch_replay_v2';
result.adaptiveRetry = struct( ...
    'near', nearRetry, 'first', firstRetry, 'far', farRetry, ...
    'finalValidCandidateCount', nnz(result.valid), ...
    'finalFailedCandidateCount', nnz(~result.valid), ...
    'formalPosteriorWeightsModified', false);
end

function [primary, diagnostic] = local_retry_failed( ...
        primary, deterministicResult, testData, schedules, baseSeed, ...
        branchPrior, strictResidual, offsets, phase)
failed = find(~primary.valid);
diagnostic = struct('phase', phase, ...
    'inputCandidateIndex', failed(:), ...
    'inputCandidateCount', numel(failed), ...
    'recoveredCandidateIndex', zeros(0,1), ...
    'recoveredCandidateCount', 0, ...
    'remainingCandidateIndex', failed(:), ...
    'remainingCandidateCount', numel(failed));
if isempty(failed) || isempty(offsets)
    return;
end

retry = sht_steady_model_uq_b_branch_constrained_replay( ...
    deterministicResult, testData, schedules(failed), baseSeed(failed), ...
    branchPrior, struct('strictResidual', strictResidual, ...
    'seedRelativeOffsets', offsets));
retry.passSummary = local_tag_summary( ...
    retry.passSummary, phase, numel(failed));
primary.passSummary = [primary.passSummary; retry.passSummary];
primary.initialSeedTransferMaxAbsError = max( ...
    primary.initialSeedTransferMaxAbsError, ...
    retry.initialSeedTransferMaxAbsError);
primary.seedRelativeOffsets = [primary.seedRelativeOffsets, ...
    retry.seedRelativeOffsets];

recoveredLocal = find(retry.valid);
recoveredGlobal = failed(recoveredLocal);
nPoint = primary.pointCount;
primaryPassCount = height(primary.passSummary) - height(retry.passSummary);
for i = 1:numel(recoveredLocal)
    localIndex = recoveredLocal(i);
    globalIndex = recoveredGlobal(i);
    candidate = retry.candidate(localIndex);
    finitePass = isfinite(candidate.selectedPass);
    candidate.selectedPass(finitePass) = ...
        candidate.selectedPass(finitePass) + primaryPassCount;
    primary.candidate(globalIndex) = candidate;
    primary.valid(globalIndex) = true;

    globalRows = (globalIndex - 1) * nPoint + (1:nPoint);
    localRows = (localIndex - 1) * nPoint + (1:nPoint);
    replacement = retry.rootTable(localRows, :);
    replacement.particle_local_index(:) = globalIndex;
    finiteRootPass = isfinite(replacement.selected_pass);
    replacement.selected_pass(finiteRootPass) = ...
        replacement.selected_pass(finiteRootPass) + primaryPassCount;
    primary.rootTable(globalRows, :) = replacement;
end

diagnostic.recoveredCandidateIndex = recoveredGlobal(:);
diagnostic.recoveredCandidateCount = numel(recoveredGlobal);
diagnostic.remainingCandidateIndex = find(~primary.valid).';
diagnostic.remainingCandidateCount = nnz(~primary.valid);
end

function summary = local_tag_summary(summary, phase, candidateCount)
summary.phase = repmat(string(phase), height(summary), 1);
summary.evaluated_candidate_count = ...
    repmat(candidateCount, height(summary), 1);
summary = movevars(summary, ...
    {'phase','evaluated_candidate_count'}, 'Before', 1);
end

function value = local_option(options, name, defaultValue)
value = defaultValue;
if isfield(options, name) && ~isempty(options.(name))
    value = options.(name);
end
if ~isnumeric(value) || any(~isfinite(value(:)))
    error('SHT:SteadyUQBAdaptiveBranch:BadNumericOption', ...
        'userOptions.%s必须为有限数值。', name);
end
if strcmp(name, 'strictResidual') && ...
        (~isscalar(value) || value <= 0)
    error('SHT:SteadyUQBAdaptiveBranch:BadResidual', ...
        'strictResidual必须为有限正标量。');
end
if ~strcmp(name, 'strictResidual') && ...
        any(1 + value(:) <= 0)
    error('SHT:SteadyUQBAdaptiveBranch:BadOffset', ...
        '%s包含使初始转速非正的偏移。', name);
end
end
