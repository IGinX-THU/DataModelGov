function conditional=sht_tc24_uq_conditional_nuisance(contract,step2,theta)
% C/D矩边缘化目标的条件附加参数。保留其与主要参数的条件关联，
% 不在预测时重新无条件抽取附加参数先验。
if isfield(step2,'boundedLikelihood')
    % 新目标使用原始有界先验；保留有界条件积分节点，不能退回无界高斯。
    model=step2.boundedLikelihood;model.nodeCount=128;
    exact=sht_steady_model_uq_c_common('evaluate',contract,theta,contract.trainingData, ...
        struct('useCache',true,'useRobustTransientFallback',true));
    assert(all(exact.valid),'TC24:Conditional:BoundedInvalid','有界条件分布需有效训练回放。');
    [~,detail]=sht_tc24_uq_c_bounded_likelihood('evaluate',model,exact.residual,exact.valid,true);
    box=detail.box;
    conditional=struct('mean',box.mean,'covariance',mean(box.covariance,3), ...
        'covarianceByParticle',box.covariance,'priorMean',step2.nuisanceMean, ...
        'trainingValid',exact.valid,'parameterTable',contract.nuisanceParameterTable, ...
        'gain',model.gain,'anchorVariationCovariance',model.anchorVariationCovariance, ...
        'marginalOutsideSupportProbability',zeros(size(box.mean)),'supportClippingApplied',false, ...
        'representation','bounded_affine_conditional_QMC','quadratureSamples',box.samples, ...
        'quadratureWeights',box.weights,'quadratureCount',model.nodeCount, ...
        'quadratureSeed',model.seed,'integrationEss',box.integrationEss, ...
        'dllEvaluationCount',exact.dllEvaluationCount);
    % 分布由截断前高斯参数与物理边界完整确定，不必在Excel展开全部积分点。
    conditional.gaussianMean=-model.gain*(exact.residual+model.additiveResidualShift);
    conditional.gaussianCovariance=model.conditionalCovariance;
    return;
end
G=(step2.nuisanceJacobian{1}+step2.nuisanceJacobian{2})/2;
V=diag(step2.nuisanceVariance);
S=step2.measurementC.selected.covariance;
gain=(V*G.')/S;
exact=sht_steady_model_uq_c_common('evaluate',contract,theta,contract.trainingData, ...
    struct('useCache',true,'useRobustTransientFallback',true));
residual=exact.residual+step2.likelihood.additiveResidualShift;
mu=step2.nuisanceMean-gain*residual;
mu(:,~exact.valid)=repmat(step2.nuisanceMean,1,nnz(~exact.valid));
covariance=V-gain*G*V;covariance=(covariance+covariance.')/2;
assert(min(eig(covariance))>=-1e-12,'TC24:Conditional:Covariance','条件协方差非半正定。');
extra=.25*(step2.nuisanceJacobian{1}-step2.nuisanceJacobian{2})*V* ...
    (step2.nuisanceJacobian{1}-step2.nuisanceJacobian{2}).';
reconstructed=step2.baseMeasurement.selected.covariance+extra+G*V*G.';
assert(norm(reconstructed-S,'fro')/norm(S,'fro')<1e-10, ...
    'TC24:Conditional:Identity','条件模型必须与用于采样的边缘化目标一致。');
sd=sqrt(max(diag(covariance),eps));tbl=contract.nuisanceParameterTable;
outside=.5*erfc(-(tbl.lower_bound-mu)./(sqrt(2)*sd)) + ...
    .5*erfc((tbl.upper_bound-mu)./(sqrt(2)*sd));
conditional=struct('mean',mu,'covariance',covariance,'priorMean',step2.nuisanceMean, ...
    'trainingValid',exact.valid, ...
    'parameterTable',tbl,'gain',gain,'anchorVariationCovariance',extra, ...
    'marginalOutsideSupportProbability',outside,'supportClippingApplied',false, ...
    'representation','moment_gaussian_conditional_approximation', ...
    'dllEvaluationCount',exact.dllEvaluationCount);
end
