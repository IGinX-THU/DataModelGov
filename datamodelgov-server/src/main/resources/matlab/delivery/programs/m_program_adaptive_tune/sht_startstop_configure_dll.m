function initialization = sht_startstop_configure_dll(alias, cfg)
%SHT_STARTSTOP_CONFIGURE_DLL 向已加载DLL写入低速求解和起停物理先验。
%
% 两组向量均有显式版本号和固定长度。所有工程先验从集中配置生成，
% 动态仿真循环不再重复传输，也不会占用既有stepIn健康参数区域。

assert(libisloaded(alias), 'DLL别名尚未加载：%s。', alias);

solver = cfg.lowSpeedSolver;
solverVector = [solver.maxIterations; solver.maxBacktracks; ...
    solver.accuracyRequired; solver.disturbanceFactor; ...
    solver.minimumStepScale; solver.pivotRelativeTolerance; ...
    solver.rankRelativeTolerance; solver.lowFlowReferenceKgPerS; ...
    solver.zeroHoldSpeedRpm; solver.acPathMaximum; solver.ccPathMaximum; ...
    solver.nozzleFlowBlendPressureRatio; solver.shutdownAccuracyRequired];
solverPointer = libpointer('doublePtr', solverVector);
solverStatus = calllib(alias, 'DLL_SHT_LowSpeedSolverConfigure', ...
    26082503, numel(solverVector), solverPointer);
assert(solverStatus == 0, '低速求解器初始化失败，状态码=%d。', solverStatus);

p = cfg.startStop;
physicsVector = [p.designNpRpm; p.designNgRpm; p.idleNgRatio; ...
    p.lightOffNgRatio; p.selfSustainNgRatio; p.starterCutoutNgRatio; ...
    p.ignitionDelayS; p.flameBuildS; p.starterStallTorqueNm; ...
    p.starterZeroTorqueSpeedRatio; p.lightOffFuelKgPerS; ...
    p.idleFuelKgPerS; p.hpsInertiaKgM2; p.ptEngineInertiaKgM2; ...
    p.rotorReflectedInertiaKgM2; p.hpsCoulombLossNm; ...
    p.hpsViscousLossNmPerKrpm; p.hpsWindageLossNmPerKrpm2; ...
    p.ptCoulombLossNm; p.ptViscousLossNmPerKrpm; ...
    p.ptWindageLossNmPerKrpm2; p.gtAccessoryPowerW; ...
    p.designRotorPowerW; p.thetaZeroDeg; p.thetaDesignDeg; ...
    p.profileTorqueFraction; p.rotorCoulombLossNm; ...
    p.rotorViscousLossNmPerKrpm; p.freewheelSpeedToleranceRpm];
if p.configVersion == 26091204
    physicsVector(end+1,1) = p.maximumGasTemperatureK;
else
    assert(p.configVersion == 26082401, '不支持的起停物理配置版本。');
end
physicsPointer = libpointer('doublePtr', physicsVector);
physicsStatus = calllib(alias, 'DLL_SHT_StartStopConfigure', ...
    p.configVersion, numel(physicsVector), physicsPointer);
assert(physicsStatus == 0, '起停物理初始化失败，状态码=%d。', physicsStatus);

initialization = struct('solverStatus', solverStatus, ...
    'physicsStatus', physicsStatus, 'solverVector', solverVector, ...
    'physicsVector', physicsVector);
end
