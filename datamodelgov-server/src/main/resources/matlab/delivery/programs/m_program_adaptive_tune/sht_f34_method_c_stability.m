function diagnostic=sht_f34_method_c_stability(primary,repeat,parameter)
%SHT_F34_METHOD_C_STABILITY 方法C独立随机种子稳定性诊断。
%
% 该诊断只比较两次以不同随机种子、同一先验和似然合同得到的
% 独立SMC结果。它不读取测试数据或隐藏真值，也不把两批样本静默合并
% 为新的正式后验。

required={'samples','weights','mean','covariance','interval95','ess', ...
    'finalBeta','seed','likelihoodContractHash'};
if ~all(isfield(primary,required))||~all(isfield(repeat,required))
    error('SHT:F34MethodCStability:Schema','两次方法C结果字段不完整。');
end
if ~strcmp(primary.likelihoodContractHash,repeat.likelihoodContractHash)
    error('SHT:F34MethodCStability:Lineage','两次SMC的似然合同不一致。');
end
if primary.seed==repeat.seed
    error('SHT:F34MethodCStability:Seed','稳定性诊断必须使用不同随机种子。');
end
if abs(primary.finalBeta-1)>1e-10||abs(repeat.finalBeta-1)>1e-10
    error('SHT:F34MethodCStability:Beta','两次SMC都必须到达beta=1。');
end

variancePrimary=max(diag(primary.covariance),0);
varianceRepeat=max(diag(repeat.covariance),0);
pooledStd=sqrt(0.5*(variancePrimary+varianceRepeat));
meanDifference=repeat.mean-primary.mean;
normalizedMeanDifference=abs(meanDifference)./max(pooledStd,eps);
nominalMcSe=sqrt(variancePrimary/max(primary.ess,1)+ ...
    varianceRepeat/max(repeat.ess,1));
meanDifferenceOverNominalMcSe=abs(meanDifference)./max(nominalMcSe,eps);

widthPrimary=primary.interval95(:,2)-primary.interval95(:,1);
widthRepeat=repeat.interval95(:,2)-repeat.interval95(:,1);
intersection=max(0,min(primary.interval95(:,2),repeat.interval95(:,2))- ...
    max(primary.interval95(:,1),repeat.interval95(:,1)));
intervalOverlapFraction=intersection./max(min(widthPrimary,widthRepeat),eps);
endpointDifference=max(abs(repeat.interval95-primary.interval95),[],2);
normalizedEndpointDifference=endpointDifference./max(pooledStd,eps);

tableValue=table(parameter.parameter_id,parameter.name,parameter.unit, ...
    primary.mean,repeat.mean,meanDifference,pooledStd,normalizedMeanDifference, ...
    nominalMcSe,meanDifferenceOverNominalMcSe,primary.interval95(:,1), ...
    primary.interval95(:,2),repeat.interval95(:,1),repeat.interval95(:,2), ...
    intervalOverlapFraction,normalizedEndpointDifference, ...
    'VariableNames',{'parameter_id','name','unit','primary_mean', ...
    'repeat_mean','mean_difference','pooled_posterior_std', ...
    'mean_difference_over_posterior_std','nominal_mc_standard_error', ...
    'mean_difference_over_nominal_mc_se','primary_q025','primary_q975', ...
    'repeat_q025','repeat_q975','interval_overlap_fraction', ...
    'endpoint_difference_over_posterior_std'});

% 阈值只用于判断是否需要增加粒子，不是物理真实性验收。
stable=max(normalizedMeanDifference)<=0.35&& ...
    min(intervalOverlapFraction)>=0.50;
if stable
    qualityLevel='INDEPENDENT_SEED_STABLE';
else
    qualityLevel='INDEPENDENT_SEED_REQUIRES_MORE_PARTICLES';
end
diagnostic=struct('schemaVersion','SHT_F34_METHOD_C_STABILITY_V1', ...
    'createdAt',datestr(now,31),'qualityLevel',qualityLevel, ...
    'stable',stable,'primarySeed',primary.seed,'repeatSeed',repeat.seed, ...
    'primaryParticleCount',primary.particleCount, ...
    'repeatParticleCount',repeat.particleCount, ...
    'maximumMeanDifferenceOverPosteriorStd',max(normalizedMeanDifference), ...
    'minimumIntervalOverlapFraction',min(intervalOverlapFraction), ...
    'table',tableValue,'testDataUsed',false,'truthDataUsed',false, ...
    'likelihoodContractHash',primary.likelihoodContractHash, ...
    'note',['本诊断反映有限粒子随机误差；它不能代替似然校准、' ...
    '模型差异校验或跨架次Q的纵向标定。']);
end
