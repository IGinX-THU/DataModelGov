function result = Start_SteadyModelUQ_B_01_ProblemContract(userCfg)
%START_STEADYMODELUQ_B_01_PROBLEMCONTRACT 冻结方法B的可变维概率合同。
if nargin < 1, userCfg = struct(); end
timer = tic;
cfg = sht_steady_model_uq_b_common('defaultconfig',userCfg);
manifest = sht_steady_model_uq_b_io('createrun',cfg);
contract = sht_steady_model_uq_b_common('buildcontract',cfg);
prior = sht_steady_model_uq_sampler('buildprior',contract,contract.priorType);
selfTest = sht_steady_model_uq_sampler('selftest',contract);
if ~selfTest.passed
    error('SHT:SteadyUQB:SamplerSelfTestFailed', ...
        '方法B先验和提议采样器自检未通过。');
end
result = struct('contract',contract,'prior',prior, ...
    'samplerSelfTest',selfTest,'methodAPosteriorUsed',false, ...
    'truthRead',false,'testDataRead',false);
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_b_io( ...
    'savestep',manifest,1,'problem_contract',result,runtime);
writetable(contract.parameterTable,sht_steady_model_uq_b_io( ...
    'reportfile',manifest,'UQB01_parameter_contract.csv'));
writetable(contract.parameterGroupTable,sht_steady_model_uq_b_io( ...
    'reportfile',manifest,'UQB01_parameter_groups.csv'));
writetable(contract.parameterBlockTable,sht_steady_model_uq_b_io( ...
    'reportfile',manifest,'UQB01_parameter_blocks.csv'));
fprintf(['[2.4UQ-B.1] 合同完成：run=%s，参数=%d（%d+%d+%d），' ...
    '训练点=%d，观测=%d。\n'],manifest.runId,contract.parameterCount, ...
    contract.aggregateParameterCount,contract.localParameterCount, ...
    contract.bleedParameterCount, ...
    contract.trainingPointCount,contract.observationDimension);
fprintf('[2.4UQ-B.1] 废弃方法A历史后验用于B先验/初值/提议：%d。\n', ...
    contract.methodAPosteriorUsed);
fprintf('[2.4UQ-B.1] 产物：%s\n',file);
result.manifest = manifest;
end
