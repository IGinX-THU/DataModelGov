function delivery=sht_load_2p4_uq_delivery(workbookFile)
%SHT_LOAD_2P4_UQ_DELIVERY 从正式Excel独立恢复B/C联合经验后验。
% 每列theta是一整组参数，weights与其逐列对应，不能拆成独立边际。
% 不读取内部MAT、训练观测、真值或SHA旁车；不重新采样、不改变权重。
assert(isfile(workbookFile),'SHT:UQDelivery:MissingFile','UQ工作簿不存在。');
m=readtable(workbookFile,'Sheet','Manifest','PreserveVariableNames',true);
p=readtable(workbookFile,'Sheet','ParameterSummary','PreserveVariableNames',true);
s=readtable(workbookFile,'Sheet','PosteriorSamples','PreserveVariableNames',true);
fixed=readtable(workbookFile,'Sheet','FixedAnchors','PreserveVariableNames',true);
localApproximation=string(m.method_id)=="D" && ...
    (startsWith(string(m.formal_status),"LOCAL_APPROXIMATION") || ...
    ismember(string(m.formal_status),["LOCAL_IMPORTANCE_CORRECTED","LOCAL_TEMPERED_CORRECTED"]));
assert(height(m)==1 && ismember(string(m.method_id),["B","C","D"]) && ...
    (string(m.formal_status)=="FORMAL_ACCEPTED" || localApproximation) && ~logical(m.hidden_truth_exported), ...
    'SHT:UQDelivery:InvalidManifest','需要已发布、无真值泄漏的B/C后验或标明身份的D初评。');
n=double(m.parameter_count); count=double(m.sample_count);
assert(height(p)==n && height(s)==count && ...
    isequal(double(p.parameterIndex),(1:n).') && ...
    numel(unique(string(p.name)))==n,'SHT:UQDelivery:InvalidDictionary', ...
    '参数字典、样本数或参数ID不一致。');
names=matlab.lang.makeUniqueStrings( ...
    matlab.lang.makeValidName(cellstr("theta_"+string(p.name))), ...
    {'sampleId','sampleWeight','logLikelihood','logPrior'});
assert(all(ismember(names,s.Properties.VariableNames)), ...
    'SHT:UQDelivery:MissingSampleColumn','后验样本缺少参数列。');
theta=double(s{:,names}).'; weight=double(s.sampleWeight);
assert(all(isfinite(theta(:))) && all(isfinite(weight)) && all(weight>=0) && ...
    abs(sum(weight)-1)<1e-10 && ...
    all(theta>=p.lowerBound-1e-12 & theta<=p.upperBound+1e-12,'all'), ...
    'SHT:UQDelivery:InvalidSamples','联合后验样本、权重或硬边界无效。');
meanValue=theta*weight;
assert(max(abs(meanValue-p.posteriorMean))<1e-10, ...
    'SHT:UQDelivery:MeanMismatch','后验样本与摘要均值不一致。');
delivery=struct('method',char(string(m.method_id)),'route',char(string(m.route)), ...
    'runId',char(string(m.run_id)),'manifest',m,'parameterTable',p, ...
    'theta',theta,'weights',weight,'mean',meanValue,'fixedAnchors',fixed,'parameterCount',n, ...
    'sampleCount',count,'internalDataRead',false,'truthRead',false, ...
    'representation','weighted_joint_empirical_posterior', ...
    'marginalizedNuisanceSampled',false);
% 老B工作簿把独立零先验起点误标为确定性估计，不能拿这一列做来源校验。
delivery.deterministicReferenceReliable=ismember( ...
    'deterministic_reference_semantics',m.Properties.VariableNames) || string(m.method_id)=="C";
delivery.formalGlobalPosterior=~localApproximation;
if localApproximation,delivery.representation='bounded_local_quadratic_approximation';end
if ismember('distribution_representation',m.Properties.VariableNames)
    delivery.representation=char(string(m.distribution_representation));
end
if ismember('conditional_nuisance_representation',m.Properties.VariableNames)
    nt=readtable(workbookFile,'Sheet','ConditionalNuisance','PreserveVariableNames',true);
    cm=readtable(workbookFile,'Sheet','ConditionalMeans','PreserveVariableNames',true);
    cv=readtable(workbookFile,'Sheet','ConditionalCovariance','PreserveVariableNames',true);
    assert(height(cm)==count && height(cv)==height(nt) && width(cv)==height(nt) && ...
        isequal(cm.sampleId,(1:count).'),'SHT:UQDelivery:ConditionalMismatch','条件附加参数与联合样本不对应。');
    cols=cellstr(compose('eta%02d',1:height(nt)));
    delivery.conditionalNuisance=struct('parameterTable',nt,'mean',cm{:,cols}.', ...
        'trainingValid',isfinite(cm.training_physical_valid) & cm.training_physical_valid~=0, ...
        'trainingValidityKnown',isfinite(cm.training_physical_valid), ...
        'covariance',cv{:,:},'representation',char(string(m.conditional_nuisance_representation)));
    if ismember('conditional_quadrature_count',m.Properties.VariableNames)
        q=double(m.conditional_quadrature_count);
        validateattributes(q,{'numeric'},{'scalar','integer','positive'});
        encoded=ismember('conditional_gaussian_encoded',m.Properties.VariableNames) && logical(m.conditional_gaussian_encoded);
        if encoded
            assert(string(m.conditional_quadrature_algorithm)=="Genz_Sobol_static_order_v1", ...
                'SHT:UQDelivery:QuadratureAlgorithm','未知有界条件分布积分协议。');
            gm=readtable(workbookFile,'Sheet','ConditionalGaussianMeans','PreserveVariableNames',true);
            gc=readtable(workbookFile,'Sheet','ConditionalGaussianCov','PreserveVariableNames',true);
            assert(height(gm)==count && isequal(gm.sampleId,(1:count).') && ...
                isequal(size(gc{:,:}),[height(nt),height(nt)]), ...
                'SHT:UQDelivery:ConditionalGaussianSize','条件高斯编码维数或顺序错误。');
            gaussianMean=gm{:,cols}.';gaussianCov=gc{:,:};
            assert(all(isfinite(gaussianMean(:))) && all(isfinite(gaussianCov(:))), ...
                'SHT:UQDelivery:ConditionalGaussianFinite','条件高斯编码不能包含非有限值。');
            box=sht_tc24_uq_box_normal(gaussianMean,gaussianCov,nt.lower_bound,nt.upper_bound, ...
                q,double(m.conditional_quadrature_seed),true);
            values=box.samples;weightCloud=box.weights;
            delivery.conditionalNuisance.gaussianMean=gaussianMean;
            delivery.conditionalNuisance.gaussianCovariance=gaussianCov;
        else
            cloud=readtable(workbookFile,'Sheet','ConditionalQuadrature','PreserveVariableNames',true);
            assert(height(cloud)==q*count && ...
                isequal(cloud.sampleId,repelem((1:count).',q)) && ...
                isequal(cloud.quadratureId,repmat((1:q).',count,1)), ...
                'SHT:UQDelivery:QuadratureOrder','有界条件节点顺序或数量错误。');
            weightCloud=reshape(cloud.weight,q,count);
            values=permute(reshape(cloud{:,cols},q,count,height(nt)),[3,1,2]);
        end
        assert(all(isfinite(values(:))) && all(weightCloud(:)>=0) && ...
            max(abs(sum(weightCloud,1)-1))<1e-10 && ...
            all(values>=nt.lower_bound-1e-12 & values<=nt.upper_bound+1e-12,'all'), ...
            'SHT:UQDelivery:QuadratureBounds','有界条件分布的节点/权重无效。');
        reconstructed=squeeze(sum(values.*reshape(weightCloud,1,q,count),2));
        assert(max(abs(reconstructed(:)-delivery.conditionalNuisance.mean(:)))<1e-10, ...
            'SHT:UQDelivery:QuadratureMean','条件节点与条件均值不一致。');
        delivery.conditionalNuisance.quadratureSamples=values;
        delivery.conditionalNuisance.quadratureWeights=weightCloud;
    elseif string(m.conditional_nuisance_representation)=="bounded_affine_conditional_QMC"
        error('SHT:UQDelivery:MissingQuadrature','有界条件分布不能缺少必要积分节点。');
    end
end
end
