    'pitchDeg',12,'mainPitchDeg',12,'tailPitchDeg',10, ...
    'tailToMainPowerRatio',0.10,'tailDesignPitchDeg',10, ...
    'mainPitchBounds',[6 14],'tailPitchBounds',[-8 18], ...
    'legacyPulses',false,'initialTransitionConfirmed',false, ...
    'logEverySeconds',5,'plots',false);
% 主/尾桨按同一PT侧转速折算。0.10是可配置工程先验，不是已标定参数。
% 常规初态仍为配套MDL正转速点。初始目标若与该状态不同，必须显式
% 确认从配套初态过渡，不能把目标冒充已经配平的初态。
end
