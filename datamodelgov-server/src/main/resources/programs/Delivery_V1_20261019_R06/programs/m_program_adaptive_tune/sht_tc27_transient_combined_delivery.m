function model=sht_tc27_transient_combined_delivery(action,input,file,executionOptions)
%SHT_TC27_TRANSIENT_COMBINED_DELIVERY 自含稳态调度与瞬态系数的正式Excel。
% 原稳态交付四张工作表保持原样；增加瞬态参数及组合模型身份。
% 第四参数只定位配套运行包；读回仍严格匹配原生成身份，不重签Excel。
if nargin<4||isempty(executionOptions),executionOptions=struct();end
selection='selected';
if isfield(executionOptions,'runtimeDirectory')&&~isempty(executionOptions.runtimeDirectory)
    selection=executionOptions.runtimeDirectory;
end
names={'K_Jg';'K_Jp';'K_tau_HPC';'K_tau_Burner';'K_tau_GT';'K_tau_PT'; ...
    'K_gapW_HPC';'K_gapEta_HPC';'K_gapEta_GT';'K_gapEta_PT'; ...
    'K_diskTau_HPC';'K_diskTau_GT';'K_diskTau_PT'};
if strcmp(action,'write')
    assert(~isfile(file),'TC27:Combined:Exists','组合模型不得覆盖已有Excel。');
    source=char(input.steadyFile);
    steady=sht_tc27_delivery('read',[],source);
    assert(steady.modelMode==0&&steady.thermalMode==3, ...
        'TC27:Combined:Parent','父模型须为三部件Visser正式交付。');
    h=input.transientCoefficients(:);
    assert(numel(h)==13&&all(isfinite(h))&&all(h>=-.5&h<=1), ...
        'TC27:Combined:Coefficients','13个瞬态系数维数、边界或数值无效。');
    package=sht_tc27_runtime_package(selection);
    [ok,message]=copyfile(source,file);
    assert(ok,'TC27:Combined:Copy','复制稳态模型失败：%s',message);
    try
        corrections=table((58:70).',string(names),h, ...
            repmat("estimated",13,1),'VariableNames', ...
            {'hIndex','parameter','value','source'});
        manifest=table("SHT_TC27_COMBINED_TRANSIENT_EXCEL_V1", ...
            string(input.runId),string(steady.sha256),string(package.id), ...
            string(sht_tc27_file_identity(package.manifestFile)), ...
            string(sht_tc27_file_identity(fullfile(package.directory,'GTESS.dll'))), ...
            string(sht_tc27_file_identity(package.thermalFile)),0,3, ...
            'VariableNames',{'schema','run_id','parent_steady_sha256', ...
            'runtime_package_id','runtime_manifest_sha256', ...
            'dll_sha256','thermal_sha256','model_mode','thermal_mode'});
        writetable(corrections,file,'Sheet','TransientCorrections');
        writetable(manifest,file,'Sheet','CombinedManifest');
        model=sht_tc27_transient_combined_delivery('read',[],file,executionOptions);
        assert(max(abs(model.transientCoefficients-h))<1e-14, ...
            'TC27:Combined:Roundtrip','瞬态系数Excel往返不一致。');
    catch failure
        if isfile(file),delete(file);end
        rethrow(failure);
    end
    return;
end
assert(strcmp(action,'read'),'TC27:Combined:Action','未知组合模型操作。');
steady=sht_tc27_delivery('read',[],file);
q=readtable(file,'Sheet','TransientCorrections');
m=readtable(file,'Sheet','CombinedManifest');
assert(height(q)==13&&isequal(q.hIndex,(58:70).')&& ...
    isequal(string(q.parameter),string(names))&&all(isfinite(q.value))&& ...
    all(q.value>=-.5&q.value<=1),'TC27:Combined:Dictionary', ...
    '瞬态参数字典、边界或数值不一致。');
assert(height(m)==1&&string(m.schema)=="SHT_TC27_COMBINED_TRANSIENT_EXCEL_V1"&& ...
    m.model_mode==0&&m.thermal_mode==3&&steady.modelMode==0&&steady.thermalMode==3, ...
    'TC27:Combined:Schema','组合模型身份不合法。');
package=sht_tc27_runtime_package(selection);
assert(strcmp(char(string(m.runtime_package_id)),package.id)&& ...
    ismember('runtime_manifest_sha256',m.Properties.VariableNames)&& ...
    strcmpi(char(string(m.runtime_manifest_sha256)), ...
    sht_tc27_file_identity(package.manifestFile))&& ...
    strcmpi(char(string(m.dll_sha256)),sht_tc27_file_identity(fullfile(package.directory,'GTESS.dll')))&& ...
    strcmpi(char(string(m.thermal_sha256)),sht_tc27_file_identity(package.thermalFile)), ...
    'TC27:Combined:Runtime','组合模型物理运行包与当前所选包不一致。');
model=struct('schema',char(string(m.schema)),'file',file, ...
    'sha256',sht_tc27_file_identity(file),'runId',char(string(m.run_id)), ...
    'parentSteadySHA256',char(string(m.parent_steady_sha256)), ...
    'runtimePackageId',package.id, ...
    'runtimeManifestSHA256',char(string(m.runtime_manifest_sha256)), ...
    'modelMode',0,'thermalMode',3, ...
    'steadySchedule',steady.finalSchedule,'npBranchModel',steady.npBranchModel, ...
    'fuelBias',steady.finalSchedule.fuelBias,'transientCoefficients',q.value, ...
    'transientTable',q,'internalMatRead',false);
end
