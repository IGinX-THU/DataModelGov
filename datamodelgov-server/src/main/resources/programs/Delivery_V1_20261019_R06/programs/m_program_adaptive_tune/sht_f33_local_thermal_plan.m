function plan=sht_f33_local_thermal_plan(time,windows,warmup_s)
% 按测量时间轴给每个拟合窗口配置有限热准备前史；不新增拟合样本。
% 本函数只制作数据索引，热平衡和升温过程由每个候选模型独立计算。
validateattributes(warmup_s,{'numeric'},{'scalar','real','finite','nonnegative'});
time=time(:);dt=median(diff(time));
assert(numel(time)>=2&&dt>0&&all(isfinite(time))&& ...
    max(abs(diff(time)-dt))<1e-8,'SHT:F33ThermalPlan:Time','时间轴必须完整等间隔。');
assert(all(ismember({'first','last'},windows.Properties.VariableNames)), ...
    'SHT:F33ThermalPlan:Window','窗口缺少first/last记录索引。');
first=windows.first(:);last=windows.last(:);
assert(all(isfinite(first)&isfinite(last)&first==round(first)&last==round(last)& ...
    first>=1&last<=numel(time)&last>=first),'SHT:F33ThermalPlan:Window','窗口索引无效。');
n=numel(first);initFirst=zeros(n,1);
for i=1:n
    initFirst(i)=find(time>=time(first(i))-warmup_s-1e-8,1);
end
plan=table((1:n)',first,last,time(first),time(last),initFirst,time(initFirst), ...
    time(first)-time(initFirst),last-first+1,first-initFirst, ...
    repmat("candidate_equilibrium_measured_warmup",n,1),false(n,1), ...
    'VariableNames',{'window_id','fit_first','fit_last','fit_start_s','fit_end_s', ...
    'initialization_first','initialization_start_s','warmup_s','fit_sample_count', ...
    'preparation_sample_count','initialization_policy','equilibrium_certified'});
end
