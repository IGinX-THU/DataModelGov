function result = sht_initialize_reynolds_correction_dll( ...
        interface, modelMode, configuration)
%SHT_INITIALIZE_REYNOLDS_CORRECTION_DLL 一次性初始化三/六部件RNI修正。
%
% 配置独立于 stepIn。DLL 只在发动机打开时接收一次设计参考和图谱
% 端点，随后在每次部件求值时使用部件实际入口状态计算 RNI。

if ~isnumeric(modelMode)||~isreal(modelMode)||~isscalar(modelMode)|| ...
        ~isfinite(modelMode)||~ismember(modelMode,[0,1])
    error('SHT:ReynoldsCorrection:ModelMode', ...
        '雷诺数修正初始化只支持modelMode=0或1。');
end
names={'AC','CC','GT1','GT2','PT1','PT2'};
if modelMode==0,names={'HPC','GT','PT'};end
required = {'schemaVersion','configVersion','parameterCount','flowLossFraction','components'};
if ~isstruct(configuration) || ~isscalar(configuration) || ...
        ~all(isfield(configuration,required)) || ...
        ~isstruct(configuration.components)||numel(configuration.components) ~= numel(names)
    error('SHT:ReynoldsCorrection:ConfigurationSchema', ...
        '雷诺数修正配置结构不完整。');
end
if isfield(configuration,'modelMode') && ~isequal(configuration.modelMode,modelMode)
    error('SHT:ReynoldsCorrection:ModelMode','配置所属模型与DLL实例不一致。');
end
globalValues={configuration.configVersion,configuration.parameterCount,configuration.flowLossFraction};
if ~all(cellfun(@local_real_scalar,globalValues)) || ...
        configuration.configVersion~=1 || configuration.parameterCount~=43 || ...
        configuration.flowLossFraction<0 || configuration.flowLossFraction>1 || ...
        ~strcmp(configuration.schemaVersion,'SHT_REYNOLDS_CORRECTION_V1')
    error('SHT:ReynoldsCorrection:ConfigurationValue','RNI版本、长度或流量耦合比例无效。');
end
fields={'name','enabled','designTemperature_K','designPressure_Pa', ...
    'lowIndex','lowEfficiencyFactor','highIndex','highEfficiencyFactor'};
if ~all(isfield(configuration.components,fields))
    error('SHT:ReynoldsCorrection:ConfigurationSchema','部件RNI字段不完整。');
end

% 三部件使用前3槽；后3槽填合法但禁用的占位数据，不代表实际部件。
% 保留43参数ABI，使原六部件配置和已发布DLL的调用格式不变。
vector = [0;repmat([0;288.15;101325;.1;.95;1;1],6,1)];
vector(1) = configuration.flowLossFraction;
for i = 1:numel(names)
    component = configuration.components(i);
    if ~strcmp(component.name,names{i}) || ...
            ~(isnumeric(component.enabled)||islogical(component.enabled)) || ...
            ~isreal(component.enabled)||~isscalar(component.enabled)|| ...
            ~isfinite(component.enabled)||~ismember(component.enabled,[0,1])
        error('SHT:ReynoldsCorrection:ComponentIdentity', ...
            'RNI第%d槽应为%s且enabled只能为0/1。',i,names{i});
    end
    numericFields=fields(3:end);
    if ~all(cellfun(@(name)local_real_scalar(component.(name)),numericFields))
        error('SHT:ReynoldsCorrection:ConfigurationValue', ...
            '%s的RNI参数必须为有限实标量，不允许复数或向量。',names{i});
    end
    startIndex = 2 + 7*(i-1);
    vector(startIndex:startIndex+6) = [double(component.enabled); ...
        component.designTemperature_K; component.designPressure_Pa; ...
        component.lowIndex; component.lowEfficiencyFactor; ...
        component.highIndex; component.highEfficiencyFactor];
end
if configuration.configVersion ~= 1 || ...
        configuration.parameterCount ~= numel(vector) || ...
        any(~isfinite(vector))
    error('SHT:ReynoldsCorrection:ConfigurationValue', ...
        '雷诺数修正配置版本、长度或数值无效。');
end

parameterPointer = libpointer('doublePtr',vector);
status = calllib(interface.libraryName, ...
    'DLL_SHT_InitializeReynoldsCorrection', ...
    configuration.configVersion,numel(vector),parameterPointer);
if status ~= 0
    error('SHT:ReynoldsCorrection:DllInitialization', ...
        'DLL雷诺数修正初始化失败，状态码=%d。',status);
end
enabledCount = nnz([configuration.components.enabled]);
statusCheck = calllib(interface.libraryName, ...
    'DLL_SHT_ReynoldsCorrectionGetStatus');
if statusCheck ~= enabledCount
    error('SHT:ReynoldsCorrection:DllStatus', ...
        'DLL报告%d个启用部件，配置要求%d个。',statusCheck,enabledCount);
end

result = struct('initialized',true, ...
    'schemaVersion',configuration.schemaVersion, ...
    'configVersion',configuration.configVersion, ...
    'parameterCount',numel(vector),'enabledCount',enabledCount, ...
    'parameterVector',vector,'configuration',configuration);
end

function yes=local_real_scalar(value)
yes=isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value);
end
