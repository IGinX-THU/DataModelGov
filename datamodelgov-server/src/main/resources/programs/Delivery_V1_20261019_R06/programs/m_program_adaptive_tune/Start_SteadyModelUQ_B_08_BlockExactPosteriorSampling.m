function result = Start_SteadyModelUQ_B_08_BlockExactPosteriorSampling(userCfg)
%START_STEADYMODELUQ_B_08_BLOCKEXACTPOSTERIORSAMPLING 单一全局总体确定性混合SMC。
% 文件名保留用于兼容既有入口。参数维数由Excel及附加参数字典确定；只有一个粒子总体、一套
% 全局归一化权重和一条祖先谱系；分块核仅用于联合后验内部的高效移动。
% 当前默认规模为1024粒子，512粒子作为用户可选的快速配置。实际规模从
% B01冻结的问题合同读取，不允许B08单独覆盖，以免合同与采样结果不一致。
if nargin < 1, userCfg = struct(); end
timer = tic;
manifest = sht_steady_model_uq_b_io('resolvewritable',userCfg);
step1 = sht_steady_model_uq_b_io('loadstep',manifest,1);
step5 = sht_steady_model_uq_b_io('loadstep',manifest,5);
step6 = sht_steady_model_uq_b_io('loadstep',manifest,6);
step7 = sht_steady_model_uq_b_io('loadstep',manifest,7);
% 直接从B08开始也须检查真实准备来源，不能依赖上层入口恰好运行过B07。
sht_tc24_uq_external_io('b','checkpreparationidentity', ...
    step5,'B05',step6,'B06',step7,'B07');
assert(isfield(step7,'proposal'),'TC24:UQ:PreparationIdentityMissing','B07缺少已校验的提议。');
sht_tc24_uq_external_io('b','checkpreparationidentity',step7.proposal,'B07正式提议');
contract = step1.contract;
cfg = step7.smcConfig;
cfg.particleCount = local_contract_particle_count(contract.config);
local_assert_requested_particle_count(userCfg,cfg.particleCount);
cfg.randomSeed = contract.config.bSamplingSeed;
cfg.useCache = contract.config.useCache;
cfg.verbose = contract.config.verbose;
if isfield(userCfg,'runControl'),cfg.runControl=userCfg.runControl;end
formal = sht_steady_model_uq_b_smc(contract,step1.prior, ...
    step5.likelihood,step7.proposal,cfg);
formal.logRawWeight = log(max(formal.weights,realmin));
formal.logProposal = nan(size(formal.weights));
formal.method = ...
    'single_global_population_geometric_bridge_five_kernel_smc';
minimumEss = max(contract.config.minimumEffectiveSampleSize, ...
    contract.config.minimumEffectiveSampleFraction*cfg.particleCount);
maximumWeight = max(formal.weights);
distinctFraction = local_distinct_fraction(formal.theta,contract.priorSigma);
pilotCenter = step6.theta*step6.weights(:);
formalCenter = formal.theta*formal.weights(:);
centerDifference = norm((formalCenter-pilotCenter)./step1.prior.sigma) / ...
    sqrt(contract.parameterCount);
kernelCovered = all(formal.kernelAttempted>0);
allocationCount = formal.initialProposalAudit.componentCount;
allocationWeight = formal.initialProposalAudit.densityWeight;
singlePopulationPassed = formal.populationCount==1 && ...
    formal.singleGlobalWeightVector && ...
    ~formal.postHocPosteriorPoolingUsed && ...
    sum(allocationCount)==cfg.particleCount && ...
    norm(allocationWeight-allocationCount/cfg.particleCount,1)<1e-12 && ...
    strcmp(formal.initialProposalAudit.samplingMode, ...
    'deterministic_mixture');
subspaceMixing = local_subspace_mixing_diagnostic( ...
    formal.theta,formal.weights,step1.prior,step7.samplingGeometry);
referenceLogPrior = sht_steady_model_uq_sampler( ...
    'logprior',step1.prior,step5.thetaLocal);
referenceLogPosterior = referenceLogPrior+step5.localLogLikelihood;
formalLogPosterior = formal.logPrior+formal.logLikelihood;
maximumFormalLogPosterior = max(formalLogPosterior(isfinite( ...
    formalLogPosterior)));
referenceDominanceGap = referenceLogPosterior-maximumFormalLogPosterior;
maximumReferenceDominanceGap = max(20, ...
    0.75*step5.activeLatentInformedRank);
referenceCoveragePassed = isfinite(maximumFormalLogPosterior) && ...
    referenceDominanceGap<=maximumReferenceDominanceGap;
minimumMedianNullLatentStd = 0.30;
minimumQ10NullLatentStd = 0.05;
if subspaceMixing.nullDirectionCount == 0
    subspaceMixingPassed = true;
else
    subspaceMixingPassed = ...
        subspaceMixing.medianNullLatentStd >= minimumMedianNullLatentStd && ...
        subspaceMixing.q10NullLatentStd >= minimumQ10NullLatentStd;
end
passed = formal.finalBeta==1 && ...
    formal.diagnostic.effectiveSampleSize>=minimumEss && ...
    maximumWeight<=contract.config.maximumNormalizedWeight && ...
    distinctFraction>=0.25 && kernelCovered && singlePopulationPassed && ...
    all(isfinite(formalCenter));
acceptanceCriteria = struct('minimumEss',minimumEss, ...
    'maximumWeight',contract.config.maximumNormalizedWeight, ...
    'minimumDistinctFraction',0.25,'allFiveKernelsAttempted',true, ...
    'singleGlobalPopulationRequired',true, ...
    'deterministicMixtureActualQuotaDensityRequired',true, ...
    'postHocPosteriorPoolingForbidden',true, ...
    'minimumMedianNullLatentStd',minimumMedianNullLatentStd, ...
    'minimumQ10NullLatentStd',minimumQ10NullLatentStd, ...
    'subspaceMixingSevereCollapseGuard',false, ...
    'maximumReferenceDominanceGap',maximumReferenceDominanceGap, ...
    'knownHighPosteriorRegionCoverageGuard',false, ...
    'localGeometryReportedNotHardGated',true, ...
    'kernelAcceptanceReportedNotHardGated',true, ...
    'pilotFormalCenterDistanceReportedNotGated',true);
formal.passed = passed;
formal.maximumNormalizedWeight = maximumWeight;
formal.distinctParticleFraction = distinctFraction;
formal.pilotFormalCenterDistancePriorScale = centerDifference;
subspaceMixing.passed = subspaceMixingPassed;
formal.subspaceMixingDiagnostic = subspaceMixing;
formal.referenceLogPosterior = referenceLogPosterior;
formal.maximumSampleLogPosterior = maximumFormalLogPosterior;
formal.referenceDominanceGap = referenceDominanceGap;
formal.maximumReferenceDominanceGap = maximumReferenceDominanceGap;
formal.referenceCoveragePassed = referenceCoveragePassed;
formal.singlePopulationPassed = singlePopulationPassed;
formal.numericalChecksPassed=passed;
formal.statisticalCalibrationEstablished=false;
formal.qualityStatus='finite_budget_joint_posterior';
% 局部低敏感方向在其他位置可能受非线性约束；典型概率质量也不要求
% 命中最高密度参考点。两项继续报警，但不能据此强迫收紧提议或拒绝全部结果。
formal.samplingPrecisionDiagnostic.localGeometryWarning= ...
    ~subspaceMixingPassed || ~referenceCoveragePassed;
formal.samplingPrecisionDiagnostic.precisionWarning= ...
    formal.samplingPrecisionDiagnostic.precisionWarning || ...
    formal.samplingPrecisionDiagnostic.localGeometryWarning;
precision=formal.samplingPrecisionDiagnostic;
result = struct('formal',formal,'method',formal.method,'pilot',step6, ...
    'passed',passed,'acceptanceCriteria',acceptanceCriteria, ...
    'methodAPosteriorUsed',false,'truthRead',false,'testDataRead',false);
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_b_io( ...
    'savestep',manifest,8, ...
    'global_deterministic_mixture_smc_posterior',result,runtime);
fprintf(['[2.4UQ-B.8] 正式SMC：N=%d，stage=%d，ESS=%.1f，maxW=%.4f，' ...
    'distinct=%.1f%%，kernel acc=[%.1f %.1f %.1f %.1f %.1f]%%，pass=%d。\n'], ...
    cfg.particleCount,formal.stageCount, ...
    formal.diagnostic.effectiveSampleSize,maximumWeight, ...
    100*distinctFraction,100*formal.blockAcceptance,passed);
fprintf(['[2.4UQ-B.8] 几何桥=%d，每轮候选预算=%d（每粒子一个候选），' ...
    '全局pCN/独立核接受率=[%.1f %.1f]%%。\n'], ...
    formal.geometricBridgeUsed,formal.proposalBudgetPerSweep, ...
    100*formal.globalSubkernelAcceptance);
fprintf(['[2.4UQ-B.8] 单一总体确定性混合：总体=%d，配额=[%d %d]，' ...
    '密度权重=[%.6f %.6f]，事后拼接=%d，guard=%d。\n'], ...
    formal.populationCount,allocationCount,allocationWeight, ...
    formal.postHocPosteriorPoolingUsed,singlePopulationPassed);
fprintf(['[2.4UQ-B.8] 活动潜空间混合：信息方向std中位数=%.3f，' ...
    '弱信息方向std中位数/q10=%.3f/%.3f，局部几何诊断=%d（非放行门）。\n'], ...
    subspaceMixing.medianInformedLatentStd, ...
    subspaceMixing.medianNullLatentStd,subspaceMixing.q10NullLatentStd, ...
    subspaceMixingPassed);
fprintf(['[2.4UQ-B.8] 参考点密度比较：参考log posterior=%.3f，' ...
    '样本最大值=%.3f，差值=%.3f（提示阈值%.3f），诊断=%d（非放行门）。\n'], ...
    referenceLogPosterior,maximumFormalLogPosterior, ...
    referenceDominanceGap,maximumReferenceDominanceGap, ...
    referenceCoveragePassed);
fprintf('[2.4UQ-B.8] 产物：%s\n',file);
if ~passed
    warning('SHT:SteadyUQB:FormalPosteriorNotAccepted', ...
        '方法B正式后验未通过全部采样门限；已保存结果供诊断。');
end
result.manifest = manifest;
fprintf(['[2.4UQ-B.8] 精度诊断（不等同于权重ESS）：祖先质量ESS=%.1f，' ...
    '最大祖先质量=%.1f%%，各核每粒子接受次数=[%.2f %.2f %.2f %.2f %.2f]。\n'], ...
    precision.ancestorMassEss,100*precision.maximumAncestorMass,precision.acceptedMovesPerParticle);
fprintf(['[2.4UQ-B.8] 末段均值最大漂移/先验尺度=%.3f，标准差相对变化中位数=%.1f%%；' ...
    '程序检查通过不代表已完成统计校准。\n'],precision.maximumMeanDriftPriorScale, ...
    100*precision.medianStdRelativeChange);
if precision.precisionWarning
    warning('SHT:SteadyUQB:FiniteBudgetPrecision', ...
        '有限预算采样仍有谱系或移动稳定性警告；保留结果并报告，不无限延长或隐瞒。');
end
end

function count = local_contract_particle_count(config)
if isfield(config,'particleCount') && ~isempty(config.particleCount)
    count = config.particleCount;
else
    % 兼容在particleCount字段引入前冻结的只读历史合同。
    count = config.formalSampleCount;
end
count = local_positive_integer(struct('count',count),'count',NaN);
if ~ismember(count,[512,1024])
    error('SHT:SteadyUQB:UnsupportedContractParticleCount', ...
        '方法B正式合同粒子数只允许为512或1024，当前为%d。',count);
end
end

function local_assert_requested_particle_count(userCfg,contractCount)
name = {'particleCount','formalSampleCount', ...
    'posteriorPredictiveSampleCount'};
for i = 1:numel(name)
    if isstruct(userCfg) && isfield(userCfg,name{i}) && ...
            ~isempty(userCfg.(name{i})) && ...
            (~isnumeric(userCfg.(name{i})) || ...
            ~isscalar(userCfg.(name{i})) || ...
            double(userCfg.(name{i})) ~= contractCount)
        error('SHT:SteadyUQB:RunContractParticleCountConflict', ...
            ['运行请求中的%s与B01冻结合同的粒子数%d不一致。' ...
             '请使用新的runId从B01开始运行。'],name{i},contractCount);
    end
end
end

function fraction = local_distinct_fraction(theta,scale)
normalized = theta./max(scale(:),eps);
rounded = round(normalized*1e9)/1e9;
[~,index] = unique(rounded.','rows','stable');
fraction = numel(index)/size(theta,2);
end

function value = local_positive_integer(options,name,defaultValue)
value = defaultValue;
if isstruct(options) && isfield(options,name) && ...
        ~isempty(options.(name))
    value = options.(name);
end
if ~isscalar(value) || ~isnumeric(value) || ~isfinite(value) || ...
        value < 1 || value ~= floor(value)
    error('SHT:SteadyUQB:BadFormalSampleCount', ...
        '%s必须为正整数。',name);
end
value = double(value);
end

function diagnostic = local_subspace_mixing_diagnostic( ...
        theta,weights,prior,geometry)
latent = sht_steady_model_uq_sampler('thetatolatent',prior,theta);
coordinate = geometry.globalBasis.'*latent;
weights = weights(:).'/sum(weights);
center = coordinate*weights.';
normalizer = max(1-sum(weights.^2),eps);
latentStd = sqrt(sum((coordinate-center).^2.*weights,2)/normalizer);
rankValue = geometry.globalInformedRank;
informedStd = latentStd(1:rankValue);
nullStd = latentStd(rankValue+1:end);
diagnostic = struct( ...
    'activeDirectionCount',numel(latentStd), ...
    'informedDirectionCount',numel(informedStd), ...
    'nullDirectionCount',numel(nullStd), ...
    'latentStd',latentStd,'informedLatentStd',informedStd, ...
    'nullLatentStd',nullStd, ...
    'medianInformedLatentStd',local_finite_median(informedStd), ...
    'medianNullLatentStd',local_finite_median(nullStd), ...
    'q10NullLatentStd',local_quantile(nullStd,0.10), ...
    'minimumNullLatentStd',local_finite_minimum(nullStd));
end

function value = local_finite_median(input)
input = input(isfinite(input));
if isempty(input), value = NaN; else, value = median(input); end
end

function value = local_finite_minimum(input)
input = input(isfinite(input));
if isempty(input), value = NaN; else, value = min(input); end
end

function value = local_quantile(input,probability)
input = sort(input(isfinite(input)));
if isempty(input), value = NaN; return; end
position = 1+(numel(input)-1)*probability;
lowerIndex = floor(position);
upperIndex = ceil(position);
fraction = position-lowerIndex;
value = (1-fraction)*input(lowerIndex)+fraction*input(upperIndex);
end
