function run = sht_run_flight_mission(mission, userOptions)
%SHT_RUN_FLIGHT_MISSION 运行一条已独立配平的飞行任务并完成物理验收。
%
% run = sht_run_flight_mission(mission)
% run = sht_run_flight_mission(mission, userOptions)
%
% 本函数只消费 S5 已生成的 mission.runtimeConfig，不修改任务定义、
% 不重新配平，也不注入测量误差。验收覆盖时间网格、总距映射、旋翼
% 负载方程、飞行边界调度、DLL 共同工作残差、保护选择和候选稳态窗口。
% distortionMode='unity' 用于清洁进气基准；'schedule' 要求逐点跟随任务
% sigmaDist 调度且必须实际包含小于 1 的样本。

if nargin < 2 || isempty(userOptions)
    userOptions = struct();
end
if ~isstruct(mission) || ~isscalar(mission) || ...
        ~isstruct(userOptions) || ~isscalar(userOptions)
    error('sht:flightMissionRun:badInput', ...
        'mission 和 userOptions 必须是标量结构体。');
end

options = struct( ...
    'requiredMissionId', '', ...
    'stageTag', '3.1-S6', ...
    'runVariantId', 'nominal', ...
    'distortionMode', 'unity', ...
    'baselineReferenceWindowId', '', ...
    'baselineRevisitWindowId', '', ...
    'maxResidualAllowed', 0.01, ...
    'npRateNormalizedLimitPerSec', 2.5e-4, ...
    'ngRateNormalizedLimitPerSec', 5.0e-4, ...
    'equationRelativeTolerance', 2e-11, ...
    'scheduleAbsoluteTolerance', 2e-11, ...
    'maxRelativeStepNp', 0.02, ...
    'maxRelativeStepNg', 0.02, ...
    'maxRelativeStepWf', 0.25, ...
    'maxRelativeStepT45', 0.10);
options = local_merge_known(options, userOptions);
options = local_validate_options(options);

local_require_fields(mission, ...
    {'id','definition','schedule','runtimeBoundarySchedule', ...
     'runtimeConfig','initialTrim','summary'}, 'mission');
if ~isempty(options.requiredMissionId) && ...
        ~strcmp(mission.id, options.requiredMissionId)
    error('sht:flightMissionRun:wrongMission', ...
        '要求任务 %s，但收到 %s。', options.requiredMissionId, mission.id);
end
if ~istable(mission.schedule) || isempty(fieldnames(mission.runtimeConfig))
    error('sht:flightMissionRun:missingPreparedConfig', ...
        '%s 必须先由 S5 独立配平并生成 runtimeConfig。', mission.id);
end

cfg = mission.runtimeConfig;
local_validate_first_round_contract(mission, cfg);
simulation = sht_simulate_control_m(cfg);
logData = simulation.log;
time_s = simulation.time(:);
schedule = mission.schedule;

requiredLogFields = {'Np','Ng','Wf','T45','Mkg','Mkp','NpDem', ...
    'maxErr','convergeTag','xEngine','thetaCollectiveDeg','kTheta', ...
    'thetaWithinValidRange','Npr','Qload','Pload', ...
    'flightBoundaryEnabled','flightBoundaryTime','flightPt1', ...
    'flightTt1','flightPamb','flightHpsPower','flightSigmaDist', ...
    'flightWIn','flightHpcPressureRatio','flightGtPressureRatio', ...
    'flightPtPressureRatio', ...
    'flightMissionId','flightSegmentId', ...
    't45ProtectionActive','t45ProtectionSelected', ...
    'mkpProtectionActive','mkpProtectionSelected', ...
    'ngTopProtectionActive','ngTopProtectionSelected', ...
    'accelLimitSelected','decelLimitSelected'};
local_require_fields(logData, requiredLogFields, 'simulation.log');

sampleCount = numel(time_s);
expectedCount = height(schedule);
% validate_runtime_config 会按控制/积分周期公约数重算 Tsim，十进制
% 0.025 在双精度中会产生逐步累计到 1e-12 量级的时间表示误差。
% 这里按样本数放大机器精度，只容纳浮点累计误差，不容纳错位采样点。
timeTolerance = max(1e-10, 100 * expectedCount * ...
    eps(max(1, schedule.time_s(end))));
timeGridMatched = sampleCount == expectedCount && ...
    max(abs(time_s - schedule.time_s(:))) <= timeTolerance;
if ~timeGridMatched
    error('sht:flightMissionRun:timeGridMismatch', ...
        '%s 的仿真时间网格与任务调度不一致。', mission.id);
end

finiteFields = {'Np','Ng','Wf','T45','Mkg','Mkp','NpDem', ...
    'maxErr','thetaCollectiveDeg','kTheta','Npr','Qload','Pload', ...
    'flightBoundaryTime','flightPt1','flightTt1','flightPamb', ...
    'flightHpsPower','flightSigmaDist','flightWIn', ...
    'flightHpcPressureRatio','flightGtPressureRatio', ...
    'flightPtPressureRatio'};
allFinite = all(isfinite(logData.xEngine(:)));
for i = 1:numel(finiteFields)
    value = logData.(finiteFields{i});
    allFinite = allFinite && numel(value) == sampleCount && ...
        all(isfinite(value(:)));
end

model = mission.runtimeBoundarySchedule.model;
mappingCfg = model.collectivePitchMapping;
designNpRpm = model.designNpRpm;
designTorqueNm = model.designTorqueNm;
[mappedKTheta, mappingDiagnostic] = sht_collective_pitch_mapping( ...
    logData.thetaCollectiveDeg, 'thetaToKTheta', mappingCfg);

expectedNpr = logData.Np(:) / designNpRpm;
expectedQload = designTorqueNm .* logData.kTheta(:) .* expectedNpr.^2;
expectedPload = expectedQload .* logData.Np(:) * pi / 30;

diagnostic = struct();
diagnostic.sampleCount = sampleCount;
diagnostic.duration_s = time_s(end) - time_s(1);
diagnostic.maxThetaScheduleError_deg = max(abs( ...
    logData.thetaCollectiveDeg(:) - schedule.theta_deg(:)));
diagnostic.maxKThetaScheduleError = max(abs( ...
    logData.kTheta(:) - schedule.kTheta(:)));
diagnostic.maxThetaMappingError = max(abs( ...
    mappedKTheta(:) - logData.kTheta(:)));
diagnostic.maxNprEquationError = max(abs(logData.Npr(:) - expectedNpr));
diagnostic.maxQloadEquationError_Nm = max(abs( ...
    logData.Qload(:) - expectedQload));
diagnostic.maxPloadEquationError_W = max(abs( ...
    logData.Pload(:) - expectedPload));
diagnostic.maxEngineResidual = max(logData.maxErr(:));
diagnostic.nonzeroConvergeTagCount = nnz(logData.convergeTag(:) ~= 0);
diagnostic.maxAbsNpTrackingError_rpm = max(abs( ...
    logData.Np(:) - logData.NpDem(:)));
diagnostic.rmsNpTrackingError_rpm = sqrt(mean( ...
    (logData.Np(:) - logData.NpDem(:)).^2));
diagnostic.allThetaWithinValidRange = ...
    all(logData.thetaWithinValidRange(:)) && ...
    all(mappingDiagnostic.thetaWithinValidRange(:));
diagnostic.allFlightBoundaryEnabled = ...
    all(logData.flightBoundaryEnabled(:));
diagnostic.allMissionLabelsMatched = all(strcmp( ...
    logData.flightMissionId(:), mission.id));
diagnostic.allSegmentLabelsMatched = isequal( ...
    logData.flightSegmentId(:), schedule.segmentId(:));
diagnostic.maxSigmaDistScheduleError = max(abs( ...
    logData.flightSigmaDist(:) - schedule.sigmaDist(:)));
diagnostic.maxPt1ScheduleError_Pa = max(abs( ...
    logData.flightPt1(:) - schedule.Pt1_Pa(:)));
diagnostic.maxTt1ScheduleError_K = max(abs( ...
    logData.flightTt1(:) - schedule.Tt1_K(:)));
diagnostic.maxPambScheduleError_Pa = max(abs( ...
    logData.flightPamb(:) - schedule.Pamb_Pa(:)));
diagnostic.distortionIsConstantUnity = ...
    max(abs(logData.flightSigmaDist(:) - 1)) <= ...
        options.scheduleAbsoluteTolerance;
diagnostic.distortionContainsLoss = ...
    min(logData.flightSigmaDist(:)) < 1 - ...
        options.scheduleAbsoluteTolerance;
diagnostic.distortionScheduleMatched = ...
    diagnostic.maxSigmaDistScheduleError <= ...
        options.scheduleAbsoluteTolerance;
switch options.distortionMode
    case 'unity'
        diagnostic.distortionRequirementPassed = ...
            diagnostic.distortionScheduleMatched && ...
            diagnostic.distortionIsConstantUnity;
    case 'schedule'
        diagnostic.distortionRequirementPassed = ...
            diagnostic.distortionScheduleMatched && ...
            diagnostic.distortionContainsLoss;
    otherwise
        error('sht:flightMissionRun:internalDistortionMode', ...
            '未处理 distortionMode=%s。', options.distortionMode);
end
diagnostic.hpsPowerIs30000W = max(abs( ...
    logData.flightHpsPower(:) - 30000)) <= ...
    options.scheduleAbsoluteTolerance;

qScale = max(1, max(abs(expectedQload)));
pScale = max(1, max(abs(expectedPload)));
scheduleConsistent = ...
    diagnostic.maxThetaScheduleError_deg <= ...
        options.scheduleAbsoluteTolerance && ...
    diagnostic.maxKThetaScheduleError <= ...
        options.scheduleAbsoluteTolerance && ...
    diagnostic.maxThetaMappingError <= ...
        options.equationRelativeTolerance && ...
    diagnostic.maxNprEquationError <= ...
        options.equationRelativeTolerance && ...
    diagnostic.maxQloadEquationError_Nm <= ...
        options.equationRelativeTolerance * qScale && ...
    diagnostic.maxPloadEquationError_W <= ...
        options.equationRelativeTolerance * pScale && ...
    diagnostic.maxSigmaDistScheduleError <= ...
        options.scheduleAbsoluteTolerance && ...
    diagnostic.maxPt1ScheduleError_Pa <= ...
        options.equationRelativeTolerance * ...
            max(1, max(abs(schedule.Pt1_Pa))) && ...
    diagnostic.maxTt1ScheduleError_K <= ...
        options.equationRelativeTolerance * ...
            max(1, max(abs(schedule.Tt1_K))) && ...
    diagnostic.maxPambScheduleError_Pa <= ...
        options.equationRelativeTolerance * ...
            max(1, max(abs(schedule.Pamb_Pa)));

[steadyWindows, steadyPassed] = local_steady_window_summary( ...
    mission, simulation, options);
protectionSummary = local_protection_summary(logData);
jumpDiagnostic = local_jump_diagnostic(logData, mission, options);
baselineRevisit = local_baseline_revisit_summary(steadyWindows, ...
    options.baselineReferenceWindowId, options.baselineRevisitWindowId);

validation = struct();
validation.passed = allFinite && timeGridMatched && ...
    sampleCount == mission.summary.sampleCount && ...
    abs(diagnostic.duration_s - mission.definition.duration_s) <= ...
        timeTolerance && scheduleConsistent && ...
    diagnostic.maxEngineResidual <= options.maxResidualAllowed && ...
    diagnostic.nonzeroConvergeTagCount == 0 && ...
    diagnostic.allThetaWithinValidRange && ...
    diagnostic.allFlightBoundaryEnabled && ...
    diagnostic.allMissionLabelsMatched && ...
    diagnostic.allSegmentLabelsMatched && ...
    diagnostic.distortionRequirementPassed && ...
    diagnostic.hpsPowerIs30000W && steadyPassed && ...
    jumpDiagnostic.passed;
validation.allFinite = allFinite;
validation.timeGridMatched = timeGridMatched;
validation.scheduleAndLoadEquationsPassed = scheduleConsistent;
validation.distortionRequirementPassed = ...
    diagnostic.distortionRequirementPassed;
validation.steadyWindowsPassed = steadyPassed;
validation.jumpCheckPassed = jumpDiagnostic.passed;
validation.maxResidualPassed = ...
    diagnostic.maxEngineResidual <= options.maxResidualAllowed;
validation.convergenceTagsPassed = ...
    diagnostic.nonzeroConvergeTagCount == 0;

if ~validation.passed
    error('sht:flightMissionRun:validationFailed', ...
        ['%s 的时域验收失败：finite=%d，schedule=%d，steady=%d，' ...
         'jump=%d，thetaValid=%d，boundary=%d，mission=%d，' ...
         'segment=%d，distortion=%d，hps=%d，maxErr=%.6g，' ...
         'nonzeroTag=%d。'], ...
        mission.id, allFinite, scheduleConsistent, steadyPassed, ...
        jumpDiagnostic.passed, diagnostic.allThetaWithinValidRange, ...
        diagnostic.allFlightBoundaryEnabled, ...
        diagnostic.allMissionLabelsMatched, ...
        diagnostic.allSegmentLabelsMatched, ...
        diagnostic.distortionRequirementPassed, ...
        diagnostic.hpsPowerIs30000W, diagnostic.maxEngineResidual, ...
        diagnostic.nonzeroConvergeTagCount);
end

run = struct();
run.stage = options.stageTag;
run.variantId = options.runVariantId;
run.missionId = mission.id;
run.simulation = simulation;
run.schedule = schedule;
run.diagnostic = diagnostic;
run.steadyWindows = steadyWindows;
run.protectionSummary = protectionSummary;
run.jumpDiagnostic = jumpDiagnostic;
run.baselineRevisit = baselineRevisit;
run.validation = validation;
run.options = options;
end

function local_validate_first_round_contract(mission, cfg)
if numel(cfg.engine.initial.state) ~= 2 || ...
        ~isequal(cfg.engine.stateNames, {'Np','Ng'})
    error('sht:flightMissionRun:stateCount', ...
        '%s 必须使用严格的 [Np; Ng] 两状态模型。', mission.id);
end
if isfield(cfg.engine, 'transientEffects')
    error('sht:flightMissionRun:transientEffectsEnabled', ...
        '第 3 阶段首轮飞行任务不允许启用三类瞬态增强状态。');
end
interfaceHealthLength = cfg.engine.interface.healthLength;
if ~isfield(cfg.engine.boundary, 'health') || ...
        ~isnumeric(cfg.engine.boundary.health) || ...
        ~isreal(cfg.engine.boundary.health) || ...
        numel(cfg.engine.boundary.health) ~= interfaceHealthLength || ...
        any(~isfinite(cfg.engine.boundary.health(:)))
    error('sht:flightMissionRun:badHealth', ...
        ['第3阶段飞行任务必须使用与当前DLL字典一致的有限健康向量；' ...
         '原100维真值应在扩展区补零。']);
end
% S9 只允许传统稳态健康参数 hlthparas[0:57] 非零。惯量、热沉浸和
% 动态间隙修正位于 hlthparas[58:99]，这些通道仍必须关闭，才能保证
% 当前运行严格保持 [Np; Ng] 两状态基准模型。
health = cfg.engine.boundary.health(:);
if nnz(health(59:100)) ~= 0 || ...
        (numel(health) > 100 && nnz(health(101:end)) ~= 0)
    error('sht:flightMissionRun:transientHealthEnabled', ...
        ['第 3 阶段首轮只允许 hlthparas[0:57] 的稳态健康参数非零；' ...
         'hlthparas[58:99] 及接口扩展区必须全部为零。']);
end
if ~strcmpi(cfg.sensor.mode, 'identity') || ...
        cfg.sensor.timeConstant ~= 0 || nnz(cfg.sensor.bias) ~= 0 || ...
        nnz(cfg.sensor.noiseStd) ~= 0
    error('sht:flightMissionRun:measurementErrorEnabled', ...
        ['发动机闭环内部传感器必须保持恒等；S8/S9 飞参测量误差只能在' ...
         '真值仿真结束后加入。']);
end
if mission.runtimeBoundarySchedule.model.deltaPExhaust_Pa ~= 0
    error('sht:flightMissionRun:exhaustBackPressureEnabled', ...
        '第 3 阶段首轮的排气背压增量必须为 0 Pa。');
end
if mission.runtimeBoundarySchedule.model.hpsPower_W ~= 30000
    error('sht:flightMissionRun:badHpsPower', ...
        '第 3 阶段首轮的 GT 轴附件功率必须为 30000 W。');
end
end

function [summary, allPassed] = local_steady_window_summary( ...
        mission, simulation, options)
logData = simulation.log;
time_s = simulation.time(:);
schedule = mission.schedule;
dt = median(diff(time_s));
dNp = gradient(logData.Np(:), dt);
dNg = gradient(logData.Ng(:), dt);
npReference = mission.runtimeBoundarySchedule.model.designNpRpm;
ngReference = mission.initialTrim.Ng;
windows = mission.definition.steadyWindows;
protectionFields = {'t45ProtectionSelected','mkpProtectionSelected', ...
    'ngTopProtectionSelected','accelLimitSelected','decelLimitSelected'};

n = numel(windows);
windowId = cell(n, 1);
startTime_s = zeros(n, 1);
endTime_s = zeros(n, 1);
sampleCount = zeros(n, 1);
meanNp_rpm = zeros(n, 1);
rangeNp_rpm = zeros(n, 1);
rmsNpTrackingError_rpm = zeros(n, 1);
meanNg_rpm = zeros(n, 1);
meanWf_kgps = zeros(n, 1);
meanT45_K = zeros(n, 1);
meanMkg_Nm = zeros(n, 1);
meanMkp_Nm = zeros(n, 1);
meanPload_W = zeros(n, 1);
maxNormalizedNpRate_per_s = zeros(n, 1);
maxNormalizedNgRate_per_s = zeros(n, 1);
maxEngineResidual = zeros(n, 1);
protectionSwitchCount = zeros(n, 1);
allFinite = false(n, 1);
passed = false(n, 1);

for i = 1:n
    windowId{i} = windows(i).id;
    startTime_s(i) = windows(i).startTime_s;
    endTime_s(i) = windows(i).endTime_s;
    mask = strcmp(schedule.candidateWindowId, windowId{i});
    index = find(mask);
    sampleCount(i) = numel(index);
    if isempty(index)
        continue;
    end
    meanNp_rpm(i) = mean(logData.Np(index));
    rangeNp_rpm(i) = max(logData.Np(index)) - min(logData.Np(index));
    rmsNpTrackingError_rpm(i) = sqrt(mean( ...
        (logData.Np(index) - logData.NpDem(index)).^2));
    meanNg_rpm(i) = mean(logData.Ng(index));
    meanWf_kgps(i) = mean(logData.Wf(index));
    meanT45_K(i) = mean(logData.T45(index));
    meanMkg_Nm(i) = mean(logData.Mkg(index));
    meanMkp_Nm(i) = mean(logData.Mkp(index));
    meanPload_W(i) = mean(logData.Pload(index));
    maxNormalizedNpRate_per_s(i) = max(abs(dNp(index))) / npReference;
    maxNormalizedNgRate_per_s(i) = max(abs(dNg(index))) / ngReference;
    maxEngineResidual(i) = max(logData.maxErr(index));
    protectionSwitchCount(i) = local_switch_count( ...
        logData, index, protectionFields);
    finiteValues = [logData.Np(index); logData.Ng(index); ...
        logData.Wf(index); logData.T45(index); logData.Mkg(index); ...
        logData.Mkp(index); logData.Pload(index); logData.maxErr(index)];
    allFinite(i) = all(isfinite(finiteValues));
    passed(i) = allFinite(i) && ...
        maxNormalizedNpRate_per_s(i) <= ...
            options.npRateNormalizedLimitPerSec && ...
        maxNormalizedNgRate_per_s(i) <= ...
            options.ngRateNormalizedLimitPerSec && ...
        maxEngineResidual(i) <= options.maxResidualAllowed && ...
        protectionSwitchCount(i) == 0;
end

summary = table(windowId, startTime_s, endTime_s, sampleCount, ...
    meanNp_rpm, rangeNp_rpm, rmsNpTrackingError_rpm, meanNg_rpm, ...
    meanWf_kgps, meanT45_K, meanMkg_Nm, meanMkp_Nm, meanPload_W, ...
    maxNormalizedNpRate_per_s, maxNormalizedNgRate_per_s, ...
    maxEngineResidual, protectionSwitchCount, allFinite, passed);
allPassed = all(passed);
end

function summary = local_protection_summary(logData)
names = {'T45Active','T45Selected','MkpActive','MkpSelected', ...
    'NgActive','NgSelected','AccelSelected','DecelSelected'};
fields = {'t45ProtectionActive','t45ProtectionSelected', ...
    'mkpProtectionActive','mkpProtectionSelected', ...
    'ngTopProtectionActive','ngTopProtectionSelected', ...
    'accelLimitSelected','decelLimitSelected'};
n = numel(fields);
activeSampleCount = zeros(n, 1);
transitionCount = zeros(n, 1);
for i = 1:n
    state = logData.(fields{i})(:) > 0.5;
    activeSampleCount(i) = nnz(state);
    transitionCount(i) = nnz(diff(double(state)) ~= 0);
end
summary = table(names(:), fields(:), activeSampleCount, transitionCount, ...
    'VariableNames', {'channel','logField','activeSampleCount', ...
    'transitionCount'});
end

function diagnostic = local_jump_diagnostic(logData, mission, options)
signals = {'Np','Ng','Wf','T45'};
relativeLimits = [options.maxRelativeStepNp, options.maxRelativeStepNg, ...
    options.maxRelativeStepWf, options.maxRelativeStepT45];
reference = [mission.runtimeBoundarySchedule.model.designNpRpm, ...
    mission.initialTrim.Ng, max(abs(logData.Wf)), max(abs(logData.T45))];
maxAbsoluteStep = zeros(numel(signals), 1);
maxRelativeStep = zeros(numel(signals), 1);
timeOfMaxStep_s = zeros(numel(signals), 1);
passed = false(numel(signals), 1);
for i = 1:numel(signals)
    step = abs(diff(logData.(signals{i})(:)));
    [maxAbsoluteStep(i), index] = max(step);
    maxRelativeStep(i) = maxAbsoluteStep(i) / max(reference(i), realmin);
    timeOfMaxStep_s(i) = logData.time(index + 1);
    passed(i) = maxRelativeStep(i) <= relativeLimits(i);
end
diagnostic = struct();
diagnostic.table = table(signals(:), maxAbsoluteStep, maxRelativeStep, ...
    timeOfMaxStep_s, relativeLimits(:), passed, ...
    'VariableNames', {'signal','maxAbsoluteStep','maxRelativeStep', ...
    'timeOfMaxStep_s','relativeLimit','passed'});
diagnostic.passed = all(passed);
end

function revisit = local_baseline_revisit_summary(steadyWindows, ...
        referenceWindowId, revisitWindowId)
revisit = struct('available', false, ...
    'referenceWindow', referenceWindowId, ...
    'revisitWindow', revisitWindowId, 'table', table());
if isempty(referenceWindowId) || isempty(revisitWindowId)
    return;
end
first = find(strcmp(steadyWindows.windowId, referenceWindowId), 1);
last = find(strcmp(steadyWindows.windowId, revisitWindowId), 1);
if isempty(first) || isempty(last)
    return;
end
revisit.available = true;
fields = {'meanNp_rpm','meanNg_rpm','meanWf_kgps','meanT45_K', ...
    'meanMkg_Nm','meanMkp_Nm','meanPload_W'};
delta = zeros(numel(fields), 1);
relativeDelta = zeros(numel(fields), 1);
for i = 1:numel(fields)
    reference = steadyWindows.(fields{i})(first);
    value = steadyWindows.(fields{i})(last);
    delta(i) = value - reference;
    relativeDelta(i) = delta(i) / max(abs(reference), realmin);
end
revisit.table = table(fields(:), delta, relativeDelta, ...
    'VariableNames', {'signal','delta','relativeDelta'});
end

function count = local_switch_count(logData, index, fields)
count = 0;
if numel(index) < 2
    return;
end
for i = 1:numel(fields)
    state = logData.(fields{i})(index) > 0.5;
    count = count + nnz(diff(double(state)) ~= 0);
end
end

function options = local_validate_options(options)
textNames = {'requiredMissionId','stageTag','runVariantId', ...
    'distortionMode','baselineReferenceWindowId', ...
    'baselineRevisitWindowId'};
for i = 1:numel(textNames)
    name = textNames{i};
    options.(name) = local_char_row(options.(name), name);
end
if isempty(options.stageTag) || isempty(options.runVariantId)
    error('sht:flightMissionRun:emptyRunIdentity', ...
        'stageTag 和 runVariantId 不得为空。');
end
if ~ismember(options.distortionMode, {'unity','schedule'})
    error('sht:flightMissionRun:badDistortionMode', ...
        'distortionMode 必须为 ''unity'' 或 ''schedule''。');
end
hasReference = ~isempty(options.baselineReferenceWindowId);
hasRevisit = ~isempty(options.baselineRevisitWindowId);
if hasReference ~= hasRevisit
    error('sht:flightMissionRun:incompleteBaselinePair', ...
        '基线窗口和回访窗口必须同时给出或同时留空。');
end
positiveNames = {'maxResidualAllowed','npRateNormalizedLimitPerSec', ...
    'ngRateNormalizedLimitPerSec','equationRelativeTolerance', ...
    'scheduleAbsoluteTolerance','maxRelativeStepNp','maxRelativeStepNg', ...
    'maxRelativeStepWf','maxRelativeStepT45'};
for i = 1:numel(positiveNames)
    name = positiveNames{i};
    value = options.(name);
    if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
            ~isfinite(value) || value <= 0
        error('sht:flightMissionRun:badOption', ...
            'userOptions.%s 必须是有限正标量。', name);
    end
end
end

function merged = local_merge_known(base, override)
merged = base;
names = fieldnames(override);
for i = 1:numel(names)
    name = names{i};
    if ~isfield(base, name)
        error('sht:flightMissionRun:unknownOption', ...
            '未知 userOptions 字段 %s。', name);
    end
    merged.(name) = override.(name);
end
end

function local_require_fields(value, names, valueName)
for i = 1:numel(names)
    if ~isfield(value, names{i})
        error('sht:flightMissionRun:missingField', ...
            '%s 缺少字段 %s。', valueName, names{i});
    end
end
end

function value = local_char_row(value, name)
if isstring(value) && isscalar(value)
    value = char(value);
end
if ~ischar(value) || (~isempty(value) && size(value, 1) ~= 1)
    error('sht:flightMissionRun:badText', '%s 必须是字符行。', name);
end
end
