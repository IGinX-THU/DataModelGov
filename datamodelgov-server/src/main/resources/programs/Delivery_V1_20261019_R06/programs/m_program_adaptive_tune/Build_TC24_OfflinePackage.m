function inventory=Build_TC24_OfflinePackage(destination)
% 生成不依赖开发机绝对目录的TC24离线源码包，不复制历史计算缓存。
% 不改输入文件，只复制依赖；目标目录须不存在。MATLAB及VC2010仍需安装。
root=fileparts(mfilename('fullpath'));destination=sht_tc24_absolute_path(destination);
assert(~exist(destination,'dir'),'TC24:Package:Exists','交付目录已存在，请另选新目录。');
entries={'Start_TC24_00_Offline.m','sht_tc24_offline_example.m', ...
    'Start_TC24_01_PreprocessPreview.m','sht_tc24_run_control.m','sht_tc24_runtime_estimate.m', ...
    'Start_TC24_04_SteadyEstimation.m','Start_TC24_05_TransientInstantEstimation.m', ...
    'Start_TC24_07_UncertaintyAssessment.m','Start_SteadyModelPredict_01_InputDrivenPrediction.m', ...
    'sht_tc24_b_config.m','sht_tc24_b_lean_config.m','Start_TC24_B_Lean.m', ...
    'sht_tc24_result_view.m','sht_load_2p4_uq_delivery.m'};
sources=cellfun(@(n)fullfile(root,n),entries,'UniformOutput',false);
% 静态调用闭包加明确字符串声明的源码身份依赖；动态eval外部代码不允许。
while true
    previous=numel(sources);
    [required,~]=matlab.codetools.requiredFilesAndProducts(sources);
    required=required(cellfun(@(f)strcmpi(fileparts(f),root),required));
    sources=unique([sources(:);required(:)],'stable');
    extra={};
    for k=1:numel(sources)
        text=fileread(sources{k});names=regexp(text,'[A-Za-z][A-Za-z0-9_]*\.m(?=[''"; ])','match');
        for j=1:numel(names)
            file=fullfile(root,names{j});if isfile(file),extra{end+1,1}=file;end %#ok<AGROW>
        end
    end
    sources=unique([sources(:);extra(:)],'stable');
    if numel(sources)==previous,break;end
end
package=sht_tc24_runtime_package();
record=jsondecode(fileread(package.selectionFile));
relative=cellfun(@(f)f(numel(root)+2:end),sources,'UniformOutput',false);
fixed={'sht_controller_gain_schedule.mat','sht_controller_ndot_schedule.mat', ...
    'TestData/three_component/tc24_runtime_selection.json', ...
    'matlab_loadlibrary_include/stdio.h', ...
    'TestData/compatibility/joe-kuo-old.1111', ...
    'TestData/compatibility/Sobol_LICENSE.txt'};
relative=[relative(:);fixed(:)];
for k=1:numel(record.assets)
    a=record.assets(k);
    relative{end+1,1}=fullfile(record.runtimeRelative,a.name); %#ok<AGROW>
    if a.matchFormalSource,relative{end+1,1}=a.name;end %#ok<AGROW>
end
% 头文件解析桩是实际冷加载依赖，不能靠已生成thunk碰巧通过。
stub=fullfile(record.runtimeRelative,'matlab_loadlibrary_include','stdio.h');
if isfile(fullfile(root,stub)),relative{end+1,1}=stub;end
relative=unique(relative,'stable');mkdir(destination);
names=strings(numel(relative),1);hashes=names;bytes=zeros(numel(relative),1);
for k=1:numel(relative)
    source=fullfile(root,relative{k});target=fullfile(destination,relative{k});
    assert(isfile(source),'TC24:Package:Missing','缺少离线依赖：%s',source);
    folder=fileparts(target);if ~exist(folder,'dir'),mkdir(folder);end
    copyfile(source,target);names(k)=string(relative{k});
    hashes(k)=string(sht_steady_model_uq_common('filehash',target));d=dir(target);bytes(k)=d.bytes;
end
% 交付包内自带启动说明，不要求用户回到开发项目寻找文档。
readme=fullfile(destination,'README_离线运行.md');
lines={'# TC24离线运行', '', ...
    '环境：Windows x64、MATLAB R2019b、已配置VC2010加载环境；默认不需要Optimization/Statistics工具箱。', ...
    '本包不是EXE；不需要GUI、Codex或联网下载。不包含用户试车数据或旧结果。', '', ...
    '1. 进入本目录，执行 addpath(pwd); sht_r2019b_preflight;', ...
    '2. cfg=sht_tc24_offline_example(用户工作目录); 集中设置训练Excel、可空的testFile、outputDirectory和唯一runId。', ...
    '3. cfg.route为steady或transient_instant。r=Start_TC24_00_Offline(cfg)开始确定性辨识。', ...
    '4. 用sht_tc24_result_view(结果文件)独立读结果；训练与测试分开，燃油偏置单位kg/s。', '', ...
    '可直接调用Start_TC24_04_SteadyEstimation或05，二者与离线Start共用求解器。', ...
    '现行默认配置通过sht_tc24_estimation_options(route)查询；不要把示例短测预算当正式默认。', ...
    '输入每工况一行测量均值及实际sample_count，使用完整有效稳态段；参见sht_tc24_validate_measurements。', ...
    '正式跨阶段模型为Excel；result_view.mat、缓存、检查点仅供内部结果浏览和计算。', '', ...
    '独立预测：Start_SteadyModelPredict_01_InputDrivenPrediction(p,modelExcel,[],options)。', ...
    'p需明确环境、Pt1/Tt1边界、Mach/Tamb、物理Wf_model及Mkp/Mkg；不需要目标Np/Ng或目标输出。', ...
    'Wf_model不再扣燃油测量偏置。第三参数可给workbookFile后验配置，仅匹配的后验允许区间传播。', '', ...
    'UQ：cfg=sht_tc24_offline_example(用户工作目录,''uq''); 编辑路径后Start_TC24_00_Offline(cfg)。', ...
    '也可Start_TC24_07_UncertaintyAssessment(''B''/''C''/''D'',options)，使用同一核心，显式指定训练Excel和deterministicWorkbookFile。', ...
    'B默认V2/1024粒子/中间4轮/末层64轮/冻结参考精确移动；bConfiguration=''V1''可选较短2/32轮配置。', ...
    '正式B配置查询sht_tc24_b_config；particleCount可选512或1024，不改变先验和似然。历史B只作冻结对照，不能改名为本次结果。', ...
    'route选择steady（稳态模型）或transient_instant（瞬态时刻模型）；当前B/C完整验证为瞬态时刻模型，预测均使用稳态模型。', ...
    '稳态模型中Np/Ng是待预测输出。稳态B/C完整全局计算仍未验证；稳态D仅有局部初评代表证据。', ...
    'D是局部快速初评，不是全局正式后验。完整B/C计算前先核对预算，lastStep可用于分阶段准备。', '', ...
    '日志：runId目录的status.json/progress.jsonl/execution.json；无可靠预计时间时明确标注不可估。', ...
    '可选progressCallback及plotEnabled均不是计算前置条件。未收敛状态与物理无效分开报告。', ...
    '预览：p=Start_TC24_01_PreprocessPreview(route,options); 正式运行设置preparedInput=p.file复用。', ...
    '只有数据内容、数值配置、运行包及源码身份一致才复用；参数预算变化须重新准备。', ...
    '协作停止需enableRunControl=true；sht_tc24_run_control(requeststop,完整任务目录)提交请求。', ...
    '计算命令行忙碌时，在第二个独立MATLAB会话addpath本程序目录后调用requeststop；该会话仅写请求、不加载DLL。需本机许可支持第二会话，并可访问同一任务目录。不要用Ctrl+C或强杀代替安全停止。', ...
    '停止不是强杀：A/B每次完整求解、D完整求解通道、SMC完整移动轮及D初评完整迭代处保存。', ...
    '恢复使用同一runId、完整数值配置和resume=true；不得改变预算或重签旧检查点。', ...
    '完整任务目录已含runId，不要重复拼接。status=stopped才表示已安全保存，stop_requested仍在运行。', ...
    '异常退出留下session.lock时，先确认旧进程已结束，再人工处理该任务锁；不要并发恢复。', ...
    '运行前可调用sht_tc24_fixed_runtime_estimate(task,options)；task取identification_steady、identification_transient_instant或uq_B/C/D。', ...
    '预计时间按冻结实测基准和本次工作量粗估，首次新数据运行也可得数值与工程范围；这不是准确倒计时。timingHistoryDirectory仅保存实际耗时供后续校准，不是估时前提。', ...
    'V2同规模12训练/4测试本机完整原生运行约89.55分钟，非各步骤独立相加的重复计时；512或新数据仅是工作量外推。', ...
    'Excel可sht_tc24_result_view读取确定性模型或联合后验；完整任务result.mat保留训练/测试预测、配置、状态和执行记录。', ...
    '常见错误：任务目录已存在时换runId；缺文件/运行库时修复部署；后验错配时不能重签旧文件。', ...
    '运行目录需可写以生成桥接库。Windows过深目录可能触发Excel路径限制，建议使用简短输出根。', ...
    'dependency_manifest.csv给出本包依赖SHA；TestData/compatibility包含Sobol方向数与许可证。'};
fid=fopen(readme,'w','n','UTF-8');assert(fid>=0,'无法写离线说明。');
guard=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',lines{:});clear guard;
names(end+1,1)="README_离线运行.md";
hashes(end+1,1)=string(sht_steady_model_uq_common('filehash',readme));d=dir(readme);bytes(end+1,1)=d.bytes;
inventory=table(names,hashes,bytes,'VariableNames',{'relative_file','sha256','bytes'});
% 显式UTF-8，避免R2019b本机默认编码使交付清单中的中文文件名失真。
writetable(inventory,fullfile(destination,'dependency_manifest.csv'),'Encoding','UTF-8');
fprintf('TC24离线包：%d个文件，%.1f MB；不含试车数据、隐藏真值或旧检查点。\n',height(inventory),sum(bytes)/1024^2);
end
