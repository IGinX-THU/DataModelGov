function result = sht_steady_np_branch_prior( ...
        trainingData, testData, trainingReference, userOptions)
%SHT_STEADY_NP_BRANCH_PRIOR 从训练工况提炼测试点Np合理分支先验。
%
% 本函数不使用测试集Np。训练工况的已知转速设定值与实测Mkp共同
% 形成轴功率，再以实测Wf为横坐标建立分段线性功率曲线：
%
%   P_i = Mkp_i * pi * Np_ref_i / 30
%   P_hat = F(Wf_test)
%   Np_branch = 30 * P_hat / (pi * Mkp_test)
%
% 得到的Np_branch只用于识别稳态共同工作根，不作为新观测、不进入
% 贝叶斯似然，也不能代替真实试车转速指令。容许带由训练点内部留一
% 误差给出，测试Wf超出训练覆盖域时禁止外插。

if nargin < 4 || isempty(userOptions), userOptions = struct(); end
options = local_options(userOptions);
local_validate_data(trainingData, '训练集', 3);
local_validate_data(testData, '目标集', 1);
local_validate_reference(trainingReference, trainingData);

nTraining = height(trainingData);
referenceNp = nan(nTraining, 1);
for i = 1:nTraining
    index = find(string(trainingReference.point_id) == ...
        string(trainingData.point_id(i)), 1);
    referenceNp(i) = trainingReference.Np_ref_rpm(index);
end

wf = double(trainingData.Wf_mean(:));
mkp = double(trainingData.Mkp_mean(:));
power = mkp .* (pi / 30) .* referenceNp;
[wfSorted, order] = sort(wf);
powerSorted = power(order);
npSorted = referenceNp(order);
pointSorted = string(trainingData.point_id(order));
mkpSorted = mkp(order);

if any(diff(wfSorted) <= options.minimumWfSeparation)
    error('SHT:SteadyNpBranch:DuplicateFuelCoordinate', ...
        ['训练工况Wf坐标存在重复或过近节点，无法建立唯一分段线性' ...
         '功率曲线。最小节点间距必须大于%.6g kg/s。'], ...
        options.minimumWfSeparation);
end
powerIncrement = diff(powerSorted);
if options.requireIncreasingPower && any(powerIncrement <= options.minimumPowerIncrementW)
    error('SHT:SteadyNpBranch:NonmonotonicPowerCurve', ...
        ['训练数据没有形成随Wf严格递增的轴功率曲线。当前方法拒绝' ...
         '静默平滑或强行单调化，请先检查工况、偏置或附件负载变化。']);
end

% 端点不能做无外插留一验证，只对内部节点执行留一线性插值。
looIndex = (2:nTraining-1).';
looEstimate = nan(numel(looIndex), 1);
looRelativeError = nan(numel(looIndex), 1);
for k = 1:numel(looIndex)
    i = looIndex(k);
    keep = true(nTraining, 1);
    keep(i) = false;
    estimatedPower = interp1(wfSorted(keep), powerSorted(keep), ...
        wfSorted(i), 'linear');
    looEstimate(k) = 30 * estimatedPower / (pi * mkpSorted(i));
    looRelativeError(k) = ...
        (looEstimate(k) - npSorted(i)) / npSorted(i);
end
looRmsRelative = sqrt(mean(looRelativeError .^ 2));
looMaxAbsRelative = max(abs(looRelativeError));
relativeHalfWidth = options.sigmaMultiplier * looRmsRelative;
relativeHalfWidth = max(relativeHalfWidth, ...
    options.minimumRelativeHalfWidth);
relativeHalfWidth = min(relativeHalfWidth, ...
    options.maximumRelativeHalfWidth);

testWf = double(testData.Wf_mean(:));
testMkp = double(testData.Mkp_mean(:));
inside = testWf >= wfSorted(1) & testWf <= wfSorted(end);
estimatedPower = nan(height(testData), 1);
branchCenter = nan(height(testData), 1);
estimatedPower(inside) = interp1(wfSorted, powerSorted, ...
    testWf(inside), 'linear');
branchCenter(inside) = 30 * estimatedPower(inside) ./ ...
    (pi * testMkp(inside));
lower = branchCenter .* (1 - relativeHalfWidth);
upper = branchCenter .* (1 + relativeHalfWidth);
available = inside & isfinite(branchCenter) & branchCenter > 0;

trainingTable = table(pointSorted, wfSorted, mkpSorted, npSorted, ...
    powerSorted, 'VariableNames', {'point_id','Wf_measured_kgps', ...
    'Mkp_measured_Nm','Np_reference_rpm','reference_power_W'});
looTable = table(pointSorted(looIndex), wfSorted(looIndex), ...
    npSorted(looIndex), looEstimate, 100 * looRelativeError, ...
    'VariableNames', {'point_id','Wf_measured_kgps','Np_reference_rpm', ...
    'Np_leave_one_out_rpm','relative_error_pct'});
testTable = table(string(testData.point_id), testWf, testMkp, ...
    estimatedPower, branchCenter, repmat(relativeHalfWidth, ...
    height(testData), 1), lower, upper, inside, available, ...
    'VariableNames', {'point_id','Wf_measured_kgps','Mkp_measured_Nm', ...
    'estimated_power_W','Np_branch_center_rpm', ...
    'relative_half_width','Np_lower_rpm','Np_upper_rpm', ...
    'inside_training_Wf_range','available'});

result = struct( ...
    'schemaVersion', 'steady_np_branch_prior_v1', ...
    'method', 'training_piecewise_linear_power_curve', ...
    'trainingTable', trainingTable, ...
    'leaveOneOutTable', looTable, ...
    'testTable', testTable, ...
    'trainingPointCount', nTraining, ...
    'leaveOneOutPointCount', numel(looIndex), ...
    'leaveOneOutRmsRelative', looRmsRelative, ...
    'leaveOneOutMaxAbsRelative', looMaxAbsRelative, ...
    'relativeHalfWidth', relativeHalfWidth, ...
    'sigmaMultiplier', options.sigmaMultiplier, ...
    'testNpUsed', false, ...
    'extrapolationAllowed', false, ...
    'allTestPointsAvailable', all(available), ...
    'options', options);
end

function options = local_options(userOptions)
options = struct( ...
    'sigmaMultiplier', 3.0, ...
    'minimumRelativeHalfWidth', 0.03, ...
    'maximumRelativeHalfWidth', 0.08, ...
    'minimumWfSeparation', 1e-10, ...
    'minimumPowerIncrementW', 1.0, ...
    'requireIncreasingPower',true);
names = fieldnames(options);
for i = 1:numel(names)
    if isfield(userOptions, names{i}) && ~isempty(userOptions.(names{i}))
        options.(names{i}) = userOptions.(names{i});
    end
end
positiveScalar = {'sigmaMultiplier','minimumRelativeHalfWidth', ...
    'maximumRelativeHalfWidth','minimumWfSeparation', ...
    'minimumPowerIncrementW'};
for i = 1:numel(positiveScalar)
    value = options.(positiveScalar{i});
    if ~isnumeric(value) || ~isscalar(value) || ...
            ~isfinite(value) || value <= 0
        error('SHT:SteadyNpBranch:BadOption', ...
            '配置%s必须为有限正标量。', positiveScalar{i});
    end
end
if options.minimumRelativeHalfWidth > ...
        options.maximumRelativeHalfWidth
    error('SHT:SteadyNpBranch:BadWidthBounds', ...
        '容许带最小半宽不能大于最大半宽。');
end
end

function local_validate_data(data, role, minimumPointCount)
required = {'point_id','Wf_mean','Mkp_mean'};
if ~istable(data) || any(~ismember(required, data.Properties.VariableNames))
    error('SHT:SteadyNpBranch:BadData', ...
        '%s必须是包含point_id、Wf_mean和Mkp_mean的表格。', role);
end
if height(data) < minimumPointCount || ...
        numel(unique(string(data.point_id))) ~= height(data)
    error('SHT:SteadyNpBranch:BadPointId', ...
        '%s至少需要%d个工况，且point_id必须唯一。', ...
        role, minimumPointCount);
end
value = [double(data.Wf_mean(:)), double(data.Mkp_mean(:))];
if any(~isfinite(value(:))) || any(value(:) <= 0)
    error('SHT:SteadyNpBranch:BadMeasuredBoundary', ...
        '%s的Wf和Mkp必须为有限正值。', role);
end
end

function local_validate_reference(reference, trainingData)
required = {'point_id','Np_ref_rpm'};
if ~istable(reference) || ...
        any(~ismember(required, reference.Properties.VariableNames))
    error('SHT:SteadyNpBranch:BadReference', ...
        '训练转速设定必须是包含point_id和Np_ref_rpm的表格。');
end
if numel(unique(string(reference.point_id))) ~= height(reference) || ...
        any(~isfinite(reference.Np_ref_rpm)) || ...
        any(reference.Np_ref_rpm <= 0)
    error('SHT:SteadyNpBranch:BadReferenceValue', ...
        '训练转速设定的point_id必须唯一，Np_ref_rpm必须为有限正值。');
end
missing = setdiff(string(trainingData.point_id), string(reference.point_id));
if ~isempty(missing)
    error('SHT:SteadyNpBranch:MissingReference', ...
        '以下训练工况缺少Np_ref：%s。', strjoin(cellstr(missing), ', '));
end
end
