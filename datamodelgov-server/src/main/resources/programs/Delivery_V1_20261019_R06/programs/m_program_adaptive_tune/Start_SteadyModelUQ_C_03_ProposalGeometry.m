function result = Start_SteadyModelUQ_C_03_ProposalGeometry(userCfg)
%START_STEADYMODELUQ_C_03_PROPOSALGEOMETRY 构造五核pCN的局部几何。
%
% Jacobian和SVD只用来确定提议移动的方向与尺度。每个候选仍由
% 完整DLL残差和方法C似然执行Metropolis验收，因此局部线性化
% 不会替代非线性后验。
if nargin < 1, userCfg = struct(); end
timer = tic;
manifest = sht_steady_model_uq_c_io('resolvewritable',userCfg);
step1 = sht_steady_model_uq_c_io('loadstep',manifest,1);
step2 = sht_steady_model_uq_c_io('loadstep',manifest,2);
contract = step1.contract;
prior = step1.prior;
likelihood = step2.likelihood;

anchorCandidate = [zeros(contract.parameterCount,1),contract.thetaHat(:)];
anchorName = ["zero_prior_center";"deterministic_estimate"];
if contract.modelMode==0
    [dAnchor,dSource]=sht_tc24_uq_d_proposal_anchor(contract);
    if ~isempty(dAnchor),anchorCandidate(:,end+1)=dAnchor;anchorName(end+1)=string(dSource);end
end
anchorExact = sht_steady_model_uq_c_common('evaluate', ...
    contract,anchorCandidate,contract.trainingData, ...
    struct('useCache',contract.config.useCache));
anchorLogLikelihood = sht_steady_model_uq_likelihood( ...
    'evaluate',likelihood,anchorExact.residual,anchorExact.valid);
anchorLogPrior = sht_steady_model_uq_sampler( ...
    'logprior',prior,anchorCandidate);
anchorLogPosterior = anchorLogLikelihood+anchorLogPrior;
anchorLatentCandidate = sht_steady_model_uq_sampler( ...
    'thetatolatent',prior,anchorCandidate);
anchorLogPriorLatent = sht_steady_model_uq_b_proposal( ...
    'logpriorlatent',anchorLatentCandidate);
anchorLogTargetLatent = anchorLogLikelihood+anchorLogPriorLatent;
[~,selectedAnchorIndex] = max(anchorLogPosterior);
selectedAnchor = anchorCandidate(:,selectedAnchorIndex);
selectedAnchorName = anchorName(selectedAnchorIndex);

[jacobian,differenceStep,retryCount,jacobianSource,dllCount,dllRuntime] = ...
    local_physical_jacobian(contract,selectedAnchor,selectedAnchorName);
whitenedJacobian = likelihood.cholLower \ jacobian;
[latentTransform,anchorLatent] = local_prior_latent_jacobian( ...
    prior,selectedAnchor);
latentJacobian = whitenedJacobian*latentTransform;
[~,singularMatrix,globalBasis] = svd(latentJacobian);
globalSingularValue = diag(singularMatrix);
globalInformedRank = nnz(globalSingularValue > 1);

blockBasis = cell(4,1);
blockSingularValue = cell(4,1);
blockInformedRank = zeros(4,1);
blockEnergyFraction = zeros(4,1);
globalEnergy = sum(globalSingularValue.^2);
for k = 1:4
    index = contract.parameterBlockIndex{k};
    [~,blockS,blockBasis{k}] = svd(latentJacobian(:,index));
    blockSingularValue{k} = diag(blockS);
    blockInformedRank(k) = nnz(blockSingularValue{k} > 1);
    blockEnergyFraction(k) = sum(blockSingularValue{k}.^2)/ ...
        max(globalEnergy,eps);
end

proposalGeometry = struct( ...
    'activeParameterIndex',(1:contract.parameterCount).', ...
    'structuralPriorOnlyParameterIndex',zeros(0,1), ...
    'activeLatentPcnBasis',globalBasis, ...
    'activeLatentInformedRank',globalInformedRank, ...
    'activeLatentSingularValues',globalSingularValue, ...
    'thetaLocal',selectedAnchor);
proposalOptions = struct('priorWeight',1-contract.config.proposalLocalFraction);
guidedProposal = sht_steady_model_uq_b_proposal( ...
    'build',prior,proposalGeometry,proposalOptions);
proposalAudit = sht_steady_model_uq_b_proposal( ...
    'selftest',guidedProposal,3000,contract.config.randomSeed+3001, ...
    'deterministic_mixture');
if ~proposalAudit.passed
    error('SHT:SteadyUQC:ProposalSelfTestFailed', ...
        '方法C防御混合提议自检失败。');
end

blockTable = contract.parameterBlockTable(1:4,:);
blockTable.informed_rank = blockInformedRank;
blockTable.latent_dimension = cellfun(@numel, ...
    contract.parameterBlockIndex(1:4)).';
blockTable.prior_scaled_information_energy_fraction = blockEnergyFraction;
blockTable.initial_pcn_scale = contract.config.initialPcnScale(1:4).';
globalTable = table(contract.parameterCount,globalInformedRank, ...
    globalEnergy,contract.config.initialPcnScale(5), ...
    'VariableNames',{'latent_dimension','informed_rank', ...
    'prior_scaled_information_energy','initial_pcn_scale'});

result = struct('anchorCandidate',anchorCandidate, ...
    'anchorName',anchorName,'anchorExact',anchorExact, ...
    'anchorLogLikelihood',anchorLogLikelihood, ...
    'anchorLogPrior',anchorLogPrior, ...
    'anchorLogPosterior',anchorLogPosterior, ...
    'anchorLatentCandidate',anchorLatentCandidate, ...
    'anchorLogPriorLatent',anchorLogPriorLatent, ...
    'anchorLogTargetLatent',anchorLogTargetLatent, ...
    'selectedAnchorIndex',selectedAnchorIndex, ...
    'selectedAnchor',selectedAnchor, ...
    'selectedAnchorName',selectedAnchorName, ...
    'jacobian',jacobian,'differenceStep',differenceStep, ...
    'differenceRetryCount',retryCount,'jacobianSource',jacobianSource, ...
    'whitenedJacobian',whitenedJacobian, ...
    'latentTransformJacobian',latentTransform, ...
    'selectedAnchorLatent',anchorLatent, ...
    'latentWhitenedJacobian',latentJacobian, ...
    'globalBasis',globalBasis,'globalSingularValue',globalSingularValue, ...
    'globalInformedRank',globalInformedRank, ...
    'blockBasis',{blockBasis},'blockSingularValue',{blockSingularValue}, ...
    'blockInformedRank',blockInformedRank, ...
    'blockEnergyFraction',blockEnergyFraction, ...
    'proposalGeometry',proposalGeometry,'guidedProposal',guidedProposal, ...
    'proposalAudit',proposalAudit,'blockTable',blockTable, ...
    'globalTable',globalTable,'dllEvaluationCount',dllCount, ...
    'dllRuntime_s',dllRuntime,'truthRead',false,'testDataRead',false, ...
    'passed',all(isfinite(jacobian(:))) && proposalAudit.passed);
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_c_io( ...
    'savestep',manifest,3,'proposal_geometry',result,runtime);
writetable(blockTable,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC03_block_information_geometry.csv'));
writetable(globalTable,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC03_global_information_geometry.csv'));
result.plotAudit=sht_steady_model_uq_common('optionalplot',contract.config, ...
    @()local_plot_singular_values(result,contract,manifest));
plotAudit=result.plotAudit; %#ok<NASGU>
save(sht_steady_model_uq_c_io('runfile',manifest,'step03_plot_audit.mat'),'plotAudit');
fprintf(['[2.4UQ-C.3] 提议几何完成：锚点=%s，J=%dx%d，' ...
    '全局信息秩=%d，四块信息秩=[%d %d %d %d]。\n'], ...
    selectedAnchorName,size(jacobian,1),size(jacobian,2), ...
    globalInformedRank,blockInformedRank);
fprintf('[2.4UQ-C.3] Jacobian来源=%s，DLL新计算=%d。\n', ...
    jacobianSource,dllCount);
fprintf('[2.4UQ-C.3] 产物：%s\n',file);
result.manifest = manifest;
end

function [jacobian,step,retryCount,source,dllCount,dllRuntime] = ...
        local_physical_jacobian(contract,anchor,anchorName)
dllCount = 0;
dllRuntime = 0;
% 当选中的是确定性锚点且方法A合同完全相同时，物理
% 残差Jacobian与似然协方差无关，可直接复用。
if contract.modelMode~=0 && anchorName == "deterministic_estimate"
    try
        manifestA = sht_steady_model_uq_io('resolve', ...
            struct('runId',contract.config.methodAReferenceRunId));
        step1A = sht_steady_model_uq_io('loadstep',manifestA,1);
        step5A = sht_steady_model_uq_io('loadstep',manifestA,5);
        if strcmp(step1A.contract.contractHash,contract.baseContractHash) && ...
                isequal(size(step5A.jacobian), ...
                [contract.observationDimension,contract.parameterCount]) && ...
                norm(anchor-contract.thetaHat) <= 1e-14
            jacobian = step5A.jacobian;
            step = step5A.differenceStep;
            retryCount = step5A.differenceRetryCount;
            source = ['reused_method_a_run_' ...
                contract.config.methodAReferenceRunId];
            return;
        end
    catch exception
        warning('SHT:SteadyUQC:JacobianReuseFailed', ...
            '方法A Jacobian未能复用，将执行方法C中心差分：%s', ...
            exception.message);
    end
end
source = 'method_c_exact_central_difference';
step = contract.parameterTable.difference_step;
margin = min(anchor-contract.lowerBound,contract.upperBound-anchor);
step = min(step,0.20*margin);
if any(step <= 0)
    error('SHT:SteadyUQC:AnchorAtBoundary', ...
        '提议锚点位于硬边界，无法执行中心差分。');
end
retryCount = zeros(contract.parameterCount,1);
for retry = 0:7
    candidate = repmat(anchor,1,1+2*contract.parameterCount);
    for j = 1:contract.parameterCount
        candidate(j,2*j) = candidate(j,2*j)+step(j);
        candidate(j,2*j+1) = candidate(j,2*j+1)-step(j);
    end
    exact = sht_steady_model_uq_c_common('evaluate',contract,candidate, ...
        contract.trainingData,struct('useCache',contract.config.useCache));
    dllCount = dllCount+exact.dllEvaluationCount;
    dllRuntime = dllRuntime+exact.dllRuntime_s;
    failed = false(contract.parameterCount,1);
    for j = 1:contract.parameterCount
        failed(j) = ~(exact.valid(2*j) && exact.valid(2*j+1));
    end
    if exact.valid(1) && ~any(failed), break; end
    if ~exact.valid(1)
        error('SHT:SteadyUQC:GeometryAnchorInvalid', ...
            '方法C提议锚点精确回放无效。');
    end
    step(failed) = 0.5*step(failed);
    retryCount(failed) = retryCount(failed)+1;
end
if any(failed)
    error('SHT:SteadyUQC:GeometryDifferenceInvalid', ...
        '缩小步长后仍有%d个显式参数无法中心差分。',nnz(failed));
end
jacobian = zeros(contract.observationDimension,contract.parameterCount);
for j = 1:contract.parameterCount
    jacobian(:,j) = (exact.residual(:,2*j)- ...
        exact.residual(:,2*j+1))/(2*step(j));
end
end

function [transform,latent] = local_prior_latent_jacobian(prior,theta)
latent = sht_steady_model_uq_sampler('thetatolatent',prior,theta);
correlatedLatent = prior.cholCorrelation*latent;
zMarginal = (theta-prior.mean)./prior.sigma;
phiCorrelated = exp(-0.5*correlatedLatent.^2)/sqrt(2*pi);
phiMarginal = max(exp(-0.5*zMarginal.^2)/sqrt(2*pi),realmin);
diagonal = prior.sigma.*prior.normalization.*phiCorrelated./phiMarginal;
transform = diag(diagonal)*prior.cholCorrelation;
end

function local_plot_singular_values(result,contract,manifest)
figureHandle = figure('Visible',contract.config.figureVisible, ...
    'Name','Method C prior-scaled information singular values', ...
    'Position',[100,100,1150,720]);
subplot(2,1,1);
semilogy(result.globalSingularValue,'o-','LineWidth',1.0); hold on;
yline(1,'--','\sigma=1'); grid on;
xlabel('方向序号'); ylabel('奇异值');
title('全局50维先验尺度信息奇异值');
subplot(2,1,2); hold on;
style = {'o-','s-','^-','d-'};
for k = 1:4
    semilogy(result.blockSingularValue{k},style{k},'LineWidth',1.0);
end
yline(1,'--','\sigma=1'); grid on;
xlabel('块内方向序号'); ylabel('奇异值');
legend({'压气机+燃烧室','燃气涡轮','涵道+动力涡轮+喷管', ...
    '燃油偏置','\sigma=1'},'Location','best');
title('四个物理块的先验尺度信息奇异值');
saveas(figureHandle,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC03_information_singular_values.png'));
close(figureHandle);
end
