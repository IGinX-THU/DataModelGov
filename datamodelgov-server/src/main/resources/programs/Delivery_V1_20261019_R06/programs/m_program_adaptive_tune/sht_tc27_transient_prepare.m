function output=sht_tc27_transient_prepare(action,request)
%SHT_TC27_TRANSIENT_PREPARE 独立瞬态输入、物理身份和事件范围准备。
% prepare只使用测量Excel和模型元数据，不打开DLL。verify重新核对来源身份。
assert(isstruct(request)&&isscalar(request),'TC27:TransientUI:Request','请求须为标量结构体。');
required={'steadyModelFile','trainingHistoryFile','outputDirectory'};
for j=1:numel(required)
    assert(isfield(request,required{j})&&~isempty(request.(required{j})), ...
        'TC27:TransientUI:Required','缺少%s。',required{j});
end
modelFile=local_file(request.steadyModelFile);
trainFile=local_file(request.trainingHistoryFile);
directory=sht_tc27_canonical_path(request.outputDirectory);
assert(isfolder(fileparts(directory)),'TC27:TransientUI:Parent','输出目录的父目录不存在。');
assert(~strcmpi(directory,fileparts(modelFile))&&~strcmpi(directory,fileparts(trainFile)), ...
    'TC27:TransientUI:Output','输出不得与输入目录相同。');
testFiles=local_value(request,'testHistoryFiles',{});
assert(iscell(testFiles),'TC27:TransientUI:Tests','测试文件须为路径cell列表。');
for j=1:numel(testFiles),testFiles{j}=local_file(testFiles{j});end
assert(~any(strcmpi(trainFile,testFiles)),'TC27:TransientUI:Tests','训练记录不能兼作测试。');
model=sht_tc27_delivery('read',[],modelFile);
assert(model.modelMode==0&&model.thermalMode==3, ...
    'TC27:TransientUI:Model','仅接受三部件Visser的TC27正式稳态Excel。');
sidecar=fullfile(fileparts(modelFile),[local_stem(modelFile),'_identity.json']);
assert(isfile(sidecar),'TC27:TransientUI:Identity','稳态模型缺少独立身份JSON。');
identityFile=jsondecode(fileread(sidecar));
assert(isempty(local_value(request,'sourceRuntimeDirectory','')), ...
    'TC27:TransientUI:SourceRuntime', ...
    '瞬态辨识只有一套与父模型匹配的运行包；不接受sourceRuntimeDirectory。');
selection=local_value(request,'runtimeDirectory','selected');
assert((ischar(selection)&&isrow(selection))||(isstring(selection)&&isscalar(selection)), ...
    'TC27:TransientUI:Runtime','runtimeDirectory必须为目录路径或selected/legacy。');
package=sht_tc27_runtime_package(selection);
assert(strcmpi(identityFile.modelSHA256,model.sha256)&& ...
    strcmp(identityFile.runtimePackageId,package.id)&& ...
    identityFile.modelMode==0&&identityFile.thermalMode==3, ...
    'TC27:TransientUI:Runtime','稳态模型与当前三部件物理包不一致。');
assert(strcmpi(identityFile.thermalSHA256,sht_tc27_file_identity(package.thermalFile)), ...
    'TC27:TransientUI:Thermal','稳态模型与当前Visser热资产不一致。');
dll=fullfile(package.directory,'GTESS.dll');
assert(strcmpi(identityFile.dllSHA256,sht_tc27_file_identity(dll)), ...
    'TC27:TransientUI:DLL','稳态模型与当前DLL不一致。');
mode=char(local_value(request,'selectionMode','automatic'));
ranges=local_value(request,'eventRanges_s',zeros(0,2));
assert(ismember(mode,{'automatic','manual'})&&isnumeric(ranges)&&size(ranges,2)==2&& ...
    all(isfinite(ranges(:)))&&all(ranges(:,2)>ranges(:,1)), ...
    'TC27:TransientUI:Ranges','选段方式或起止时间草稿无效。');
if strcmp(mode,'manual')
    assert(~isempty(ranges),'TC27:TransientUI:Ranges','人工模式需提供起止时间草稿。');
else
    assert(isempty(ranges),'TC27:TransientUI:Ranges','自动模式不得暗含人工范围。');
end
screen=local_value(request,'screeningOptions',struct());
assert(isstruct(screen)&&isscalar(screen),'TC27:TransientUI:Screen','筛选配置须为结构体。');
warmup=local_value(request,'localWarmup_s',60);
validateattributes(warmup,{'numeric'},{'scalar','finite','nonnegative'});
assert(warmup<=60,'TC27:TransientUI:Warmup','本轮准备历史最长为60秒。');
fitOptions=local_value(request,'estimationOptions',struct());
assert(isstruct(fitOptions)&&isscalar(fitOptions), ...
    'TC27:TransientUI:Options','估计配置须为标量结构体。');
maximumIterations=local_value(fitOptions,'maxIterations',6);
validateattributes(maximumIterations,{'numeric'},{'scalar','integer','finite','nonnegative'});
integrationStep=local_value(fitOptions,'integrationStep_s',.1);
validationStep=local_value(fitOptions,'validationIntegrationStep_s',.025);
assert(ismember(integrationStep,[.1,.025])&&ismember(validationStep,[.1,.025]), ...
    'TC27:TransientUI:Step','积分步长只允许0.1或0.025秒。');
input=struct('steadyModelFile',modelFile,'steadyModelSHA256',model.sha256, ...
    'steadyIdentityFile',sidecar,'steadyIdentitySHA256',sht_tc27_file_identity(sidecar), ...
    'trainingHistoryFile',trainFile,'trainingHistorySHA256',sht_tc27_file_identity(trainFile), ...
    'testHistoryFiles',{testFiles},'testSHA256',{cellfun(@sht_tc27_file_identity, ...
    testFiles,'UniformOutput',false)},'runtimePackageId',package.id, ...
    'runtimeManifestSHA256',sht_tc27_file_identity(package.manifestFile), ...
    'runtimeDirectory',package.directory, ...
    'selectionMode',mode,'eventRanges_s',ranges,'screeningOptions',screen, ...
    'localWarmup_s',warmup);
input.preparationCode=local_code_identity(fileparts(mfilename('fullpath')));
raw=readtable(trainFile);
assert(ismember('Time_s',raw.Properties.VariableNames),'TC27:TransientUI:Time','缺少Time_s。');
duration=raw.Time_s(end)-raw.Time_s(1);
testTables=cell(numel(testFiles),1);testDuration=0;
for j=1:numel(testFiles)
    testTables{j}=readtable(testFiles{j});
    assert(ismember('Time_s',testTables{j}.Properties.VariableNames), ...
        'TC27:TransientUI:Time','测试数据缺少Time_s。');
    testDuration=testDuration+testTables{j}.Time_s(end)-testTables{j}.Time_s(1);
end
before=local_estimate(duration,0,1,testDuration,maximumIterations, ...
    integrationStep,validationStep,'raw_length_before_selection');
preparedFile=fullfile(directory,'MiddleData','tc27_transient_prepared.mat');
selectionFile=fullfile(directory,'report_outputs','tc27_transient_selected_ranges.json');
output=struct('input',input,'model',model,'package',package, ...
    'outputDirectory',directory,'preparedFile',preparedFile, ...
    'selectionFile',selectionFile,'estimatedBefore',before);
if strcmp(action,'inspect'),return;end
if strcmp(action,'verify')
    assert(isfile(preparedFile),'TC27:TransientUI:MissingPreparation','未找到本任务选段准备。');
    saved=load(preparedFile,'identity','result');
    assert(isequaln(saved.identity,input),'TC27:TransientUI:StalePreparation', ...
        '模型、数据、物理包或选段配置改变，不得复用准备结果。');
    assert(isequaln(saved.result.train.data,raw), ...
        'TC27:TransientUI:StalePreparation','训练测量记录与准备结果不同。');
    output.prepared=saved.result;
    output.selection=saved.result.selection;
    assert(isfile(selectionFile),'TC27:TransientUI:SelectionFile', ...
        '准备结果缺少已确认范围JSON，不能复用。');
    selection=saved.result.selection;
    integration=sum(selection.integrationEnd_s-selection.integrationStart_s);
    output.estimatedAfter=local_estimate(duration,integration,height(selection), ...
        testDuration,maximumIterations,integrationStep,validationStep, ...
        'confirmed_event_selection');
    return;
end
assert(strcmp(action,'prepare'),'TC27:TransientUI:Action','未知准备操作。');
assert(~isfile(preparedFile),'TC27:TransientUI:Exists','准备文件已经存在；请核对身份后复用。');
assert(~isfile(selectionFile),'TC27:TransientUI:Exists','范围JSON已经存在，不得覆盖。');
record=sht_tc27_segment_history(raw,screen,'train');
if strcmp(mode,'manual')
    record.diagnostic.eventFitMask=local_manual_mask(record,ranges);
end
plan=sht_tc27_transient_plan(record,'event_windows');
[plan,localPlan]=sht_tc27_local_history_plan(plan,warmup);
selection=local_selection(record,plan,localPlan);
testRecords=struct([]);testSources=struct('file',{},'sha256',{});
for j=1:numel(testFiles)
    r=sht_tc27_segment_history(testTables{j},screen,sprintf('test%02d',j));
    if isempty(testRecords),testRecords=r;else,testRecords(end+1)=r;end %#ok<AGROW>
    testSources(end+1)=struct('file',testFiles{j},'sha256',input.testSHA256{j}); %#ok<AGROW>
end
integration=sum(selection.integrationEnd_s-selection.integrationStart_s);
after=local_estimate(duration,integration,height(selection),testDuration, ...
    maximumIterations,integrationStep,validationStep,'confirmed_event_selection');
result=struct('schema','TC27_TRANSIENT_PREPARED_V1','train',record, ...
    'testRecords',testRecords,'testFiles',testSources,'selection',selection, ...
    'selectionFile',selectionFile,'estimatedBefore',before,'estimatedTime',after, ...
    'inputFiles',struct('trainingHistory',trainFile, ...
    'trainingHistorySHA256',input.trainingHistorySHA256, ...
    'steadyModel',modelFile,'steadyModelSHA256',model.sha256));
middle=fileparts(preparedFile);if ~isfolder(middle),mkdir(middle);end
folder=fileparts(selectionFile);if ~isfolder(folder),mkdir(folder);end
recordIndex=struct('schema','TC27_TRANSIENT_SELECTION_V1', ...
    'trainingFileSHA256',input.trainingHistorySHA256, ...
    'selectionMode',mode,'ranges',table2struct(selection), ...
    'fitRecords',sum(selection.fitSamples), ...
    'integrationRecords',sum(selection.integrationSamples), ...
    'preparationPolicy','independent_local_equilibrium_then_measured_history');
fid=fopen(selectionFile,'w','n','UTF-8');
assert(fid>=0,'TC27:TransientUI:SelectionFile','无法写入选段范围JSON。');
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(recordIndex));clear cleanup;
identity=input;save(preparedFile,'result','identity','-v7.3');
output.prepared=result;output.selection=selection;output.estimatedAfter=after;
end

function mask=local_manual_mask(record,ranges)
t=record.data.Time_s;d=record.diagnostic;mask=false(numel(t),1);
dt=d.sampleTime_s;
for j=1:size(ranges,1)
    [left,a]=min(abs(t-ranges(j,1)));[right,b]=min(abs(t-ranges(j,2)));
    assert(left<=dt/2+1e-8&&right<=dt/2+1e-8&&a<b, ...
        'TC27:TransientUI:Grid','人工边界必须落在实际采样记录上。');
    assert(all(d.qualityMask(a:b))&&numel(unique(d.continuousBlock(a:b)))==1, ...
        'TC27:TransientUI:Gap','人工窗口不可跨缺测或不连续记录块。');
    mask(a:b)=true;
end
end

function selection=local_selection(record,plan,localPlan)
t=record.data.Time_s;selection=table();
for j=1:numel(plan)
    fit=plan(j).data.Time_s;
    [~,first]=min(abs(t-fit(1)));[~,last]=min(abs(t-fit(end)));
    selection=[selection;table(string(plan(j).id),first,last,first+1,last+1, ...
        fit(1),fit(end),localPlan.initializationStart_s(j), ...
        plan(j).replayData.Time_s(end),height(plan(j).data), ...
        height(plan(j).replayData),record.diagnostic.continuousBlock(first), ...
        'VariableNames',{'eventId','firstRecordRow','lastRecordRow', ...
        'firstExcelRow','lastExcelRow','fitStart_s','fitEnd_s', ...
        'integrationStart_s','integrationEnd_s','fitSamples','integrationSamples', ...
        'continuousBlock'})]; %#ok<AGROW>
end
end

function estimate=local_estimate(rawSeconds,integrationSeconds,eventCount,testSeconds, ...
    maximumIterations,integrationStep,validationStep,stage)
% R021: 480秒训练+240秒测试、13参数、3次有效移动耗时2004.729秒。
% 新交付另需两次训练回放（零瞬态基线及最终估计）；仅作粗略增量。
if integrationSeconds<=0,integrationSeconds=rawSeconds;end
% 只有积分相关的75%按步长缩放，热平衡、文件及调度开销保留原成本。
trainStepFactor=.25+.75*(.1/integrationStep);
testStepFactor=.25+.75*(.025/validationStep);
work=(max(integrationSeconds,1)/480)*trainStepFactor+ ...
    (max(testSeconds,0)/240)*.10*testStepFactor;
work=work+max(0,eventCount-1)*.12;
expectedIterations=min(maximumIterations,3);
deliveryReplays=2;
centerFactor=(15+13*(expectedIterations+1)+deliveryReplays)/(15+13*4);
maximumFactor=(15+13*(maximumIterations+1)+deliveryReplays)/(15+13*4);
center=max(60,2004.729*work*centerFactor);
estimate=struct('status','rough_numeric','stage',stage, ...
    'seconds',center,'lowerSeconds',max(30,.35*center), ...
    'upperSeconds',3*max(center,2004.729*work*maximumFactor), ...
    'center_s',center,'lower_s',max(30,.35*center), ...
    'upper_s',3*max(center,2004.729*work*maximumFactor), ...
    'baselineVersion','TC27_R021_2004p729s_v4', ...
    'baselineTrain_s',480,'baselineTest_s',240, ...
    'assumedAcceptedMoves',expectedIterations, ...
    'configuredMaximumIterations',maximumIterations,'candidateDimension',13, ...
    'additionalTrainingDeliveryReplays',deliveryReplays, ...
    'integrationStep_s',integrationStep, ...
    'validationIntegrationStep_s',validationStep, ...
    'integrationCostFraction',.75, ...
    'available',true,'modelVersion','TC27_TRANSIENT_FIXED_WORK_V4_20261005', ...
    'benchmarkEnvironment','Windows x64, R2019b, TC27本项目开发机及VC2010 DLL', ...
    'hardwareLimitation','原报告未冻结CPU型号及后台负载，不保证跨机耗时', ...
    'scope','瞬态系数辨识及训练/测试回放和组合Excel，不含父稳态模型辨识', ...
    'intervalMeaning','工程范围，非概率置信区间或强制停止条件', ...
    'coldFullReferenceSeconds',center,'remainingResolved',false,'remainingSeconds',NaN, ...
    'assumption','同类VC2010 DLL；仅积分成本随步长改变，热平衡与重试不确定，范围不作完成承诺');
end

function value=local_value(s,name,fallback)
value=fallback;if isfield(s,name)&&~isempty(s.(name)),value=s.(name);end
end
function file=local_file(value)
file=sht_tc27_canonical_path(value);
assert(isfile(file),'TC27:TransientUI:File','输入文件不存在：%s',file);
end
function stem=local_stem(file)
[~,stem]=fileparts(file);
end
function entries=local_code_identity(root)
names={'sht_tc27_transient_prepare.m','sht_tc27_segment_history.m', ...
    'sht_tc27_transient_plan.m','sht_tc27_local_history_plan.m'};
entries=cell(numel(names),2);
for j=1:numel(names)
    entries{j,1}=names{j};
    entries{j,2}=sht_tc27_file_identity(fullfile(root,names{j}));
end
end
