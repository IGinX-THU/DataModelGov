function quality = sht_f31_quality_metrics( ...
        simulationOrLog, mission, designNp, designPower, thermalEquilibrium)
%SHT_F31_QUALITY_METRICS 验收3.1第二轮长航线仿真质量。
%
% 验收对象包括：样本与状态维数、DLL共同工作收敛、Visser能量闭合、
% 飞行边界真正写入DLL、总距与边界时序对齐、初始热平衡稳定性以及
% 动力涡轮转速调节误差。阈值用于识别程序或数值故障，不把正常的动态
% 转速偏差误判为计算失败。

if isstruct(simulationOrLog) && isfield(simulationOrLog,'log')
    log = simulationOrLog.log;
else
    log = simulationOrLog;
end

required = {'time','xEngine','Np','Ng','Wf','Mkp','Mkg','Pt1','Tt1', ...
    'Pt2','Pt3','Tt3','Pt45','Tt45','Pamb','Pload','maxErr', ...
    'convergeTag','evaluationValid','visserNormalizedEnergyResidual', ...
    'flightAltitude','flightMach','flightPt1','flightTt1','flightPamb', ...
    'flightPback','flightPbackCommand','flightDeltaPExhaust', ...
    'flightInletBoundaryMode', ...
    'thetaCollectiveDeg','thetaTailDeg','mainRotorPower','tailRotorPower', ...
    'tailLoadFactor','reynoldsIndex','reynoldsFlowMultiplier', ...
    'reynoldsEfficiencyMultiplier'};
missing = required(~isfield(log,required));
if ~isempty(missing)
    error('SHT:F31Quality:MissingLogField', ...
        '3.1质量验收缺少日志字段：%s。',strjoin(missing,', '));
end

sampleCount = numel(log.time);
allFinite = all(isfinite(log.xEngine(:)));
for i = 1:numel(required)
    value = log.(required{i});
    if isnumeric(value)
        allFinite = allFinite && all(isfinite(value(:)));
    end
end

% 飞行边界在Heun预测点和校正后的k+1端点都会按t_{k+1}刷新，日志也
% 保存该端点边界，因此这里应与同一时刻任务值直接比较。2.6非飞行总距
% 日志采用积分区间起点，存在一拍对齐约定，二者不能混用。
expectedAltitude = mission.altitude_m(:);
expectedMach = mission.mach(:);
expectedTheta = mission.theta_cmd_deg(:);
expectedTailTheta = mission.tail_pitch_cmd_deg(:);
initialEnd_s = min(mission.duration_s,mission.segment.end_s(1));
initialMask = mission.time_s <= initialEnd_s + 1e-12;
tailMask = initialMask & mission.time_s >= initialEnd_s - 5;
thermal = log.xEngine(:,3:end);
initialThermalExcursion = max(abs(thermal(initialMask,:) - thermal(1,:)),[],'all');
tailThermal = thermal(tailMask,:);
tailThermalExcursion = max(abs(tailThermal - tailThermal(1,:)),[],'all');
% 带测量噪声的闭环会产生真实温度波动。均值漂移用于判断热恢复，
% 单点最大波动仍完整保留；原入口不指定时继续使用原检查方式。
thermalCheckMode='sample_excursion';
if isfield(mission,'initialThermalCheckMode')
    thermalCheckMode=mission.initialThermalCheckMode;
end
meanWindow_s=min(5,initialEnd_s/2);
priorMask=mission.time_s>=initialEnd_s-2*meanWindow_s & ...
    mission.time_s<initialEnd_s-meanWindow_s;
lastMask=mission.time_s>=initialEnd_s-meanWindow_s & mission.time_s<=initialEnd_s;
meanDrift=max(abs(mean(thermal(lastMask,:),1)-mean(thermal(priorMask,:),1)));

pt1RelativeError = abs(log.Pt1(:)-log.flightPt1(:))./max(abs(log.flightPt1(:)),1);
pambRelativeError = abs(log.Pamb(:)-log.flightPamb(:))./max(abs(log.flightPamb(:)),1);
pbackRelativeError = abs(log.flightPback(:)-log.flightPbackCommand(:))./ ...
    max(abs(log.flightPbackCommand(:)),1);
rotorPowerClosureRelativeError = abs( ...
    log.Pload(:)-log.mainRotorPower(:)-log.tailRotorPower(:))./ ...
    max(abs(log.Pload(:)),1);
npRelativeError = abs(log.Np(:)-designNp)/designNp;

quality = struct();
quality.schemaVersion = 'F31_QUALITY_V3';
quality.sampleCount = sampleCount;
quality.expectedSampleCount = mission.sampleCount;
quality.stateCount = size(log.xEngine,2);
quality.allFinite = allFinite;
quality.allConverged = all(log.convergeTag(:)==0);
quality.allEvaluationValid = all(log.evaluationValid(:)==1);
quality.maximumCommonWorkResidual = max(abs(log.maxErr(:)));
quality.maximumNormalizedEnergyResidual = ...
    max(abs(log.visserNormalizedEnergyResidual(:)));
quality.maximumAltitudeAlignmentError_m = ...
    max(abs(log.flightAltitude(:)-expectedAltitude));
quality.maximumMachAlignmentError = ...
    max(abs(log.flightMach(:)-expectedMach));
quality.maximumThetaAppliedAlignmentError_deg = ...
    max(abs(log.thetaCollectiveDeg(:)-expectedTheta));
quality.maximumTailPitchAppliedAlignmentError_deg = ...
    max(abs(log.thetaTailDeg(:)-expectedTailTheta));
quality.maximumPt1BoundaryRelativeError = max(pt1RelativeError);
quality.maximumTt1BoundaryError_K = max(abs(log.Tt1(:)-log.flightTt1(:)));
% 间隙调度辅助总温必须与C端当前实际总温一致，不能退回参考表默认值。
quality.maximumClearanceTemperatureError_K = ...
    max(abs(log.Tt1(:)-log.flightExpectedTt1(:)));
quality.maximumPambBoundaryRelativeError = max(pambRelativeError);
quality.maximumPbackBoundaryRelativeError = max(pbackRelativeError);
quality.inletBoundaryModes = unique(log.flightInletBoundaryMode(:)).';
quality.maximumRotorPowerClosureRelativeError = ...
    max(rotorPowerClosureRelativeError);
quality.minimumExhaustPressureRise_Pa = ...
    min(log.flightPback(:)-log.flightPamb(:));
quality.maximumExhaustPressureRise_Pa = ...
    max(log.flightPback(:)-log.flightPamb(:));
quality.reynoldsIndexRange = [min(log.reynoldsIndex,[],1); ...
    max(log.reynoldsIndex,[],1)];
quality.reynoldsFlowMultiplierRange = ...
    [min(log.reynoldsFlowMultiplier,[],1); ...
    max(log.reynoldsFlowMultiplier,[],1)];
quality.reynoldsEfficiencyMultiplierRange = ...
    [min(log.reynoldsEfficiencyMultiplier,[],1); ...
    max(log.reynoldsEfficiencyMultiplier,[],1)];
quality.maximumNpRegulationErrorPct = 100*max(npRelativeError);
quality.rmsNpRegulationErrorPct = 100*sqrt(mean(npRelativeError.^2));
quality.initialHoldMaximumThermalExcursion_K = initialThermalExcursion;
quality.initialHoldTailMaximumThermalExcursion_K = tailThermalExcursion;
quality.initialHoldTailMeanDrift_K=meanDrift;
quality.initialThermalCheckMode=thermalCheckMode;
quality.initialThermalEquilibriumResidual_Kps = ...
    thermalEquilibrium.finalMaximumDerivative_Kps;
quality.actualNprRange = [min(log.Np/designNp),max(log.Np/designNp)];
quality.actualLoadPowerRatioRange = ...
    [min(log.Pload/designPower),max(log.Pload/designPower)];
quality.actualAltitudeRange_m = [min(log.flightAltitude),max(log.flightAltitude)];
quality.actualMachRange = [min(log.flightMach),max(log.flightMach)];
quality.actualThetaRange_deg = ...
    [min(log.thetaCollectiveDeg),max(log.thetaCollectiveDeg)];
quality.protectionSelectionCount = struct( ...
    'Tt45',nnz(log.t45ProtectionSelected), ...
    'Mkp',nnz(log.mkpProtectionSelected), ...
    'NgTop',nnz(log.ngTopProtectionSelected), ...
    'accel',nnz(log.accelLimitSelected), ...
    'decel',nnz(log.decelLimitSelected));

checks = struct();
checks.sampleCount = quality.sampleCount==quality.expectedSampleCount;
expectedStateCount=29;
if isfield(mission,'expectedStateCount'),expectedStateCount=mission.expectedStateCount;end
checks.stateCount = quality.stateCount==expectedStateCount;
checks.finite = quality.allFinite;
checks.convergence = quality.allConverged && quality.allEvaluationValid;
checks.commonWorkResidual = quality.maximumCommonWorkResidual<=1e-5;
checks.energyResidual = quality.maximumNormalizedEnergyResidual<=1e-10;
checks.clearanceTemperature = quality.maximumClearanceTemperatureError_K<=0.02;
checks.scheduleAlignment = ...
    quality.maximumAltitudeAlignmentError_m<=1e-8 && ...
    quality.maximumMachAlignmentError<=1e-10 && ...
    quality.maximumThetaAppliedAlignmentError_deg<=1e-8 && ...
    quality.maximumTailPitchAppliedAlignmentError_deg<=1e-8;
checks.boundaryApplied = ...
    all(log.flightInletBoundaryMode(:)==2) && ...
    quality.maximumPt1BoundaryRelativeError<=1e-10 && ...
    quality.maximumTt1BoundaryError_K<=1e-8 && ...
    quality.maximumPambBoundaryRelativeError<=1e-10 && ...
    quality.maximumPbackBoundaryRelativeError<=1e-10;
checks.installedEffects = ...
    quality.minimumExhaustPressureRise_Pa>=-1e-8 && ...
    quality.maximumExhaustPressureRise_Pa>=-1e-8 && ...
    quality.maximumRotorPowerClosureRelativeError<=1e-12 && ...
    all(isfinite(quality.reynoldsIndexRange),'all') && ...
    all(quality.reynoldsIndexRange>0,'all') && ...
    all(quality.reynoldsFlowMultiplierRange>0,'all') && ...
    all(quality.reynoldsEfficiencyMultiplierRange>0,'all');
checks.initialThermalEquilibrium = ...
    quality.initialThermalEquilibriumResidual_Kps<=1e-6 && ...
    quality.initialHoldTailMaximumThermalExcursion_K<=1.0;
if strcmp(thermalCheckMode,'window_mean_drift')
    checks.initialThermalEquilibrium= ...
        quality.initialThermalEquilibriumResidual_Kps<=1e-6 && ...
        isfinite(meanDrift) && meanDrift<=1.0;
else
    assert(strcmp(thermalCheckMode,'sample_excursion'),'未知初始热稳定性检查方式。');
end
checks.speedRegulation = quality.maximumNpRegulationErrorPct<=5.0;
quality.checks = checks;
checkNames = fieldnames(checks);
failed = checkNames(~cellfun(@(name)checks.(name),checkNames));
quality.failedChecks = failed;
quality.passed = isempty(failed);
end
