function result = Start_SteadyModelUQ_B_04_AnalyticMeasurementUncertainty(userCfg)
%START_STEADYMODELUQ_B_04_ANALYTICMEASUREMENTUNCERTAINTY 冻结B误差协方差。
if nargin < 1, userCfg = struct(); end
timer = tic;
manifest = sht_steady_model_uq_b_io('resolvewritable',userCfg);
step1 = sht_steady_model_uq_b_io('loadstep',manifest,1);
contract = step1.contract;
inputUncertainty = sht_steady_model_uq_b_common( ...
    'inputcovariance',contract);
measurement = sht_steady_model_uq_b_common( ...
    'measurementcovariance',contract,inputUncertainty);
selected = measurement.selected;
roleContract = sht_steady_model_uq_b_common( ...
    'routecontract',contract.route,contract.config.modelMode);
rolePassed = isequal(inputUncertainty.stateInputSensors, ...
    roleContract.stateInputSensors) && ...
    isequal(measurement.directOutputSensors, ...
    roleContract.directOutputSensors) && ...
    isempty(measurement.inputOutputSensorOverlap) && ...
    ~inputUncertainty.inputFlowDriftPropagated;
symmetryError = norm(selected.covariance-selected.covariance.','fro') / ...
    max(norm(selected.covariance,'fro'),eps);
passed = rolePassed && symmetryError < 1e-12 && ...
    all(diag(selected.covariance)>0) && ...
    selected.jitter < 1e-6*mean(diag(selected.covariance)) && ...
    ~inputUncertainty.methodAPosteriorUsed;
if ~passed
    error('SHT:SteadyUQB:MeasurementCovarianceAcceptanceFailed', ...
        '方法B误差协方差验收失败：symmetry=%.3e，jitter=%.3e。', ...
        symmetryError,selected.jitter);
end
result = struct('inputUncertainty',inputUncertainty, ...
    'measurement',measurement,'relativeSymmetryError',symmetryError, ...
    'roleContract',roleContract,'roleContractPassed',rolePassed, ...
    'passed',passed,'truthRead',false,'testDataRead',false);
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_b_io( ...
    'savestep',manifest,4,'analytic_measurement_uncertainty',result,runtime);
step3 = sht_steady_model_uq_b_io('loadstep',manifest,3);
standardDeviation = sqrt(diag(selected.covariance));
uncertaintyTable = table(step3.label,step3.unit,standardDeviation, ...
    'VariableNames',{'label','unit','total_standard_deviation'});
writetable(uncertaintyTable,sht_steady_model_uq_b_io( ...
    'reportfile',manifest,'UQB04_observation_standard_deviation.csv'));
scale = sqrt(diag(selected.covariance));
correlation = selected.covariance./max(scale*scale.',eps);
figureFile=sht_steady_model_uq_b_io('reportfile',manifest,'UQB04_measurement_correlation.png');
result.plotAudit=sht_steady_model_uq_common('optionalplot',contract.config, ...
    @()local_plot(correlation,contract.config.figureVisible,figureFile));
plotAudit=result.plotAudit; %#ok<NASGU>
save(sht_steady_model_uq_b_io('runfile',manifest,'step04_plot_audit.mat'),'plotAudit');
fprintf('[2.4UQ-B.4] 协方差完成：情景=%s，jitter=%.3e。\n', ...
    measurement.selectedName,selected.jitter);
fprintf('[2.4UQ-B.4] 产物：%s\n',file);
result.manifest = manifest;
end

function local_plot(correlation,visible,file)
figureHandle = figure('Visible',visible,'Name','2.4 UQ method B covariance correlation');
imagesc(correlation,[-1,1]); axis image; colorbar;
title('方法B冻结误差相关矩阵'); xlabel('观测序号'); ylabel('观测序号');
saveas(figureHandle,file);
close(figureHandle);
end
