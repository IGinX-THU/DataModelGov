function result = Start_SteadyModelUQ_B_07_DefensiveProposalAdaptation(userCfg)
%START_STEADYMODELUQ_B_07_DEFENSIVEPROPOSALADAPTATION 冻结B自己的防御提议。
if nargin < 1, userCfg = struct(); end
timer = tic;
manifest = sht_steady_model_uq_b_io('resolvewritable',userCfg);
step1 = sht_steady_model_uq_b_io('loadstep',manifest,1);
step5 = sht_steady_model_uq_b_io('loadstep',manifest,5);
step6 = sht_steady_model_uq_b_io('loadstep',manifest,6);
preparationCodeIdentity=sht_tc24_uq_external_io('b','checkpreparationidentity', ...
    step5,'B05',step6,'B06');
assert(isfield(step6,'guidedProposal'),'TC24:UQ:PreparationIdentityMissing','B06缺少已校验的先导提议。');
sht_tc24_uq_external_io('b','checkpreparationidentity',step6.guidedProposal,'B06先导提议');
contract = step1.contract;
geometry = step6.samplingGeometry;
defaultLocalProposalFraction = local_option( ...
    contract.config,'proposalLocalFraction',0.45);
localProposalFraction = local_proposal_fraction(userCfg, ...
    'proposalLocalFraction',defaultLocalProposalFraction);
proposalOptions = struct('priorWeight',1-localProposalFraction, ...
    'informedScaleInflation',local_option(contract.config,'proposalInformedScaleInflation',.75));
proposal = sht_steady_model_uq_b_proposal( ...
    'build',step1.prior,geometry,proposalOptions);
proposal.preparationCodeIdentity=preparationCodeIdentity;
audit = sht_steady_model_uq_b_proposal('selftest',proposal,3000, ...
    contract.config.randomSeed+7001,'deterministic_mixture');
minimumInitialEssFraction = 0.45;
maximumNormalizationError = 0.15;
passed = audit.passed && ...
    audit.initialImportanceEssFraction>=minimumInitialEssFraction && ...
    abs(audit.logMeanPriorToProposalWeight)<=maximumNormalizationError;
if ~passed
    error('SHT:SteadyUQB:AdaptedProposalAuditFailed', ...
        ['方法B潜空间防御提议验收失败：ESS比例=%.3f，' ...
        'log E_q[p/q]=%.3f。'],audit.initialImportanceEssFraction, ...
        audit.logMeanPriorToProposalWeight);
end
scaleSource=local_option(contract.config,'pilotInitialScaleSource','final');
scaleInput=step6.medianFinalBlockScale;
if strcmp(scaleSource,'configured_start')
    % 两者都从beta=0的同一混合提议开始；使用起始配置，而非beta=1的末端尺度。
    % 这是单项候选。先导的覆盖/诊断仍保留，正式采样仍按旧B规则自适应。
    scaleInput=contract.config.initialPcnScale;
end
initialScale = min(max(scaleInput, ...
    contract.config.minimumPcnScale),contract.config.maximumPcnScale);
formalTargetEssFraction = local_fraction(userCfg, ...
    'smcFormalTargetEssFraction', ...
    contract.config.smcFormalTargetEssFraction);
formalMaximumStageCount = local_positive_integer(userCfg, ...
    'formalMaximumStageCount',contract.config.maximumStageCount);
formalMoveSweeps = local_positive_integer(userCfg, ...
    'formalMoveSweeps',contract.config.formalMoveSweeps);
% 维数来自当前合同；末级增加精确移动，以检验弱方向的宽度与矩稳定性。
formalFinalMoveSweeps = local_positive_integer(userCfg, ...
    'formalFinalMoveSweeps',contract.config.formalFinalMoveSweeps);
smcConfig = struct('targetEssFraction', ...
    formalTargetEssFraction, ...
    'initialPcnScale',initialScale,'moveSweeps',formalMoveSweeps, ...
    'finalMoveSweeps',formalFinalMoveSweeps, ...
    'maximumStageCount',formalMaximumStageCount, ...
    'kernelWeights',contract.config.kernelWeights, ...
    'minimumPcnScale',contract.config.minimumPcnScale, ...
    'maximumPcnScale',contract.config.maximumPcnScale, ...
    'targetAcceptance',contract.config.targetAcceptance, ...
    'blockIndex',{contract.samplingKernelIndex}, ...
    'blockBasis',{geometry.blockBasis}, ...
    'blockInformedRank',geometry.blockInformedRank, ...
    'globalBasis',geometry.globalBasis, ...
    'globalInformedRank',geometry.globalInformedRank, ...
    'blockNullScaleMultiplier',contract.config.blockNullScaleMultiplier, ...
    'maximumBlockNullScale',contract.config.maximumBlockNullScale, ...
    'globalNullScaleMultiplier',contract.config.globalNullScaleMultiplier, ...
    'maximumGlobalNullScale',contract.config.maximumGlobalNullScale, ...
    'globalPcnFraction',contract.config.globalPcnFraction, ...
    'globalNullOnlyFraction',local_option(contract.config,'globalNullOnlyFraction',0), ...
    'globalNullOnlyScale',local_option(contract.config,'globalNullOnlyScale',.35), ...
    'priorOnlyIndex',step5.structuralPriorOnlyParameterIndex, ...
    'initialProposalSamplingMode','deterministic_mixture', ...
    'deterministicKernelAllocation',true, ...
    'deterministicGuidedAllocation',true);
smcConfig.pcnGeometry=contract.config.pcnGeometry;
smcConfig.freezeFinalPcnScale=contract.config.freezeFinalPcnScale;
smcConfig.blockSingularValue=geometry.blockSingularValue;
smcConfig.globalSingularValue=geometry.globalSingularValue;
smcConfig.samplerProfile=contract.config.bSamplerProfile;
% 只在正式总体最后beta=1层学习并冻结参考；先导保持原V1行为。
smcConfig.finalReferenceMove=contract.config.finalReferenceMove;
names={'conditionalEssFraction','resampleEssFraction', ...
    'referenceShrinkage','referenceEigenvalueFloor'};
for k=1:numel(names),smcConfig.(names{k})=contract.config.(names{k});end
result = struct('proposal',proposal,'smcConfig',smcConfig, ...
    'proposalAudit',audit,'samplingGeometry',geometry, ...
    'configuredLocalProposalFraction',localProposalFraction, ...
    'singleGlobalPopulation',true, ...
    'deterministicMixtureAllocation',true, ...
    'minimumInitialEssFraction',minimumInitialEssFraction, ...
    'maximumNormalizationError',maximumNormalizationError, ...
    'pilotDiagnostic',step6.diagnostic,'passed',passed, ...
    'methodAPosteriorUsed',false,'truthRead',false,'testDataRead',false);
result.preparationCodeIdentity=preparationCodeIdentity;
sht_tc24_uq_external_io('b','checkpreparationidentity',result,'新计算的B07');
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_b_io( ...
    'savestep',manifest,7,'defensive_proposal_adaptation',result,runtime);
fprintf(['[2.4UQ-B.7] 潜空间防御提议冻结：分量=%d，先验/局部权重=%.2f/%.2f，' ...
    '初始重要性ESS比例=%.3f，正式五核初值=[%.3f %.3f %.3f %.3f %.3f]，' ...
    '层内/末级搬移=%d/%d。\n'], ...
    proposal.componentCount,proposal.priorWeight,proposal.localWeight, ...
    audit.initialImportanceEssFraction,initialScale, ...
    formalMoveSweeps,formalFinalMoveSweeps);
fprintf('[2.4UQ-B.7] 产物：%s\n',file);
result.manifest = manifest;
end

function value = local_positive_integer(options,name,defaultValue)
value = local_option(options,name,defaultValue);
if ~isscalar(value) || ~isnumeric(value) || ~isfinite(value) || ...
        value < 1 || value ~= floor(value)
    error('SHT:SteadyUQB:BadFormalInteger','%s必须为正整数。',name);
end
value = double(value);
end

function value = local_fraction(options,name,defaultValue)
value = local_option(options,name,defaultValue);
if ~isscalar(value) || ~isnumeric(value) || ~isfinite(value) || ...
        value <= 0 || value >= 1
    error('SHT:SteadyUQB:BadFormalFraction', ...
        '%s必须严格位于(0,1)。',name);
end
value = double(value);
end

function value = local_proposal_fraction(options,name,defaultValue)
value = local_option(options,name,defaultValue);
if ~isscalar(value) || ~isnumeric(value) || ~isfinite(value) || ...
        value <= 0 || value >= 1
    error('SHT:SteadyUQB:BadProposalLocalFraction', ...
        '%s必须严格位于(0,1)。',name);
end
value = double(value);
end

function value = local_option(options,name,defaultValue)
value = defaultValue;
if isstruct(options) && isfield(options,name) && ...
        ~isempty(options.(name))
    value = options.(name);
end
end
