function [flightData, validation] = sht_build_flight_data_package(input)
%SHT_BUILD_FLIGHT_DATA_PACKAGE 构造 3.1 飞参替代数据及隐藏验证真值。
%
% [flightData, validation] = sht_build_flight_data_package(input)
%
% 本函数只整理已经完成的 G01/C01 仿真，不调用 DLL，也不推进发动机
% 状态。输出严格分为两层：
%   estimationData  后续预处理和参数估计程序允许读取的飞参记录；
%   validationData  合成数据验证专用的健康真值、无误差输出和误差实现。
%
% 正式估计历程固定为 G01 健康真值运行和 C01 设计畸变健康真值运行。
% C01 清洁进气运行及 100 维零健康参考运行只进入 validationData。

local_require_fields(input, {'entryProgram','entryConfig','model', ...
    'missions','nominalReference','healthTruth','healthTruthTable'}, ...
    'input');
if ~isstruct(input) || ~isscalar(input) || ...
        ~isstruct(input.missions) || numel(input.missions) ~= 2 || ...
        ~isnumeric(input.healthTruth) || ...
        numel(input.healthTruth) ~= 100 || ...
        any(~isfinite(input.healthTruth(:))) || ...
        ~istable(input.healthTruthTable)
    error('sht:flightDataPackage:badInput', ...
        'S9 数据包需要两条任务、100 维有限健康真值及健康参数表。');
end

missions = input.missions(:);
if ~isequal({missions.id}, {'G01_GroundTakeoff','C01_AirCruise'})
    error('sht:flightDataPackage:badMissionOrder', ...
        '正式数据包必须按 G01、C01 顺序接收两条任务。');
end
local_require_fields(missions(1), {'simulationRun','definition'}, ...
    'missions(1)');
local_require_fields(missions(2), ...
    {'simulationRuns','distortionComparison','definition'}, 'missions(2)');
local_require_fields(missions(2).simulationRuns, {'clean','distorted'}, ...
    'missions(2).simulationRuns');
local_require_fields(input.nominalReference, {'ground','cruise'}, ...
    'input.nominalReference');

activeRuns = {missions(1).simulationRun; ...
    missions(2).simulationRuns.distorted};
nominalRuns = {input.nominalReference.ground; ...
    input.nominalReference.cruise};
missionIds = {'G01_GroundTakeoff'; 'C01_AirCruise'};

estimationHistories = repmat(local_estimation_history( ...
    activeRuns{1}), numel(activeRuns), 1);
truthHistories = repmat(local_truth_history(activeRuns{1}), ...
    numel(activeRuns), 1);
nominalHistories = repmat(local_nominal_history(nominalRuns{1}), ...
    numel(nominalRuns), 1);
for i = 1:numel(activeRuns)
    estimationHistories(i) = local_estimation_history(activeRuns{i});
    truthHistories(i) = local_truth_history(activeRuns{i});
    nominalHistories(i) = local_nominal_history(nominalRuns{i});
end

estimationData = struct();
estimationData.description = [ ...
    '第3.1阶段后续程序允许读取的两条飞参替代历程；不含健康真值、' ...
    '无误差发动机输出、传感器生成参数或装机边界误差真值。'];
estimationData.historyCount = numel(estimationHistories);
estimationData.histories = estimationHistories;
estimationData.measurementProfile = input.entryConfig.measurementProfile;
estimationData.sampleTime_s = input.entryConfig.sampleTime_s;

[healthEffectComparison, healthEffectPassed] = ...
    local_health_effect_comparison(activeRuns, nominalRuns, ...
    input.healthTruth(:));

validationData = struct();
validationData.description = ...
    '合成飞参数据验证专用隐藏区；参数估计主流程不得默认读取。';
validationData.truthHealth = input.healthTruth(:);
validationData.truth_health_parameters = input.healthTruth(:);
validationData.healthTruthTable = input.healthTruthTable;
validationData.truthHistories = truthHistories;
validationData.nominalHealthReference = nominalHistories;
validationData.healthEffectComparison = healthEffectComparison;
validationData.cruiseCleanReference = local_truth_history( ...
    missions(2).simulationRuns.clean);
validationData.cruiseDistortionComparison = ...
    missions(2).distortionComparison;
validationData.model = input.model;
validationData.randomSeeds = [activeRuns{1}.measurement.randomSeed; ...
    activeRuns{2}.measurement.randomSeed];

measurement = activeRuns{1}.measurement;
% 这些参数只是生成替代数据时使用的隐藏真值，不是真实飞参
% 自带的对象信息。后续建模程序不得从此处读取它们。
validationData.measurementGenerationTruth = struct( ...
    'enabled', measurement.enabled, ...
    'profile', measurement.profile, ...
    'pipeline', measurement.processingOrder, ...
    'configuration', measurement.config, ...
    'channelSpecification', measurement.specification);

flightData = struct();
flightData.schemaVersion = ...
    '3.1_flight_parameter_substitute_S9_v3_observation_only';
packageStage = '3.1-S9';
flightData.createdAt = datestr(now, 31);
flightData.dataSource = 'synthetic_flight_parameter_substitute';
flightData.shaftLoadInterfaceVersion = ...
    'Mkp_Mkg_external_torque_inputs_v2';
flightData.missionDefinition = [ ...
    local_public_mission_definition(missions(1)); ...
    local_public_mission_definition(missions(2))];
flightData.measurementProfile = input.entryConfig.measurementProfile;
flightData.estimationData = estimationData;
flightData.validationData = validationData;
flightData.observationMetadata = struct( ...
    'measurementProfile', input.entryConfig.measurementProfile, ...
    'channelCount', height(measurement.specification), ...
    'generationParametersIncluded', false, ...
    'measurementObjectParametersConfiguredInStage', '3.2');
flightData.fieldDictionary = local_field_dictionary( ...
    measurement.specification);
flightData.provenance = struct( ...
    'generator', input.entryProgram, ...
    'generatedAt', flightData.createdAt, ...
    'stage', packageStage, ...
    'modelStateNames', {input.model.stateNames}, ...
    'modelStateCount', input.model.stateCount, ...
    'transientEffectsEnabled', input.model.transientEffectsEnabled, ...
    'externalSecondaryAirEnabled', ...
        input.model.externalSecondaryAirEnabled, ...
    'healthTruthLocation', 'validationData only', ...
    'measurementGenerationTruthLocation', ...
        'validationData.measurementGenerationTruth only');
flightData.qualitySummary = local_quality_summary(activeRuns, missionIds);

forbiddenPaths = local_find_forbidden_paths(estimationData, ...
    'estimationData');
historyCountPassed = estimationData.historyCount == 2 && ...
    numel(estimationData.histories) == 2;
runValidationPassed = all(cellfun(@(run) run.validation.passed && ...
    run.measurement.validation.passed, activeRuns));
measurementChannelCountPassed = all(cellfun(@(run) ...
    height(run.measurement.specification) == 15, activeRuns));
timeAlignmentPassed = all(cellfun(@local_history_time_aligned, activeRuns));
truthIsolationPassed = isempty(forbiddenPaths);
measurementParameterIsolationPassed = ...
    ~isfield(estimationData, 'uncertaintyAssumptions') && ...
    isfield(validationData, 'measurementGenerationTruth');
validation = struct( ...
    'passed', historyCountPassed && runValidationPassed && ...
        measurementChannelCountPassed && timeAlignmentPassed && ...
        truthIsolationPassed && healthEffectPassed && ...
        measurementParameterIsolationPassed, ...
    'historyCountPassed', historyCountPassed, ...
    'runValidationPassed', runValidationPassed, ...
    'measurementChannelCountPassed', measurementChannelCountPassed, ...
    'timeAlignmentPassed', timeAlignmentPassed, ...
    'truthIsolationPassed', truthIsolationPassed, ...
    'healthEffectPassed', healthEffectPassed, ...
    'measurementParameterIsolationPassed', ...
        measurementParameterIsolationPassed, ...
    'uncertaintyRepeatStudyExecuted', false, ...
    'forbiddenEstimationFieldPaths', {forbiddenPaths});
flightData.qualitySummary.packageValidationPassed = repmat( ...
    validation.passed, height(flightData.qualitySummary), 1);

if ~validation.passed
    error('sht:flightDataPackage:validationFailed', ...
        ['3.1 数据包校验失败：history=%d，run=%d，channel=%d，' ...
         'time=%d，isolation=%d，healthEffect=%d，parameterIsolation=%d。'], ...
        historyCountPassed, runValidationPassed, ...
        measurementChannelCountPassed, timeAlignmentPassed, ...
        truthIsolationPassed, healthEffectPassed, ...
        measurementParameterIsolationPassed);
end
end

function history = local_estimation_history(run)
% 这里只摘取真实飞参或允许重构的输入，不复制任何 truth/error 字段。
local_require_fields(run, {'missionId','variantId','schedule', ...
    'measurement','validation'}, 'run');
measurement = run.measurement;
schedule = run.schedule;
channels = cellstr(string(measurement.specification.name));

measured = struct('time_s', measurement.measured.time_s(:));
for i = 1:numel(channels)
    name = channels{i};
    measured.(name) = measurement.measured.(name)(:);
end

history = struct();
history.missionId = run.missionId;
history.variantId = run.variantId;
history.experimentRole = 'flight_history';
history.sampleTime_s = median(diff(measurement.measured.time_s(:)));
history.time_s = measurement.measured.time_s(:);
history.flightCondition = struct( ...
    'altitude_m', schedule.altitude_m(:), ...
    'mach', schedule.mach(:), ...
    'deltaT_K', schedule.deltaT_K(:));
history.command = struct( ...
    'NpCommand_rpm', schedule.NpCommand_rpm(:), ...
    'theta_deg', schedule.theta_deg(:), ...
    'kTheta', schedule.kTheta(:), ...
    'hpsPower_W', schedule.hpsPower_W(:));
history.measurement = measured;
history.controllerRecord = measurement.controlRecord;
history.labels = schedule(:, {'segmentId','windowType','windowTypeCode', ...
    'candidateWindowId','isSteadyCandidate', ...
    'healthEstimationEligible'});
history.quality = struct( ...
    'runAccepted', run.validation.passed, ...
    'measurementAccepted', measurement.validation.passed, ...
    'sampleAccepted', true(numel(history.time_s), 1));
end

function history = local_truth_history(run)
measurement = run.measurement;
history = struct( ...
    'missionId', run.missionId, ...
    'variantId', run.variantId, ...
    'truth', measurement.truth, ...
    'dynamic', measurement.dynamic, ...
    'delayed', measurement.delayed, ...
    'measurementError', measurement.error, ...
    'trueSchedule', run.schedule, ...
    'truthLog', run.simulation.log, ...
    'diagnostic', run.diagnostic, ...
    'runValidation', run.validation, ...
    'measurementValidation', measurement.validation, ...
    'measurementRandomSeed', measurement.randomSeed);
end

function history = local_nominal_history(run)
local_require_fields(run, {'missionId','variantId','simulation', ...
    'diagnostic','validation'}, 'nominal run');
history = struct( ...
    'missionId', run.missionId, ...
    'variantId', run.variantId, ...
    'time_s', run.simulation.time(:), ...
    'truthLog', run.simulation.log, ...
    'diagnostic', run.diagnostic, ...
    'runValidation', run.validation);
end

function public = local_public_mission_definition(mission)
% 公开任务定义不含 sigmaDist、总压恢复系数或真实旋翼负载。
def = mission.definition;
public = struct( ...
    'missionId', mission.id, ...
    'displayName', mission.displayName, ...
    'duration_s', def.duration_s, ...
    'altitude_m', def.altitude_m, ...
    'mach', def.mach, ...
    'deltaT_K', def.deltaT_K, ...
    'nodeTime_s', def.nodeTime_s, ...
    'nodeKTheta', def.nodeKTheta, ...
    'segmentId', {def.segmentId}, ...
    'segmentDescription', {def.segmentDescription}, ...
    'steadyWindows', def.steadyWindows);
end

function dictionary = local_field_dictionary(specification)
measurementName = cellstr(string(specification.name));
measurementUnit = cellstr(string(specification.unit));
measurementCount = numel(measurementName);
name = [measurementName; {'time_s';'altitude_m';'mach';'deltaT_K'; ...
    'NpCommand_rpm';'theta_deg';'kTheta';'hpsPower_W'; ...
    'fuel_command';'segmentId';'windowType';'candidateWindowId'}];
unit = [measurementUnit; {'s';'m';'1';'K';'rpm';'deg';'1';'W'; ...
    'kg/s';'text';'text';'text'}];
category = [repmat({'measurement'}, measurementCount, 1); ...
    repmat({'time_or_input'}, 9, 1); repmat({'label'}, 3, 1)];
availability = repmat({'estimationData'}, numel(name), 1);
semanticRole = name;
semanticRole(strcmp(name, 'Mkg')) = { ...
    'GT_external_accessory_load_torque_measurement'};
semanticRole(strcmp(name, 'Mkp')) = { ...
    'PT_load_output_shaft_transmitted_torque_measurement'};
semanticRole(strcmp(name, 'Wf')) = {'actual_fuel_flow_measurement'};
semanticRole(strcmp(name, 'fuel_command')) = {'controller_record_only'};
dictionary = table(name, unit, category, semanticRole, availability);
end

function quality = local_quality_summary(runs, missionIds)
count = numel(runs);
sampleCount = zeros(count, 1);
maxEngineResidual = zeros(count, 1);
nonzeroConvergeTagCount = zeros(count, 1);
steadyWindowPassCount = zeros(count, 1);
steadyWindowCount = zeros(count, 1);
runValidationPassed = false(count, 1);
measurementValidationPassed = false(count, 1);
for i = 1:count
    run = runs{i};
    sampleCount(i) = run.diagnostic.sampleCount;
    maxEngineResidual(i) = run.diagnostic.maxEngineResidual;
    nonzeroConvergeTagCount(i) = ...
        run.diagnostic.nonzeroConvergeTagCount;
    steadyWindowPassCount(i) = nnz(run.steadyWindows.passed);
    steadyWindowCount(i) = height(run.steadyWindows);
    runValidationPassed(i) = run.validation.passed;
    measurementValidationPassed(i) = run.measurement.validation.passed;
end
quality = table(missionIds, sampleCount, maxEngineResidual, ...
    nonzeroConvergeTagCount, steadyWindowPassCount, steadyWindowCount, ...
    runValidationPassed, measurementValidationPassed, ...
    'VariableNames', {'missionId','sampleCount','maxEngineResidual', ...
    'nonzeroConvergeTagCount','steadyWindowPassCount', ...
    'steadyWindowCount','runValidationPassed', ...
    'measurementValidationPassed'});
end

function [comparison, passed] = local_health_effect_comparison( ...
        activeRuns, nominalRuns, healthTruth)
channels = {'Np','Ng','Wf','T45','Mkg','Mkp','Pt3','Tt3', ...
    'Pt45','Pt5','Tt5'};
rowCount = numel(activeRuns) * numel(channels);
missionId = cell(rowCount, 1);
channel = cell(rowCount, 1);
maximumAbsoluteDifference = zeros(rowCount, 1);
rmsDifference = zeros(rowCount, 1);
maximumRelativeDifference = zeros(rowCount, 1);
timeAligned = false(rowCount, 1);
row = 0;
for i = 1:numel(activeRuns)
    active = activeRuns{i};
    nominal = nominalRuns{i};
    activeTime = active.simulation.time(:);
    nominalTime = nominal.simulation.time(:);
    sameTime = isequal(activeTime, nominalTime);
    for j = 1:numel(channels)
        row = row + 1;
        name = channels{j};
        local_require_fields(active.simulation.log, {name}, ...
            'active simulation.log');
        local_require_fields(nominal.simulation.log, {name}, ...
            'nominal simulation.log');
        activeValue = active.simulation.log.(name)(:);
        nominalValue = nominal.simulation.log.(name)(:);
        if numel(activeValue) ~= numel(nominalValue)
            error('sht:flightDataPackage:healthComparisonLength', ...
                '%s 的健康与标称参考长度不一致。', name);
        end
        difference = activeValue - nominalValue;
        scale = max(1, max(abs(nominalValue)));
        missionId{row} = active.missionId;
        channel{row} = name;
        maximumAbsoluteDifference(row) = max(abs(difference));
        rmsDifference(row) = sqrt(mean(difference .^ 2));
        maximumRelativeDifference(row) = ...
            maximumAbsoluteDifference(row) / scale;
        timeAligned(row) = sameTime;
    end
end
comparison = table(missionId, channel, maximumAbsoluteDifference, ...
    rmsDifference, maximumRelativeDifference, timeAligned);
if nnz(healthTruth) == 0
    effectCondition = max(maximumAbsoluteDifference) <= 1e-12;
else
    effectCondition = max(maximumRelativeDifference) > 1e-8;
end
passed = all(timeAligned) && all(isfinite(maximumAbsoluteDifference)) && ...
    effectCondition;
end

function passed = local_history_time_aligned(run)
t = run.simulation.time(:);
measurementTime = run.measurement.measured.time_s(:);
passed = isequal(t, measurementTime) && height(run.schedule) == numel(t);
end

function paths = local_find_forbidden_paths(value, currentPath)
% 只检查字段名和表变量名。数值真值均被组织在 validationData 中。
paths = {};
forbiddenTokens = {'truth','validation','nominalreference','sensorerror', ...
    'errorcomponent','sigmadist','totalpressurerecovery', ...
    'expectedqload','expectedpload','internalstate','future'};
if isstruct(value)
    for elementIndex = 1:numel(value)
        names = fieldnames(value(elementIndex));
        for i = 1:numel(names)
            name = names{i};
            childPath = [currentPath '.' name];
            lowerName = lower(name);
            if any(cellfun(@(token) contains(lowerName, token), ...
                    forbiddenTokens))
                paths{end + 1, 1} = childPath; %#ok<AGROW>
            end
            paths = [paths; local_find_forbidden_paths( ...
                value(elementIndex).(name), childPath)]; %#ok<AGROW>
        end
    end
elseif istable(value)
    names = value.Properties.VariableNames;
    for i = 1:numel(names)
        lowerName = lower(names{i});
        if any(cellfun(@(token) contains(lowerName, token), ...
                forbiddenTokens))
            paths{end + 1, 1} = ...
                [currentPath '.' names{i}]; %#ok<AGROW>
        end
    end
elseif iscell(value)
    for i = 1:numel(value)
        paths = [paths; local_find_forbidden_paths(value{i}, ...
            sprintf('%s{%d}', currentPath, i))]; %#ok<AGROW>
    end
end
end

function local_require_fields(value, names, valueName)
if ~isstruct(value) || ~all(isfield(value, names))
    missing = names(~isfield(value, names));
    error('sht:flightDataPackage:missingField', ...
        '%s 缺少字段：%s。', valueName, strjoin(missing, ', '));
end
end
