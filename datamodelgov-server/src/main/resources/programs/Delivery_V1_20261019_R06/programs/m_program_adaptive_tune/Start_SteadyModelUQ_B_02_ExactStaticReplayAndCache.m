function result = Start_SteadyModelUQ_B_02_ExactStaticReplayAndCache(userCfg)
%START_STEADYMODELUQ_B_02_EXACTSTATICREPLAYANDCACHE 验收B参数映射和缓存。
if nargin < 1, userCfg = struct(); end
timer = tic;
manifest = sht_steady_model_uq_b_io('resolvewritable',userCfg);
step1 = sht_steady_model_uq_b_io('loadstep',manifest,1);
contract = step1.contract;
reference = contract.referencePoint;
schedule = sht_steady_model_uq_b_common( ...
    'vectortoschedule',contract,reference);
roundTrip = sht_steady_model_uq_b_common( ...
    'scheduletovector',contract,schedule);
roundTripError = max(abs(roundTrip-reference));

localCandidate = reference;
localCandidate(contract.parameterBlockIndex{2}(1)) = 1e-3;
bleedFlowCandidate = reference;
bleedFlowCandidate(local_parameter_index(contract,30)) = 1e-4;
bleedTemperatureCandidate = reference;
thermalIndex=local_parameter_index(contract,44);
bleedTemperatureCandidate(thermalIndex) = reference(thermalIndex)+2.5e-4;
theta = [reference,localCandidate,bleedFlowCandidate, ...
    bleedTemperatureCandidate];
first = sht_steady_model_uq_b_common('evaluate',contract,theta, ...
    contract.trainingData,struct('useCache',true));
repeat = sht_steady_model_uq_b_common('evaluate',contract,reference, ...
    contract.trainingData,struct('useCache',true));
reproducibilityError = max(abs(first.residual(:,1)-repeat.residual(:,1)));
localResponse = norm(first.residual(:,2)-first.residual(:,1));
bleedFlowResponse = norm(first.residual(:,3)-first.residual(:,1));
bleedTemperatureResponse = norm(first.residual(:,4)-first.residual(:,1));
constantRoundTrip = max(abs(roundTrip(contract.parameterBlockIndex{2}) - ...
    reference(contract.parameterBlockIndex{2}))) <= 1e-14;
passed = all(first.valid) && repeat.valid && roundTripError <= 1e-12 && ...
    reproducibilityError <= 1e-12 && repeat.cacheHitCount == 1 && ...
    localResponse > 0 && bleedFlowResponse > 0 && ...
    bleedTemperatureResponse > 0 && constantRoundTrip;
if ~passed
    error('SHT:SteadyUQB:ExactReplayAcceptanceFailed', ...
        ['方法B映射/回放/缓存失败：valid=%d/%d/%d/%d，' ...
        'roundTrip=%.3e，repeat=%.3e，local=%.3e，' ...
        'Wfrac=%.3e，Tt=%.3e，hit=%d。'], ...
        first.valid(1),first.valid(2),first.valid(3),first.valid(4), ...
        roundTripError,reproducibilityError,localResponse, ...
        bleedFlowResponse,bleedTemperatureResponse, ...
        repeat.cacheHitCount);
end
result = struct('thetaEvaluated',theta,'referenceResidual', ...
    first.residual(:,1),'firstEvaluation',first,'repeatEvaluation',repeat, ...
    'roundTripMaximumAbsoluteError',roundTripError, ...
    'reproducibilityMaximumAbsoluteError',reproducibilityError, ...
    'localPerturbationResponseNorm',localResponse, ...
    'bleedFlowPerturbationResponseNorm',bleedFlowResponse, ...
    'bleedTemperaturePerturbationResponseNorm',bleedTemperatureResponse, ...
    'passed',passed, ...
    'truthRead',false,'testDataRead',false);
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_b_io( ...
    'savestep',manifest,2,'exact_static_replay_cache',result,runtime);
fprintf(['[2.4UQ-B.2] 映射/回放通过：往返=%.3e，重复=%.3e，' ...
    '局部/Wfrac/Tt响应=%.3e/%.3e/%.3e，缓存命中=%d。\n'], ...
    roundTripError,reproducibilityError,localResponse, ...
    bleedFlowResponse,bleedTemperatureResponse, ...
    repeat.cacheHitCount);
fprintf('[2.4UQ-B.2] 产物：%s\n',file);
result.manifest = manifest;
end

function index = local_parameter_index(contract,cIndex)
index = find(contract.parameterTable.c_index == cIndex & ...
    contract.parameterTable.group_kind == "health_constant",1);
if isempty(index)
    error('SHT:SteadyUQB:ReplayParameterMissing', ...
        '方法B合同缺少h%d常值参数。',cIndex);
end
end
