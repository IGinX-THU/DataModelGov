function value = local_logical_scalar(value, name)
if ~(islogical(value) || isnumeric(value)) || ~isscalar(value) || ...
        ~isfinite(value)
    error('sht:flightDataGenS2:badLogicalSwitch', ...
        '%s 必须是有限标量逻辑开关。', name);
end
value = logical(value);
end

function value = local_char_row(value, name)
if isstring(value) && isscalar(value)
    value = char(value);
end
if ~ischar(value) || size(value, 1) ~= 1
    error('sht:flightDataGenS2:badTextValue', ...
        '%s 必须是字符行向量或标量字符串。', name);
end
end

function local_assert_integer_seed(value, name)
if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
        ~isfinite(value) || value < 0 || value ~= round(value)
    error('sht:flightDataGenS2:badRandomSeed', ...
        '%s 必须是非负整数标量。', name);
end
end

function local_assert_positive_scalar(value, name)
if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
        ~isfinite(value) || value <= 0
    error('sht:flightDataGenS2:badPositiveScalar', ...
        '%s 必须是有限正标量。', name);
end
end

function local_assert_nonnegative_scalar(value, name)
if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
        ~isfinite(value) || value < 0
    error('sht:flightDataGenS2:badNonnegativeScalar', ...
        '%s 必须是有限非负标量。', name);
end
end

function local_assert_finite_scalar(value, name)
if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
        ~isfinite(value)
    error('sht:flightDataGenS2:badFiniteScalar', ...
        '%s 必须是有限实数标量。', name);
end
end
