function [truthTable, health] = local_health_truth_vector(values)
% CIndex 是 C 端 hlthparas 的 0 基下标；matlabIndex 是 100 维 MATLAB
% 健康向量的 1 基下标。S9 不允许在其他位置散布健康真值常数。
required = {'HPC_hpW','HPC_hpEf','GT_hpW','GT_hpEf','PT_hpW','PT_hpEf'};
if ~isstruct(values) || ~isscalar(values) || ...
        ~all(isfield(values, required)) || ...
        numel(fieldnames(values)) ~= numel(required)
    error('sht:flightDataGenS9:badHealthTruthDefinition', ...
        'healthTruth 必须且只能定义六个已确认的稳态健康参数。');
end
name = required(:);
cIndex = [1; 2; 7; 8; 11; 12];
matlabIndex = cIndex + 1;
configuredValue = zeros(numel(name), 1);
for i = 1:numel(name)
    value = values.(name{i});
    if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
            ~isfinite(value) || abs(value) > 0.5
        error('sht:flightDataGenS9:badHealthTruthValue', ...
            '%s 必须是绝对值不超过 0.5 的有限实数标量。', name{i});
    end
    configuredValue(i) = value;
end
health = zeros(100, 1);
health(matlabIndex) = configuredValue;
truthTable = table(name, cIndex, matlabIndex, configuredValue);
end

function windows = local_window_definition(ids, startTime_s, endTime_s, ...
        healthEstimationEligible)
% 将顶部配置中的并行数组整理为结构体，供标签和校验统一使用。
count = numel(ids);
if numel(startTime_s) ~= count || numel(endTime_s) ~= count || ...
        numel(healthEstimationEligible) ~= count
    error('sht:flightDataGenS2:badWindowDefinition', ...
        '稳态窗口 ID、起止时间和健康估计资格必须等长。');
end
windows = repmat(struct('id','','startTime_s',0,'endTime_s',0, ...
    'healthEstimationEligible',false), count, 1);
for i = 1:count
    windows(i).id = ids{i};
    windows(i).startTime_s = startTime_s(i);
    windows(i).endTime_s = endTime_s(i);
    windows(i).healthEstimationEligible = ...
        logical(healthEstimationEligible(i));
end
end

function merged = local_merge_known_struct(base, override, pathName)
% 递归合并已知字段；此入口不接收通用模型 cfg，避免误以为 S2 会运行 DLL。
merged = base;
names = fieldnames(override);
for i = 1:numel(names)
    name = names{i};
    if ~isfield(base, name)
        error('sht:flightDataGenS2:unknownConfigField', ...
            '%s.%s 不是 S2 入口支持的配置字段。', pathName, name);
    end
    baseValue = base.(name);
    overrideValue = override.(name);
    if isstruct(baseValue) && isscalar(baseValue) && ...
            isstruct(overrideValue) && isscalar(overrideValue)
        merged.(name) = local_merge_known_struct(baseValue, ...
            overrideValue, [pathName '.' name]);
    else
        merged.(name) = overrideValue;
    end
end
end

function entry = local_validate_entry(entry, mappingCfg, baseCfg)
local_assert_positive_scalar(entry.designNpRpm, 'designNpRpm');
local_assert_positive_scalar(entry.designPowerW, 'designPowerW');
local_assert_positive_scalar(entry.designTorqueNm, 'designTorqueNm');
local_assert_nonnegative_scalar(entry.hpsPower_W, 'hpsPower_W');
local_assert_finite_scalar(entry.deltaPExhaust_Pa, 'deltaPExhaust_Pa');
if entry.deltaPExhaust_Pa ~= 0
    error('sht:flightDataGenS2:exhaustBackPressureNotSupported', ...
        '首轮 S2 固定 deltaPExhaust_Pa=0，尚未接入排气背压模型。');
end
local_assert_positive_scalar(entry.sampleTime_s, 'sampleTime_s');

switchNames = {'measurementErrorEnabled','healthTruthEnabled', ...
    'installedBoundaryEnabled', ...
    'independentTrimEnabled','groundSimulationEnabled', ...
    'cruiseSimulationEnabled', ...
    'plotEnabled','saveEnabled'};
for i = 1:numel(switchNames)
    name = switchNames{i};
    entry.(name) = local_logical_scalar(entry.(name), name);
end

if (entry.groundSimulationEnabled || entry.cruiseSimulationEnabled) && ...
        ~entry.independentTrimEnabled
    error('sht:flightDataGenS9:simulationRequiresTrim', ...
        '运行 S9 时域历程前必须启用独立配平。');
end
if (entry.groundSimulationEnabled || entry.cruiseSimulationEnabled) && ...
        entry.hpsPower_W ~= 30000
    error('sht:flightDataGenS9:badHpsPower', ...
        '第 3 阶段首轮的 GT 轴附件功率必须为 30000 W。');
end
[~, configuredHealth] = local_health_truth_vector(entry.healthTruth);
if nnz(configuredHealth(59:100)) ~= 0
    error('sht:flightDataGenS9:transientHealthNonzero', ...
        'S9 的 hlthparas[58:99] 瞬态修正系数必须全部为零。');
end

entry.measurementProfile = local_char_row(entry.measurementProfile, ...
    'measurementProfile');
if ~strcmp(entry.measurementProfile, 'flightSparse')
    error('sht:flightDataGenS2:badMeasurementProfile', ...
        'S2 正式配置要求 measurementProfile=''flightSparse''。');
end
if ~isstruct(entry.measurement) || ~isscalar(entry.measurement)
    error('sht:flightDataGenS8:badMeasurementConfig', ...
        'entry.measurement 必须是标量结构体。');
end
measurementFields = {'fastSensorTimeConstant_s', ...
    'temperatureBandwidth_radps','delay_s','components'};
for i = 1:numel(measurementFields)
    if ~isfield(entry.measurement, measurementFields{i})
        error('sht:flightDataGenS8:missingMeasurementConfig', ...
            'entry.measurement 缺少字段 %s。', measurementFields{i});
    end
end
local_assert_positive_scalar(entry.measurement.fastSensorTimeConstant_s, ...
    'measurement.fastSensorTimeConstant_s');
temperatureChannels = {'Tt1','Tamb','Tt3','T45','Tt5'};
if ~isstruct(entry.measurement.temperatureBandwidth_radps) || ...
        ~isscalar(entry.measurement.temperatureBandwidth_radps)
    error('sht:flightDataGenS8:badTemperatureBandwidthConfig', ...
        'measurement.temperatureBandwidth_radps 必须是标量结构体。');
end
for i = 1:numel(temperatureChannels)
    name = temperatureChannels{i};
    if ~isfield(entry.measurement.temperatureBandwidth_radps, name)
        error('sht:flightDataGenS8:missingTemperatureBandwidth', ...
            'temperatureBandwidth_radps 缺少温度通道 %s。', name);
    end
    local_assert_positive_scalar( ...
        entry.measurement.temperatureBandwidth_radps.(name), ...
        ['measurement.temperatureBandwidth_radps.' name]);
end
local_assert_nonnegative_scalar(entry.measurement.delay_s, ...
    'measurement.delay_s');
if abs(entry.measurement.delay_s / entry.sampleTime_s - ...
        round(entry.measurement.delay_s / entry.sampleTime_s)) > 1e-10
    error('sht:flightDataGenS8:nonintegerMeasurementDelay', ...
        'measurement.delay_s 必须是 sampleTime_s 的整数倍。');
end
if ~isstruct(entry.measurement.components) || ...
        ~isscalar(entry.measurement.components)
    error('sht:flightDataGenS8:badMeasurementComponents', ...
        'measurement.components 必须是标量结构体。');
end
componentNames = {'dynamics','delay','bias','noise'};
for i = 1:numel(componentNames)
    name = componentNames{i};
    if ~isfield(entry.measurement.components, name)
        error('sht:flightDataGenS8:missingMeasurementComponent', ...
            'measurement.components 缺少字段 %s。', name);
    end
    entry.measurement.components.(name) = local_logical_scalar( ...
        entry.measurement.components.(name), ...
        ['measurement.components.' name]);
end
if entry.measurement.delay_s ~= 0 || entry.measurement.components.delay
    error('sht:flightDataGenS8:delayDisabled', ...
        ['第 3.1 阶段当前配置不引入独立纯延迟：' ...
         'measurement.delay_s 必须为 0，components.delay 必须为 false。']);
end
entry.outputDir = local_char_row(entry.outputDir, 'outputDir');
if isempty(entry.outputDir)
    error('sht:flightDataGenS2:emptyOutputDir', 'outputDir 不得为空。');
end

local_assert_integer_seed(entry.mainRandomSeed, 'mainRandomSeed');

% 调用映射函数本身完成映射参数的一致性校验。
sht_collective_pitch_mapping(mappingCfg.thetaDesignDeg, ...
    'thetaToKTheta', mappingCfg);

if ~isfield(baseCfg.engine, 'stateNames') || ...
        ~isequal(baseCfg.engine.stateNames, {'Np','Ng'})
    error('sht:flightDataGenS2:unexpectedBaselineStates', ...
        'S2 要求基准模型状态严格为 [Np, Ng]。');
end
if isfield(baseCfg.engine, 'transientEffects')
    error('sht:flightDataGenS2:transientEffectsPresent', ...
        'S2 不得加载热沉浸或动态间隙瞬态增强配置。');
end

entry.ground = local_validate_definition(entry.ground, entry.sampleTime_s);
entry.cruise = local_validate_definition(entry.cruise, entry.sampleTime_s);
end

function def = local_validate_definition(def, sampleTime_s)
required = {'missionId','displayName','altitude_m','mach','deltaT_K', ...
    'deltaTIn_K','duration_s', ...
    'npCommandRatio','sigmaIn','nodeTime_s','nodeKTheta', ...
    'nodeSigmaDist','segmentId','segmentBaseType', ...
    'segmentDescription','steadyWindows'};
for i = 1:numel(required)
    if ~isfield(def, required{i})
        error('sht:flightDataGenS2:missingMissionField', ...
            '任务定义缺少字段 %s。', required{i});
    end
end
def.missionId = local_char_row(def.missionId, 'missionId');
def.displayName = local_char_row(def.displayName, 'displayName');
local_assert_nonnegative_scalar(def.altitude_m, 'altitude_m');
local_assert_nonnegative_scalar(def.mach, 'mach');
local_assert_finite_scalar(def.deltaT_K, 'deltaT_K');
local_assert_finite_scalar(def.deltaTIn_K, 'deltaTIn_K');
local_assert_positive_scalar(def.duration_s, 'duration_s');
local_assert_positive_scalar(def.npCommandRatio, 'npCommandRatio');
if ~isscalar(def.sigmaIn) || ~isfinite(def.sigmaIn) || ...
        def.sigmaIn <= 0 || def.sigmaIn > 1
    error('sht:flightDataGenS2:badSigmaIn', ...
        '%s 的 sigmaIn 必须位于 (0,1]。', def.missionId);
end

% 在构造完整时间序列前先检查大气适用域和热力学边界。
sht_flight_data_common('flightAtmosphere', ...
    def.altitude_m, def.mach, def.deltaT_K);

nodeTime = def.nodeTime_s(:).';
nodeKTheta = def.nodeKTheta(:).';
nodeSigma = def.nodeSigmaDist(:).';
nodeCount = numel(nodeTime);
if nodeCount < 2 || numel(nodeKTheta) ~= nodeCount || ...
        numel(nodeSigma) ~= nodeCount || any(~isfinite(nodeTime)) || ...
        any(~isfinite(nodeKTheta)) || any(~isfinite(nodeSigma))
    error('sht:flightDataGenS2:badMissionNodes', ...
        '%s 的时间、kTheta 和 sigmaDist 节点必须等长且有限。', ...
        def.missionId);
end
if nodeTime(1) ~= 0 || abs(nodeTime(end) - def.duration_s) > 1e-12 || ...
        any(diff(nodeTime) <= 0)
    error('sht:flightDataGenS2:badMissionTimeCoverage', ...
        '%s 的节点必须从 0 严格递增并覆盖到 duration_s。', ...
        def.missionId);
end
if any(abs(nodeTime / sampleTime_s - round(nodeTime / sampleTime_s)) > 1e-10)
    error('sht:flightDataGenS2:nodeOffSampleGrid', ...
        '%s 存在未落在采样网格上的时间节点。', def.missionId);
end
if any(nodeSigma <= 0) || any(nodeSigma > 1)
    error('sht:flightDataGenS2:badSigmaDist', ...
        '%s 的 sigmaDist 节点必须位于 (0,1]。', def.missionId);
end

segmentCount = nodeCount - 1;
if numel(def.segmentId) ~= segmentCount || ...
        numel(def.segmentBaseType) ~= segmentCount || ...
        numel(def.segmentDescription) ~= segmentCount
    error('sht:flightDataGenS2:segmentCountMismatch', ...
        '%s 的分段标签数量必须等于节点数减一。', def.missionId);
end
allowedTypes = {'hold','transition','boundaryValidation'};
for i = 1:segmentCount
    def.segmentId{i} = local_char_row(def.segmentId{i}, 'segmentId');
    def.segmentBaseType{i} = local_char_row( ...
        def.segmentBaseType{i}, 'segmentBaseType');
    def.segmentDescription{i} = local_char_row( ...
        def.segmentDescription{i}, 'segmentDescription');
    if ~ismember(def.segmentBaseType{i}, allowedTypes)
        error('sht:flightDataGenS2:badSegmentType', ...
            '%s 的 segmentBaseType=%s 无效。', ...
            def.missionId, def.segmentBaseType{i});
    end
end
if numel(unique(def.segmentId)) ~= segmentCount
    error('sht:flightDataGenS2:duplicateSegmentId', ...
        '%s 的 segmentId 必须互异。', def.missionId);
end

windows = def.steadyWindows;
if ~isstruct(windows) || isempty(windows)
    error('sht:flightDataGenS2:badSteadyWindows', ...
        '%s 必须至少定义一个候选稳态窗口。', def.missionId);
end
windowIds = cell(numel(windows), 1);
for i = 1:numel(windows)
    windowIds{i} = local_char_row(windows(i).id, 'steadyWindow.id');
    if windows(i).startTime_s < 0 || ...
            windows(i).endTime_s > def.duration_s || ...
            windows(i).endTime_s <= windows(i).startTime_s
        error('sht:flightDataGenS2:badSteadyWindowRange', ...
            '%s 的窗口 %s 超出任务范围或起止时间无效。', ...
            def.missionId, windowIds{i});
    end
    windows(i).healthEstimationEligible = local_logical_scalar( ...
        windows(i).healthEstimationEligible, ...
        'steadyWindow.healthEstimationEligible');
end
if numel(unique(windowIds)) ~= numel(windowIds)
    error('sht:flightDataGenS2:duplicateWindowId', ...
        '%s 的稳态窗口 ID 必须互异。', def.missionId);
end

def.nodeTime_s = nodeTime;
def.nodeKTheta = nodeKTheta;
def.nodeSigmaDist = nodeSigma;
def.steadyWindows = windows;
end

function mission = local_build_mission(def, entry, mappingCfg)
stepCount = round(def.duration_s / entry.sampleTime_s);
if abs(stepCount * entry.sampleTime_s - def.duration_s) > 1e-10
    error('sht:flightDataGenS2:durationOffSampleGrid', ...
        '%s 的 duration_s 不能被 sampleTime_s 整除。', def.missionId);
end
time_s = (0:stepCount).' * entry.sampleTime_s;
time_s(end) = def.duration_s;
sampleCount = numel(time_s);

% 调度节点只配置 kTheta；统一逆映射得到精确 theta 节点，再对 theta
% 线性插值。边界和负载的逐点计算统一交给单步函数，避免入口程序复制
% 物理公式；S4 接入闭环后只需把 NpCommand_rpm 替换为发动机当前 Np。
[thetaNode_deg, nodeDiagnostic] = sht_collective_pitch_mapping( ...
    def.nodeKTheta, 'kThetaToTheta', mappingCfg);
NpCommand_rpm = repmat(entry.designNpRpm * def.npCommandRatio, ...
    sampleCount, 1);
runtimeDef = def;
runtimeDef.thetaNode_deg = thetaNode_deg;
flightCfg = struct( ...
    'designNpRpm', entry.designNpRpm, ...
    'designTorqueNm', entry.designTorqueNm, ...
    'hpsPower_W', entry.hpsPower_W, ...
    'deltaPExhaust_Pa', entry.deltaPExhaust_Pa, ...
    'installedBoundaryEnabled', entry.installedBoundaryEnabled, ...
    'collectivePitchMapping', mappingCfg);

firstBoundary = sht_flight_boundary_step(time_s(1), NpCommand_rpm(1), ...
    runtimeDef, flightCfg);
boundary = repmat(firstBoundary, sampleCount, 1);
for sampleIndex = 2:sampleCount
    boundary(sampleIndex) = sht_flight_boundary_step( ...
        time_s(sampleIndex), NpCommand_rpm(sampleIndex), ...
        runtimeDef, flightCfg);
end

altitude_m = [boundary.altitude_m].';
mach = [boundary.mach].';
deltaT_K = [boundary.deltaT_K].';
troposphereFormulaExtrapolated = ...
    [boundary.troposphereFormulaExtrapolated].';
Tisa_K = [boundary.Tisa_K].';
Ts_K = [boundary.Ts_K].';
Ps_Pa = [boundary.Ps_Pa].';
rho_kgpm3 = [boundary.rho_kgpm3].';
speedOfSound_mps = [boundary.speedOfSound_mps].';
trueAirspeed_mps = [boundary.trueAirspeed_mps].';
dynamicPressure_Pa = [boundary.dynamicPressure_Pa].';
Pt0_Pa = [boundary.Pt0_Pa].';
Tt0_K = [boundary.Tt0_K].';
sigmaIn = [boundary.sigmaIn].';
sigmaDist = [boundary.sigmaDist].';
totalPressureRecovery = [boundary.totalPressureRecovery].';
deltaTIn_K = [boundary.deltaTIn_K].';
Pt1_Pa = [boundary.Pt1_Pa].';
Tt1_K = [boundary.Tt1_K].';
Pamb_Pa = [boundary.Pamb_Pa].';
theta_deg = [boundary.theta_deg].';
kTheta = [boundary.kTheta].';
thetaWithinValidRange = [boundary.thetaWithinValidRange].';
expectedNpr = [boundary.Npr].';
expectedQload_Nm = [boundary.Qload_Nm].';
expectedPload_W = [boundary.Pload_W].';
hpsPower_W = [boundary.hpsPower_W].';
deltaPExhaust_Pa = [boundary.deltaPExhaust_Pa].';

[segmentId, segmentDescription, windowType] = ...
    local_segment_labels(time_s, def);
[candidateWindowId, isSteadyCandidate, healthEstimationEligible, ...
    windowType] = local_window_labels(time_s, def, windowType);
windowTypeCode = local_window_type_code(windowType);

missionId = repmat({def.missionId}, sampleCount, 1);
boundarySegmentId = {boundary.segmentId}.';
if ~isequal(boundarySegmentId, segmentId)
    error('sht:flightDataGenS2:segmentSchedulerMismatch', ...
        '%s 的入口标签和单步边界函数标签不一致。', def.missionId);
end

schedule = table(time_s, missionId, segmentId, segmentDescription, ...
    windowType, windowTypeCode, candidateWindowId, ...
    isSteadyCandidate, healthEstimationEligible, altitude_m, mach, ...
    deltaT_K, troposphereFormulaExtrapolated, Tisa_K, Ts_K, Ps_Pa, ...
    rho_kgpm3, speedOfSound_mps, ...
    trueAirspeed_mps, dynamicPressure_Pa, Pt0_Pa, Tt0_K, ...
    sigmaIn, sigmaDist, totalPressureRecovery, deltaTIn_K, ...
    Pt1_Pa, Tt1_K, Pamb_Pa, NpCommand_rpm, theta_deg, kTheta, ...
    thetaWithinValidRange, expectedNpr, expectedQload_Nm, ...
    expectedPload_W, hpsPower_W, deltaPExhaust_Pa);

mission = struct();
mission.id = def.missionId;
mission.displayName = def.displayName;
mission.definition = def;
mission.definition.thetaNode_deg = thetaNode_deg;
mission.definition.nodeThetaWithinValidRange = ...
    nodeDiagnostic.thetaWithinValidRange;
mission.runtimeBoundarySchedule = struct( ...
    'enabled', true, ...
    'mission', mission.definition, ...
    'model', flightCfg);
mission.schedule = schedule;
mission.summary = struct( ...
    'sampleCount', sampleCount, ...
    'segmentCount', numel(def.segmentId), ...
    'steadyCandidateSampleCount', nnz(isSteadyCandidate), ...
    'healthEligibleSampleCount', nnz(healthEstimationEligible), ...
    'transitionSampleCount', nnz(strcmp(windowType, 'transition')), ...
    'settlingSampleCount', nnz(strcmp(windowType, 'settling')), ...
    'boundaryValidationSampleCount', ...
        nnz(strcmp(windowType, 'boundaryValidation')), ...
    'thetaRange_deg', [min(theta_deg), max(theta_deg)], ...
    'kThetaRange', [min(kTheta), max(kTheta)], ...
    'sigmaDistRange', [min(sigmaDist), max(sigmaDist)], ...
    'staticTemperatureRange_K', [min(Ts_K), max(Ts_K)], ...
    'staticPressureRange_Pa', [min(Ps_Pa), max(Ps_Pa)], ...
    'inletTotalTemperatureRange_K', [min(Tt1_K), max(Tt1_K)], ...
    'inletTotalPressureRange_Pa', [min(Pt1_Pa), max(Pt1_Pa)], ...
    'expectedQloadRange_Nm', ...
        [min(expectedQload_Nm), max(expectedQload_Nm)], ...
    'expectedPloadRange_W', ...
        [min(expectedPload_W), max(expectedPload_W)]);

local_validate_built_mission(mission, entry.sampleTime_s);
end

function [segmentId, description, windowType] = ...
        local_segment_labels(time_s, def)
count = numel(time_s);
segmentId = repmat({''}, count, 1);
description = repmat({''}, count, 1);
windowType = repmat({'settling'}, count, 1);
segmentCount = numel(def.segmentId);
for i = 1:segmentCount
    mask = local_interval_mask(time_s, def.nodeTime_s(i), ...
        def.nodeTime_s(i + 1), i == segmentCount);
    segmentId(mask) = repmat(def.segmentId(i), nnz(mask), 1);
    description(mask) = repmat(def.segmentDescription(i), nnz(mask), 1);
    switch def.segmentBaseType{i}
        case 'transition'
            windowType(mask) = {'transition'};
        case 'boundaryValidation'
            windowType(mask) = {'boundaryValidation'};
        case 'hold'
            % 保持段在稳态窗口识别前先标为 settling。
        otherwise
            error('sht:flightDataGenS2:internalSegmentType', ...
                '未处理的分段类型 %s。', def.segmentBaseType{i});
    end
end
if any(cellfun(@isempty, segmentId))
    error('sht:flightDataGenS2:unlabeledSegmentSample', ...
        '%s 存在未分配 segmentId 的样本。', def.missionId);
end
end

function [windowId, isCandidate, healthEligible, windowType] = ...
        local_window_labels(time_s, def, windowType)
count = numel(time_s);
windowId = repmat({''}, count, 1);
isCandidate = false(count, 1);
healthEligible = false(count, 1);
windows = def.steadyWindows;
for i = 1:numel(windows)
    includeEnd = abs(windows(i).endTime_s - def.duration_s) <= 1e-12;
    mask = local_interval_mask(time_s, windows(i).startTime_s, ...
        windows(i).endTime_s, includeEnd);
    if any(isCandidate(mask))
        error('sht:flightDataGenS2:overlappingSteadyWindows', ...
            '%s 的候选稳态窗口发生重叠。', def.missionId);
    end
    windowId(mask) = repmat({windows(i).id}, nnz(mask), 1);
    isCandidate(mask) = true;
    healthEligible(mask) = windows(i).healthEstimationEligible;

    % C_SD 虽是准稳态窗口，但只用于装机边界验证，不标为健康估计稳态。
    boundaryMask = mask & strcmp(windowType, 'boundaryValidation');
    normalMask = mask & ~boundaryMask;
    windowType(normalMask) = {'steadyCandidate'};
end
end

function mask = local_interval_mask(time_s, startTime_s, endTime_s, includeEnd)
tolerance = 100 * eps(max(1, max(abs(time_s))));
if includeEnd
    mask = time_s >= startTime_s - tolerance & ...
        time_s <= endTime_s + tolerance;
else
    mask = time_s >= startTime_s - tolerance & ...
        time_s < endTime_s - tolerance;
end
end

function code = local_window_type_code(windowType)
code = zeros(numel(windowType), 1);
mapping = {'steadyCandidate',1; 'transition',2; ...
    'settling',3; 'boundaryValidation',4};
for i = 1:size(mapping, 1)
    code(strcmp(windowType, mapping{i, 1})) = mapping{i, 2};
end
if any(code == 0)
    error('sht:flightDataGenS2:unknownWindowType', ...
        '存在无法编码的 windowType。');
end
end

function local_validate_built_mission(mission, sampleTime_s)
t = mission.schedule.time_s;
expectedCount = round(mission.definition.duration_s / sampleTime_s) + 1;
if numel(t) ~= expectedCount || abs(t(1)) > 1e-12 || ...
        abs(t(end) - mission.definition.duration_s) > 1e-12
    error('sht:flightDataGenS2:badBuiltTimeAxis', ...
        '%s 的时间轴范围或样本数不正确。', mission.id);
end
if max(abs(diff(t) - sampleTime_s)) > 1e-10
    error('sht:flightDataGenS2:nonuniformSampleTime', ...
        '%s 的记录采样周期不一致。', mission.id);
end
if any(~mission.schedule.thetaWithinValidRange)
    error('sht:flightDataGenS2:thetaOutsideValidRange', ...
        '%s 的总距角超出首轮工程有效范围。', mission.id);
end
if any(~isfinite(mission.schedule{:, ...
        {'altitude_m','mach','deltaT_K','Tisa_K','Ts_K','Ps_Pa', ...
         'rho_kgpm3','speedOfSound_mps','trueAirspeed_mps', ...
         'dynamicPressure_Pa','Pt0_Pa','Tt0_K','sigmaIn', ...
         'sigmaDist','totalPressureRecovery','deltaTIn_K', ...
         'Pt1_Pa','Tt1_K','Pamb_Pa','NpCommand_rpm','theta_deg', ...
         'kTheta','expectedNpr','expectedQload_Nm','expectedPload_W', ...
         'hpsPower_W','deltaPExhaust_Pa'}}), 'all')
    error('sht:flightDataGenS2:nonfiniteSchedule', ...
        '%s 的数值调度存在非有限值。', mission.id);
end
positiveFields = {'Tisa_K','Ts_K','Ps_Pa','rho_kgpm3', ...
    'speedOfSound_mps','Pt0_Pa','Tt0_K','sigmaIn','sigmaDist', ...
    'totalPressureRecovery','Pt1_Pa','Tt1_K','Pamb_Pa', ...
    'NpCommand_rpm','expectedNpr','expectedQload_Nm','expectedPload_W'};
if any(mission.schedule{:, positiveFields} <= 0, 'all')
    error('sht:flightDataGenS2:nonpositiveBoundary', ...
        '%s 的大气、装机边界或负载存在非正值。', mission.id);
end

nodeIndex = round(mission.definition.nodeTime_s / sampleTime_s) + 1;
nodeKThetaError = max(abs(mission.schedule.kTheta(nodeIndex) - ...
    mission.definition.nodeKTheta(:)));
nodeSigmaError = max(abs(mission.schedule.sigmaDist(nodeIndex) - ...
    local_applied_sigma_nodes(mission.definition, mission.schedule)));
if nodeKThetaError > 1e-12 || nodeSigmaError > 1e-12
    error('sht:flightDataGenS2:nodeValueMismatch', ...
        '%s 的调度节点未精确复现设计值。', mission.id);
end

omega = mission.schedule.NpCommand_rpm * pi / 30;
powerIdentityError = max(abs(mission.schedule.expectedPload_W - ...
    mission.schedule.expectedQload_Nm .* omega));
if powerIdentityError > 1e-8
    error('sht:flightDataGenS2:powerIdentityMismatch', ...
        '%s 的 P=Q*omega 恒等关系未通过。', mission.id);
end

% 校核 0 截面冲压关系、1 截面装机恢复关系和排气环境边界。
constants = sht_flight_data_common('constants');
ramTemperatureRatio = 1 + 0.5 * (constants.gamma - 1) .* ...
    mission.schedule.mach .^ 2;
ramPressureRatio = ramTemperatureRatio .^ ...
    (constants.gamma / (constants.gamma - 1));
Tt0Error = max(abs(mission.schedule.Tt0_K - ...
    mission.schedule.Ts_K .* ramTemperatureRatio));
Pt0Error = max(abs(mission.schedule.Pt0_Pa - ...
    mission.schedule.Ps_Pa .* ramPressureRatio));
Pt1Error = max(abs(mission.schedule.Pt1_Pa - ...
    mission.schedule.totalPressureRecovery .* mission.schedule.Pt0_Pa));
Tt1Error = max(abs(mission.schedule.Tt1_K - ...
    (mission.schedule.Tt0_K + mission.schedule.deltaTIn_K)));
PambError = max(abs(mission.schedule.Pamb_Pa - ...
    (mission.schedule.Ps_Pa + mission.schedule.deltaPExhaust_Pa)));
if Tt0Error > 1e-10 || Pt0Error > 1e-8 || Pt1Error > 1e-8 || ...
        Tt1Error > 1e-10 || PambError > 1e-8
    error('sht:flightDataGenS2:boundaryIdentityMismatch', ...
        '%s 的冲压、装机恢复或排气环境边界恒等关系未通过。', mission.id);
end
if any(mission.schedule.Pt1_Pa > mission.schedule.Pt0_Pa + 1e-8)
    error('sht:flightDataGenS2:inletPressureGain', ...
        '%s 的首轮无源进气边界出现 Pt1>Pt0。', mission.id);
end

% 与直接节点插值逐点比较，以排除分段连接处的非设计跳变。
expectedTheta_deg = interp1(mission.definition.nodeTime_s, ...
    mission.definition.thetaNode_deg, t, 'linear');
if all(abs(mission.schedule.sigmaDist - 1) <= 1e-14) && ...
        any(abs(mission.definition.nodeSigmaDist - 1) > 1e-14)
    expectedSigmaDist = ones(size(t));
else
    expectedSigmaDist = interp1(mission.definition.nodeTime_s, ...
        mission.definition.nodeSigmaDist, t, 'linear');
end
if max(abs(mission.schedule.theta_deg - expectedTheta_deg)) > 1e-12 || ...
        max(abs(mission.schedule.sigmaDist - expectedSigmaDist)) > 1e-12
    error('sht:flightDataGenS2:unexpectedScheduleJump', ...
        '%s 的节点连接未保持设计的连续线性调度。', mission.id);
end
end

function sigmaNodes = local_applied_sigma_nodes(def, schedule)
if all(abs(schedule.sigmaDist - 1) <= 1e-14) && ...
        any(abs(def.nodeSigmaDist - 1) > 1e-14)
    sigmaNodes = ones(numel(def.nodeSigmaDist), 1);
else
    sigmaNodes = def.nodeSigmaDist(:);
end
end

function local_validate_mission_set(missions)
if numel(missions) ~= 2 || ...
        ~isequal({missions.id}, {'G01_GroundTakeoff','C01_AirCruise'})
    error('sht:flightDataGenS2:badMissionSet', ...
        'S2 必须且只能生成按 G01、C01 排列的两条任务。');
end
allWindowTypes = [missions(1).schedule.windowType; ...
    missions(2).schedule.windowType];
required = {'steadyCandidate','transition','settling','boundaryValidation'};
for i = 1:numel(required)
    if ~any(strcmp(allWindowTypes, required{i}))
        error('sht:flightDataGenS2:missingWindowType', ...
            '两条任务合计缺少 windowType=%s。', required{i});
    end
end

% 进气损失区段不得与总距变化重叠。
cruise = missions(2).schedule;
boundary = strcmp(cruise.windowType, 'boundaryValidation');
if any(abs(cruise.theta_deg(boundary) - cruise.theta_deg(find(boundary,1))) > 1e-12)
    error('sht:flightDataGenS2:coupledDistortionAndPitch', ...
        'C01 进气边界验证区段内总距角必须保持不变。');
end
end

function mission = local_set_cruise_distortion( ...
        mission, nodeSigmaDist, sampleTime_s)
% 从同一个独立配平任务复制清洁进气对照，只改变 sigmaDist 调度。
nodeSigmaDist = nodeSigmaDist(:).';
if numel(nodeSigmaDist) ~= numel(mission.definition.nodeTime_s) || ...
        any(~isfinite(nodeSigmaDist)) || any(nodeSigmaDist <= 0) || ...
        any(nodeSigmaDist > 1)
    error('sht:flightDataGenS7:badCruiseDistortionNodes', ...
        'C01 sigmaDist 节点必须与时间节点等长并位于 (0,1]。');
end

mission.definition.nodeSigmaDist = nodeSigmaDist;
mission.runtimeBoundarySchedule.mission.nodeSigmaDist = nodeSigmaDist;
if ~isfield(mission.runtimeConfig, 'flight') || ...
        ~isfield(mission.runtimeConfig.flight, 'boundarySchedule')
    error('sht:flightDataGenS7:missingCruiseRuntimeSchedule', ...
        'C01 缺少独立配平后的飞行边界运行配置。');
end
mission.runtimeConfig.flight.boundarySchedule.mission.nodeSigmaDist = ...
    nodeSigmaDist;

t = mission.schedule.time_s;
sigmaDist = interp1(mission.definition.nodeTime_s, nodeSigmaDist, ...
    t, 'linear');
mission.schedule.sigmaDist = sigmaDist;
mission.schedule.totalPressureRecovery = ...
    mission.schedule.sigmaIn .* sigmaDist;
mission.schedule.Pt1_Pa = mission.schedule.Pt0_Pa .* ...
    mission.schedule.totalPressureRecovery;
mission.summary.sigmaDistRange = [min(sigmaDist), max(sigmaDist)];
mission.summary.inletTotalPressureRange_Pa = ...
    [min(mission.schedule.Pt1_Pa), max(mission.schedule.Pt1_Pa)];

local_validate_built_mission(mission, sampleTime_s);
end

function comparison = local_compare_cruise_runs(cleanRun, distortedRun)
% 在同一时间坐标下比较 C01 清洁进气和设计畸变两次独立回放。
if ~cleanRun.validation.passed || ~distortedRun.validation.passed
    error('sht:flightDataGenS7:unacceptedCruiseRun', ...
        '只有两次 C01 单独验收都通过后才能进行畸变对比。');
end
t = cleanRun.simulation.time(:);
td = distortedRun.simulation.time(:);
timeTolerance = max(1e-10, 100 * numel(t) * eps(max(1, t(end))));
sameTimeGrid = numel(t) == numel(td) && ...
    max(abs(t - td)) <= timeTolerance;
if ~sameTimeGrid
    error('sht:flightDataGenS7:cruiseTimeGridMismatch', ...
        'C01 清洁进气与畸变运行的时间网格不一致。');
end

clean = cleanRun.simulation.log;
distorted = distortedRun.simulation.log;
schedule = distortedRun.schedule;
lossMask = distorted.flightSigmaDist < 1 - 1e-12;
holdMask = strcmp(schedule.candidateWindowId, 'C_SD');
if ~any(lossMask) || ~any(holdMask) || ~all(lossMask(holdMask))
    error('sht:flightDataGenS7:missingDistortionWindow', ...
        'C01 必须包含有效的进气损失样本，且 C_SD 必须位于损失保持段。');
end

signals = local_cruise_comparison_signals(clean, distorted);
names = fieldnames(signals.clean);
n = numel(names);
displayName = cell(n, 1);
unit = cell(n, 1);
cleanMean = zeros(n, 1);
distortedMean = zeros(n, 1);
meanDelta = zeros(n, 1);
relativeMeanDelta = zeros(n, 1);
peakAbsDelta = zeros(n, 1);
direction = cell(n, 1);
for i = 1:n
    name = names{i};
    displayName{i} = signals.displayName.(name);
    unit{i} = signals.unit.(name);
    cleanValue = signals.clean.(name)(:);
    distortedValue = signals.distorted.(name)(:);
    cleanMean(i) = mean(cleanValue(holdMask));
    distortedMean(i) = mean(distortedValue(holdMask));
    meanDelta(i) = distortedMean(i) - cleanMean(i);
    relativeMeanDelta(i) = meanDelta(i) / ...
        max(abs(cleanMean(i)), realmin);
    peakAbsDelta(i) = max(abs(distortedValue - cleanValue));
    direction{i} = local_delta_direction(relativeMeanDelta(i), 1e-10);
end
effectTable = table(displayName, unit, cleanMean, distortedMean, ...
    meanDelta, relativeMeanDelta, peakAbsDelta, direction);

firstLossIndex = find(lossMask, 1, 'first');
preIndex = 1:max(1, firstLossIndex - 1);
preFieldNames = {'WIn','HPC_PR','GT_PR','PT_PR','Tt3','T45','Tt5', ...
    'Np','Ng','Wf','GT_accessory_load_power','PT_load_power','Pload'};
maxPreDistortionRelativeDifference = 0;
maxResponseRelativeDifference = 0;
for i = 1:numel(preFieldNames)
    name = preFieldNames{i};
    cleanValue = signals.clean.(name)(:);
    distortedValue = signals.distorted.(name)(:);
    scale = max(1, max(abs(cleanValue)));
    maxPreDistortionRelativeDifference = max( ...
        maxPreDistortionRelativeDifference, ...
        max(abs(distortedValue(preIndex) - cleanValue(preIndex))) / scale);
    maxResponseRelativeDifference = max(maxResponseRelativeDifference, ...
        max(abs(distortedValue - cleanValue)) / scale);
end

boundaryName = {'theta_deg';'kTheta';'Tt1_K';'Pamb_Pa'; ...
    'hpsPower_W';'NpCommand_rpm'};
cleanBoundary = {clean.thetaCollectiveDeg; clean.kTheta; clean.flightTt1; ...
    clean.flightPamb; clean.flightHpsPower; clean.NpDem};
distortedBoundary = {distorted.thetaCollectiveDeg; distorted.kTheta; ...
    distorted.flightTt1; distorted.flightPamb; ...
    distorted.flightHpsPower; distorted.NpDem};
maxAbsDifference = zeros(numel(boundaryName), 1);
for i = 1:numel(boundaryName)
    maxAbsDifference(i) = max(abs( ...
        distortedBoundary{i}(:) - cleanBoundary{i}(:)));
end
boundaryIsolationTable = table(boundaryName, maxAbsDifference);

flowRow = find(strcmp(displayName, 'WIn'), 1);
pt1Row = find(strcmp(displayName, 'Pt1'), 1);
pt1LossDirectionPassed = all( ...
    distorted.flightPt1(lossMask) < clean.flightPt1(lossMask));
flowLossDirectionPassed = meanDelta(flowRow) < 0;
boundaryIsolationPassed = all(maxAbsDifference <= 2e-10);
preDistortionMatched = maxPreDistortionRelativeDifference <= 2e-12;
responseChanged = maxResponseRelativeDifference > 1e-8;
cleanSigmaPassed = max(abs(clean.flightSigmaDist - 1)) <= 2e-11;
scheduledSigmaPassed = max(abs(distorted.flightSigmaDist - ...
    schedule.sigmaDist)) <= 2e-11;
pt1MeanDeltaIsNegative = meanDelta(pt1Row) < 0;

validation = struct();
validation.cleanRunPassed = cleanRun.validation.passed;
validation.distortedRunPassed = distortedRun.validation.passed;
validation.sameTimeGrid = sameTimeGrid;
validation.cleanSigmaPassed = cleanSigmaPassed;
validation.scheduledSigmaPassed = scheduledSigmaPassed;
validation.boundaryIsolationPassed = boundaryIsolationPassed;
validation.preDistortionMatched = preDistortionMatched;
validation.pt1LossDirectionPassed = pt1LossDirectionPassed && ...
    pt1MeanDeltaIsNegative;
validation.flowLossDirectionPassed = flowLossDirectionPassed;
validation.responseChanged = responseChanged;
validation.passed = all(structfun(@(value) logical(value), validation));
if ~validation.passed
    error('sht:flightDataGenS7:cruiseComparisonFailed', ...
        ['C01 畸变对比失败：clean=%d，distorted=%d，time=%d，' ...
         'sigmaClean=%d，sigmaSchedule=%d，isolation=%d，pre=%d，' ...
         'Pt1=%d，WIn=%d，response=%d。'], ...
        validation.cleanRunPassed, validation.distortedRunPassed, ...
        validation.sameTimeGrid, validation.cleanSigmaPassed, ...
        validation.scheduledSigmaPassed, ...
        validation.boundaryIsolationPassed, ...
        validation.preDistortionMatched, ...
        validation.pt1LossDirectionPassed, ...
        validation.flowLossDirectionPassed, validation.responseChanged);
end

comparison = struct();
comparison.stage = '3.1-S7';
comparison.missionId = 'C01_AirCruise';
comparison.cleanVariantId = cleanRun.variantId;
comparison.distortedVariantId = distortedRun.variantId;
comparison.lossStartTime_s = t(firstLossIndex);
comparison.lossEndTime_s = t(find(lossMask, 1, 'last'));
comparison.holdWindowId = 'C_SD';
comparison.effectTable = effectTable;
comparison.boundaryIsolationTable = boundaryIsolationTable;
comparison.maxPreDistortionRelativeDifference = ...
    maxPreDistortionRelativeDifference;
comparison.maxResponseRelativeDifference = maxResponseRelativeDifference;
comparison.validation = validation;
end

