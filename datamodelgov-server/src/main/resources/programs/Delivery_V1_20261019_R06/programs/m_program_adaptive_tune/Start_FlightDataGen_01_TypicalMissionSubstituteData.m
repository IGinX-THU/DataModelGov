function result = Start_FlightDataGen_01_TypicalMissionSubstituteData(userCfg)
%START_FLIGHTDATAGEN_01_TYPICALMISSIONSUBSTITUTEDATA 3.1 飞参替代数据统一入口。
%
% 默认执行第二轮正式实现：分别生成1200 s辨识任务F31-CAL-01和600 s
% 独立验证任务F31-VA-01。默认三部件、159维修正区、Visser16，
% 积分/控制/FOH传感器0.025s推进后10Hz记录；modelMode=1保留六部件。
% 测量链采用“真值 -> FOH一阶动态 -> 偏置 -> 白噪声”
% 测量链；不附加纯延迟，也不执行传感器动态逆补偿。正式Excel只写入
% 编号、时间和11个可测通道（共13列；Mkg不测量且边界为0），真值隔离保存
% 在MiddleData。
% 默认thermalVariant='structured'：生成端独立热网络参数；
% transientVariant='enhanced'：适度增强热时间尺度/间隙修正，不改变惯量。
% shared/legacy仅用于受控对照，不修改辨识端标称资产。
%
% 历史G01/C01首轮实现完整保留，但必须显式配置
% implementationMode='legacyG01C01'才会进入，不再作为默认数据源。
%
% 常用调用：
%   result = Start_FlightDataGen_01_TypicalMissionSubstituteData();
%   result = Start_FlightDataGen_01_TypicalMissionSubstituteData( ...
%       struct('showFigures', false));
%   legacy = Start_FlightDataGen_01_TypicalMissionSubstituteData( ...
%       struct('implementationMode','legacyG01C01'));

thisDir = fileparts(mfilename('fullpath'));
addpath(thisDir);

if nargin < 1 || isempty(userCfg)
    userCfg = struct();
end
if ~isstruct(userCfg) || ~isscalar(userCfg)
    error('sht:flightDataGenS2:badUserConfig', ...
        'userCfg 必须是标量结构体。');
end

% 第二轮默认入口采用长航线、三部件和Visser16。首轮G01/C01
% 代码完整保留，仅在调用者显式指定implementationMode='legacyG01C01'
% 时执行，便于历史结果回归而不让旧合同继续充当当前正式数据源。
implementationMode = 'secondRoundLongMission';
if isfield(userCfg,'implementationMode')
    implementationMode = userCfg.implementationMode;
    userCfg = rmfield(userCfg,'implementationMode');
end
if isstring(implementationMode) && isscalar(implementationMode)
    implementationMode = char(implementationMode);
end
if ~ischar(implementationMode) || size(implementationMode,1)~=1
    error('SHT:F31DataGen:ImplementationMode', ...
        'implementationMode必须为字符向量或标量字符串。');
end
switch lower(strtrim(implementationMode))
    case {'secondroundlongmission','secondround','f31'}
        result = sht_f31_generate_long_missions(userCfg);
        return;
    case {'legacyg01c01','legacy'}
        % 继续执行下方冻结的首轮实现。
    otherwise
        error('SHT:F31DataGen:ImplementationMode', ...
            '未知implementationMode=%s。',implementationMode);
end

%% 3.1 顶部集中配置
% 空设计值表示从 Start_sim 使用的统一基准配置冻结一次；后续任务配平结果
% 只能作为运行初值，不能反向修改这三个归一化设计基准。
entry = struct();
entry.designNpRpm = [];
entry.designPowerW = [];
entry.hpsPower_W = 30000;
entry.deltaPExhaust_Pa = 0;
entry.sampleTime_s = 0.025;
entry.independentTrimEnabled = true;
entry.groundSimulationEnabled = true;
entry.cruiseSimulationEnabled = true;

% 0.75R 处等效总距角与归一化桨距负载因子的首轮工程映射。
entry.thetaZero_deg = 0;
entry.thetaDesign_deg = 12;
entry.profileTorqueFraction = 0.15;
entry.thetaValidRange_deg = [6, 14];

% 飞参测量总开关：true 同时启用一阶动态、偏置和白噪声；false 时
% 三类作用全部关闭，测量值与真值逐点严格一致。delay_s 和 delay
% 子开关仅为通用测量接口兼容字段，3.1 正式入口强制保持 0/false。
entry.measurementErrorEnabled = true;
entry.healthTruthEnabled = true;
entry.installedBoundaryEnabled = true;
entry.measurementProfile = 'flightSparse';
entry.mainRandomSeed = 3101001;

% S9 六维稳态健康真值。数值表示围绕标称部件特性的相对修正量；未列出
% 的 hlthparas 全部为零。GT 两项按本轮确认采用正值 0.03/0.018。
entry.healthTruth = struct( ...
    'HPC_hpW',  0.035, ...
    'HPC_hpEf', -0.020, ...
    'GT_hpW',   0.030, ...
    'GT_hpEf',  0.018, ...
    'PT_hpW',   0.028, ...
    'PT_hpEf', -0.016);

% 测量链工程配置。偏置和噪声幅值复用第2阶段弱误差配置。温度带宽按
% 安装位置分别设置；对应时间常数依次为 Tt1=1.00 s、Tamb=2.00 s、
% Tt3=0.30 s、T45=0.50 s、Tt5=0.60 s，后续仍需用实物标定替换。
entry.measurement = struct();
entry.measurement.fastSensorTimeConstant_s = 0.020;
% 一次飞行数据共用一组对象级公共偏置；只有流量依赖显著的 Wf、T45、
% Tt3 在公共偏置上叠加最大为偏置半宽10%的平滑漂移。白噪声仍由
% 各任务的 randomSeed 独立生成，偏置区间和噪声标准差随数据记录。
entry.measurement.biasRealizationMode = 'configured_fixed';
entry.measurement.biasRandomSeed = entry.mainRandomSeed + 17;
entry.measurement.flowDependentBiasEnabled = true;
entry.measurement.temperatureBandwidth_radps = struct( ...
    'Tt1',  1 / 1.00, ...
    'Tamb', 1 / 2.00, ...
    'Tt3',  1 / 0.30, ...
    'T45',  1 / 0.50, ...
    'Tt5',  1 / 0.60);
entry.measurement.delay_s = 0;
entry.measurement.components = struct( ...
    'dynamics', true, 'delay', false, 'bias', true, 'noise', true);
entry.plotEnabled = true;
entry.saveEnabled = true;
entry.outputDir = fullfile(thisDir, 'TestData', ...
    'flight_data_generation');

% G01：固定 200 m、M=0 的近地悬停/起飞功率需求替代历程。
entry.ground = struct();
entry.ground.missionId = 'G01_GroundTakeoff';
entry.ground.displayName = 'G01 Ground takeoff power substitute';
entry.ground.altitude_m = 200;
entry.ground.mach = 0;
entry.ground.deltaT_K = 10;
entry.ground.deltaTIn_K = 0;
entry.ground.duration_s = 60;
entry.ground.npCommandRatio = 1.0;
entry.ground.sigmaIn = 0.995;
entry.ground.nodeTime_s = [0, 8, 13, 23, 28, 38, 43, 50, 54, 60];
entry.ground.nodeKTheta = [0.92, 0.92, 1.00, 1.00, 0.85, ...
    0.85, 0.95, 0.95, 0.92, 0.92];
entry.ground.nodeSigmaDist = ones(1, 10);
entry.ground.segmentId = { ...
    'G01_01_initial_hover_hold', ...
    'G01_02_takeoff_ramp_up', ...
    'G01_03_high_load_hold', ...
    'G01_04_large_ramp_down', ...
    'G01_05_low_load_hold', ...
    'G01_06_second_ramp_up', ...
    'G01_07_mid_high_hold', ...
    'G01_08_return_to_baseline', ...
    'G01_09_baseline_revisit'};
entry.ground.segmentBaseType = { ...
    'hold', 'transition', 'hold', 'transition', 'hold', ...
    'transition', 'hold', 'transition', 'hold'};
entry.ground.segmentDescription = { ...
    '初始近地悬停负载', ...
    '起飞或爬升功率需求上升', ...
    '起飞高负载保持', ...
    '大幅卸载', ...
    '较低负载保持', ...
    '不同起点的再次加载', ...
    '中高负载保持', ...
    '返回初始负载', ...
    '初始基线回访'};
entry.ground.steadyWindows = local_window_definition( ...
    {'G_S0','G_S1','G_S2','G_S3','G_S0R'}, ...
    [4, 18, 33, 46, 56], [8, 23, 38, 50, 60], ...
    [true, true, true, true, true]);

% C01：固定 2000 m、M=0.20 的巡航负载及独立进气损失历程。
entry.cruise = struct();
entry.cruise.missionId = 'C01_AirCruise';
entry.cruise.displayName = 'C01 Air cruise substitute';
entry.cruise.altitude_m = 2000;
entry.cruise.mach = 0.20;
entry.cruise.deltaT_K = 10;
entry.cruise.deltaTIn_K = 0;
entry.cruise.duration_s = 60;
entry.cruise.npCommandRatio = 1.0;
entry.cruise.sigmaIn = 0.990;
entry.cruise.nodeTime_s = [0, 8, 13, 23, 28, 35, 37, 43, 45, 50, 54, 60];
entry.cruise.nodeKTheta = [0.70, 0.70, 0.82, 0.82, 0.70, 0.70, ...
    0.70, 0.70, 0.70, 0.70, 0.76, 0.76];
entry.cruise.nodeSigmaDist = [1.000, 1.000, 1.000, 1.000, 1.000, ...
    1.000, 0.990, 0.990, 1.000, 1.000, 1.000, 1.000];
entry.cruise.segmentId = { ...
    'C01_01_cruise_baseline_hold', ...
    'C01_02_maneuver_ramp_up', ...
    'C01_03_high_cruise_hold', ...
    'C01_04_return_to_cruise', ...
    'C01_05_clean_baseline_revisit', ...
    'C01_06_distortion_build', ...
    'C01_07_distortion_hold', ...
    'C01_08_distortion_recovery', ...
    'C01_09_clean_boundary_revisit', ...
    'C01_10_moderate_ramp_up', ...
    'C01_11_moderate_cruise_hold'};
entry.cruise.segmentBaseType = { ...
    'hold', 'transition', 'hold', 'transition', 'hold', ...
    'boundaryValidation', 'boundaryValidation', 'boundaryValidation', ...
    'hold', 'transition', 'hold'};
entry.cruise.segmentDescription = { ...
    '平飞巡航基线', ...
    '等效爬升或机动功率需求上升', ...
    '高巡航负载保持', ...
    '返回平飞巡航负载', ...
    '负载变化后的清洁进气基线回访', ...
    '固定总距建立进气损失', ...
    '固定负载保持进气损失', ...
    '固定总距恢复进气边界', ...
    '进气恢复后的清洁基线回访', ...
    '中等幅值负载上升', ...
    '中等巡航负载保持'};
entry.cruise.steadyWindows = local_window_definition( ...
    {'C_S0','C_S1','C_S0R1','C_SD','C_S0R2','C_S2'}, ...
    [4, 18, 31, 39, 47, 56], [8, 23, 35, 43, 50, 60], ...
    [true, true, true, false, true, true]);

% 允许调用者覆盖顶部同名字段；未知字段直接报错，避免拼写错误被静默忽略。
entry = local_merge_known_struct(entry, userCfg, 'userCfg');

baseCfg = sht_default_config();
if isempty(entry.designNpRpm)
    entry.designNpRpm = baseCfg.engine.initial.Np0;
end
if isempty(entry.designPowerW)
    entry.designPowerW = baseCfg.engine.initial.power0;
end
entry.designTorqueNm = entry.designPowerW / ...
    (entry.designNpRpm * pi / 30);

mappingCfg = struct( ...
    'thetaZeroDeg', entry.thetaZero_deg, ...
    'thetaDesignDeg', entry.thetaDesign_deg, ...
    'profileTorqueFraction', entry.profileTorqueFraction, ...
    'thetaValidRangeDeg', entry.thetaValidRange_deg);

entry = local_validate_entry(entry, mappingCfg, baseCfg);
groundMission = local_build_mission(entry.ground, entry, mappingCfg);
cruiseMission = local_build_mission(entry.cruise, entry, mappingCfg);
missions = [groundMission; cruiseMission];
local_validate_mission_set(missions);

% 每条任务都从同一个冻结基准配置出发独立配平。这里故意不把 G01 的
% 末状态或配平结果传给 C01；两个 runtimeConfig 是彼此独立的值结构体。
[healthTruthTable, configuredHealth] = ...
    local_health_truth_vector(entry.healthTruth);
if entry.healthTruthEnabled
    health = configuredHealth;
else
    health = zeros(100, 1);
end
healthTruthTable.activeValue = health(healthTruthTable.matlabIndex);
missions = local_prepare_missions(missions, baseCfg, health, ...
    entry.independentTrimEnabled);

% S9 默认先运行同边界、同指令的零健康参考，再运行健康真值模型。零健康
% 结果只用于验证健康影响，不进入 estimationData。
nominalReference = struct('ground', struct(), 'cruise', struct());
if entry.healthTruthEnabled && ...
        (entry.groundSimulationEnabled || entry.cruiseSimulationEnabled)
    nominalMissions = local_prepare_missions( ...
        [groundMission; cruiseMission], baseCfg, zeros(100, 1), true);
    if entry.groundSimulationEnabled
        nominalGroundOptions = struct( ...
            'requiredMissionId', 'G01_GroundTakeoff', ...
            'stageTag', '3.1-S9-zero-health', ...
            'runVariantId', 'ground_zero_health', ...
            'distortionMode', 'unity', ...
            'baselineReferenceWindowId', 'G_S0', ...
            'baselineRevisitWindowId', 'G_S0R');
        nominalReference.ground = sht_run_flight_mission( ...
            nominalMissions(1), nominalGroundOptions);
    end
    if entry.cruiseSimulationEnabled
        nominalCruiseOptions = struct( ...
            'requiredMissionId', 'C01_AirCruise', ...
            'stageTag', '3.1-S9-zero-health', ...
            'runVariantId', 'designed_distortion_zero_health', ...
            'distortionMode', 'schedule', ...
            'baselineReferenceWindowId', 'C_S0R1', ...
            'baselineRevisitWindowId', 'C_S0R2');
        nominalReference.cruise = sht_run_flight_mission( ...
            nominalMissions(2), nominalCruiseOptions);
    end
end

% G01 与 C01 都只消费各自独立配平得到的 runtimeConfig。即使调用者同时
% 开启两类任务，C01 也不会读取 G01 的末状态。
if entry.groundSimulationEnabled
    runOptions = struct( ...
        'requiredMissionId', 'G01_GroundTakeoff', ...
        'stageTag', '3.1-S9', ...
        'runVariantId', 'ground_active_health', ...
        'distortionMode', 'unity', ...
        'baselineReferenceWindowId', 'G_S0', ...
        'baselineRevisitWindowId', 'G_S0R');
    missions(1).simulationRun = sht_run_flight_mission( ...
        missions(1), runOptions);
    missions(1).simulationRun.measurement = ...
        sht_flight_measurement_model( ...
        missions(1).simulationRun.simulation, ...
        local_measurement_config(entry, 101));
end

if entry.cruiseSimulationEnabled
    % 两次运行共用同一个 C01 独立配平初值。cleanMission 只把
    % nodeSigmaDist 改为 1；环境、总距、控制参数、附件功率和初值不变。
    cleanMission = local_set_cruise_distortion( ...
        missions(2), ones(size(missions(2).definition.nodeSigmaDist)), ...
        entry.sampleTime_s);
    commonCruiseOptions = struct( ...
        'requiredMissionId', 'C01_AirCruise', ...
        'stageTag', '3.1-S9', ...
        'baselineReferenceWindowId', 'C_S0R1', ...
        'baselineRevisitWindowId', 'C_S0R2');
    cleanOptions = commonCruiseOptions;
    cleanOptions.runVariantId = 'clean_inlet_active_health';
    cleanOptions.distortionMode = 'unity';
    distortedOptions = commonCruiseOptions;
    distortedOptions.runVariantId = 'designed_distortion_active_health';
    distortedOptions.distortionMode = 'schedule';

    missions(2).simulationRuns.clean = sht_run_flight_mission( ...
        cleanMission, cleanOptions);
    missions(2).simulationRuns.distorted = sht_run_flight_mission( ...
        missions(2), distortedOptions);
    % 两条历程使用不同但固定的子种子，各自可逐点复现。测量链只读取
    % 已完成的真值日志，因此不会改变两次 DLL 仿真的状态或控制响应。
    missions(2).simulationRuns.clean.measurement = ...
        sht_flight_measurement_model( ...
        missions(2).simulationRuns.clean.simulation, ...
        local_measurement_config(entry, 201));
    missions(2).simulationRuns.distorted.measurement = ...
        sht_flight_measurement_model( ...
        missions(2).simulationRuns.distorted.simulation, ...
        local_measurement_config(entry, 202));
    missions(2).distortionComparison = local_compare_cruise_runs( ...
        missions(2).simulationRuns.clean, ...
        missions(2).simulationRuns.distorted);
end

% 健康真值关闭时，活动模型本身就是零健康参考，直接复用已验收运行，
% 避免无意义地重复执行完全相同的 DLL 历程。
if ~entry.healthTruthEnabled
    if entry.groundSimulationEnabled
        nominalReference.ground = missions(1).simulationRun;
    end
    if entry.cruiseSimulationEnabled
        nominalReference.cruise = missions(2).simulationRuns.distorted;
    end
end

result = struct();
result.stage = '3.1-S9';
result.entryProgram = mfilename;
result.previewOnly = ~entry.independentTrimEnabled && ...
    ~entry.groundSimulationEnabled && ~entry.cruiseSimulationEnabled;
result.dllCalled = entry.independentTrimEnabled || ...
    entry.groundSimulationEnabled || entry.cruiseSimulationEnabled;
result.independentTrimCompleted = entry.independentTrimEnabled;
result.timeDomainSimulationExecuted = entry.groundSimulationEnabled || ...
    entry.cruiseSimulationEnabled;
result.groundSimulationCompleted = entry.groundSimulationEnabled;
result.cruiseSimulationCompleted = entry.cruiseSimulationEnabled;
result.formalFlightDataGenerated = entry.groundSimulationEnabled && ...
    entry.cruiseSimulationEnabled;
result.flightBoundaryCalculated = true;
result.runtimeBoundaryConfigAvailable = true;
result.runtimeConfigAvailable = entry.independentTrimEnabled;
result.config = entry;
result.design = struct( ...
    'NpRpm', entry.designNpRpm, ...
    'powerW', entry.designPowerW, ...
    'torqueNm', entry.designTorqueNm);
result.collectivePitchMapping = mappingCfg;
result.model = struct( ...
    'stateNames', {{'Np','Ng'}}, ...
    'stateCount', 2, ...
    'transientEffectsEnabled', false, ...
    'externalSecondaryAirEnabled', false);
result.health = health;
result.healthTruthConfigured = configuredHealth;
result.healthTruthTable = healthTruthTable;
result.nominalReference = nominalReference;
result.missions = missions;
result.uncertaintyStudyCompleted = false;
result.uncertaintySummary = struct();
if entry.cruiseSimulationEnabled
    result.cruiseRuns = missions(2).simulationRuns;
    result.cruiseComparison = missions(2).distortionComparison;
else
    result.cruiseRuns = struct();
    result.cruiseComparison = struct();
end
result.summary = local_summary_table(missions);
if entry.independentTrimEnabled
    result.summary.trimConverged = arrayfun( ...
        @(mission) mission.trimValidation.trimConverged, missions);
    result.summary.trimNpError_rpm = arrayfun( ...
        @(mission) mission.trimValidation.npErrorRpm, missions);
    result.summary.trimResidualInfinityNorm = arrayfun( ...
        @(mission) mission.trimValidation.residualInfinityNorm, missions);
    result.summary.trimMaxEngineResidual = arrayfun( ...
        @(mission) mission.trimValidation.maxEngineResidual, missions);
else
    result.summary.trimConverged = false(numel(missions), 1);
    result.summary.trimNpError_rpm = nan(numel(missions), 1);
    result.summary.trimResidualInfinityNorm = nan(numel(missions), 1);
    result.summary.trimMaxEngineResidual = nan(numel(missions), 1);
end
independentTrimPassed = ~entry.independentTrimEnabled || ...
    all(result.summary.trimConverged);
groundSimulationPassed = ~entry.groundSimulationEnabled || ...
    missions(1).simulationRun.validation.passed;
cruiseSimulationPassed = ~entry.cruiseSimulationEnabled || ...
    (missions(2).simulationRuns.clean.validation.passed && ...
     missions(2).simulationRuns.distorted.validation.passed && ...
     missions(2).distortionComparison.validation.passed && ...
     missions(2).simulationRuns.clean.measurement.validation.passed && ...
     missions(2).simulationRuns.distorted.measurement.validation.passed);
measurementPassed = ...
    (~entry.groundSimulationEnabled || ...
        missions(1).simulationRun.measurement.validation.passed) && ...
    (~entry.cruiseSimulationEnabled || ...
        (missions(2).simulationRuns.clean.measurement.validation.passed && ...
         missions(2).simulationRuns.distorted.measurement.validation.passed));
nominalReferencePassed = ...
    (~entry.groundSimulationEnabled || ...
        nominalReference.ground.validation.passed) && ...
    (~entry.cruiseSimulationEnabled || ...
        nominalReference.cruise.validation.passed);
result.validation = struct( ...
    'passed', independentTrimPassed && groundSimulationPassed && ...
        cruiseSimulationPassed && measurementPassed && ...
        nominalReferencePassed, ...
    'independentTrimEnabled', entry.independentTrimEnabled, ...
    'independentTrimPassed', independentTrimPassed, ...
    'groundSimulationEnabled', entry.groundSimulationEnabled, ...
    'groundSimulationPassed', groundSimulationPassed, ...
    'cruiseSimulationEnabled', entry.cruiseSimulationEnabled, ...
    'cruiseSimulationPassed', cruiseSimulationPassed, ...
    'measurementErrorEnabled', entry.measurementErrorEnabled, ...
    'measurementPassed', measurementPassed, ...
    'healthTruthEnabled', entry.healthTruthEnabled, ...
    'activeHealthParameterCount', nnz(health), ...
    'transientHealthParametersZero', nnz(health(59:100)) == 0, ...
    'nominalReferencePassed', nominalReferencePassed, ...
    'uncertaintyStudyEnabled', false, ...
    'uncertaintyStudyPassed', true, ...
    'cruiseSimulationDeferredToS7', false, ...
    'requiredWindowTypes', {{'steadyCandidate','transition', ...
        'settling','boundaryValidation'}}, ...
    'recordCountPerMission', arrayfun( ...
        @(mission) mission.summary.sampleCount, missions).');
result.createdAt = datestr(now, 31);
result.flightData = struct();
result.dataPackageValidation = struct('passed', ...
    ~result.formalFlightDataGenerated);
if result.formalFlightDataGenerated
    packageInput = struct( ...
        'entryProgram', mfilename, ...
        'entryConfig', entry, ...
        'model', result.model, ...
        'missions', missions, ...
        'nominalReference', nominalReference, ...
        'healthTruth', health, ...
        'healthTruthTable', healthTruthTable);
    [result.flightData, result.dataPackageValidation] = ...
        sht_build_flight_data_package(packageInput);
    result.validation.dataPackagePassed = ...
        result.dataPackageValidation.passed;
    result.validation.passed = result.validation.passed && ...
        result.dataPackageValidation.passed;
else
    result.validation.dataPackagePassed = true;
end
result.output = struct('saved', false, 'matFile', '', ...
    'cleanMatFile', '', 'distortedMatFile', '', ...
    'comparisonMatFile', '');

if entry.saveEnabled
    result.output = local_save_preparation(result, entry.outputDir);
end

local_print_summary(result);
result.figures = gobjects(0);
result.previewFigures = gobjects(0);
result.groundFigures = gobjects(0);
result.cruiseFigures = gobjects(0);
result.groundMeasurementFigures = gobjects(0);
result.cruiseMeasurementFigures = gobjects(0);
result.measurementFigures = gobjects(0);
if entry.plotEnabled
    result.previewFigures = local_plot_preview(result);
    if entry.groundSimulationEnabled
        result.groundFigures = local_plot_ground_simulation( ...
            result.missions(1));
        result.groundMeasurementFigures = ...
            local_plot_measurement_comparison( ...
            result.missions(1).simulationRun, 'G01 ground mission');
    end
    if entry.cruiseSimulationEnabled
        result.cruiseFigures = local_plot_cruise_comparison( ...
            result.missions(2));
        result.cruiseMeasurementFigures = ...
            local_plot_measurement_comparison( ...
            result.missions(2).simulationRuns.distorted, ...
            'C01 designed distortion');
    end
    result.measurementFigures = [result.groundMeasurementFigures; ...
        result.cruiseMeasurementFigures];
    result.figures = [result.previewFigures; result.groundFigures; ...
        result.cruiseFigures; result.measurementFigures];
end
end

