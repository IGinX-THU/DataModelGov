function result = Start_SteadyModelUQ_C_04_BlockPilot(userCfg)
%START_STEADYMODELUQ_C_04_BLOCKPILOT 用多种子小样本冻结五核步长。
if nargin < 1, userCfg = struct(); end
timer = tic;
manifest = sht_steady_model_uq_c_io('resolvewritable',userCfg);
step1 = sht_steady_model_uq_c_io('loadstep',manifest,1);
step2 = sht_steady_model_uq_c_io('loadstep',manifest,2);
step3 = sht_steady_model_uq_c_io('loadstep',manifest,3);
contract = step1.contract;
checked=sht_steady_model_uq_c_common('defaultconfig',contract.config);
replicateCount = contract.config.pilotReplicateCount;
particleCount = contract.config.pilotSampleCount;
resumePilot = logical(local_option(userCfg,'resumePilot',true));
replicate = repmat(struct('seed',0,'smc',[],'checkpointFile',''), ...
    replicateCount,1);
center = zeros(contract.parameterCount,replicateCount);
finalScale = zeros(replicateCount,5);
acceptance = zeros(replicateCount,5);

for r = 1:replicateCount
    seed = contract.config.randomSeed+4000+100*r;
    checkpointFile = sht_steady_model_uq_c_io('runfile',manifest, ...
        sprintf('pilot_replicate_%02d.mat',r));
    options = local_smc_options(contract,step3,particleCount,seed, ...
        contract.config.smcPilotTargetEssFraction,contract.config.pilotMoveSweeps, ...
        contract.config.pilotFinalMoveSweeps,contract.config.initialPcnScale);
    profile='legacy_reference';if contract.modelMode==0,profile='quality';end
    options.samplerProfile=char(local_option(userCfg,'cSamplerProfile',checked.cSamplerProfile));
    options.conditionalEssFraction=local_option(userCfg,'cConditionalEssFraction',checked.cConditionalEssFraction);
    options.resampleEssFraction=local_option(userCfg,'cResampleEssFraction',checked.cResampleEssFraction);
    options.referenceShrinkage=local_option(userCfg,'cReferenceShrinkage',checked.cReferenceShrinkage);
    options.referenceEigenvalueFloor=local_option(userCfg,'cReferenceEigenvalueFloor',checked.cReferenceEigenvalueFloor);
    options.globalSingularValues=zeros(contract.parameterCount,1);
    options.globalSingularValues(1:numel(step3.globalSingularValue))=step3.globalSingularValue;
    referenceHash='';
    if strcmp(options.samplerProfile,'quality')
        referenceHash=sht_steady_model_uq_common('filehash',which('sht_tc27_uq_move_reference'));
    end
    signature = struct('contractHash',contract.contractHash, ...
        'samplerSchemaVersion','steady_model_uq_method_c_smc_v6_quality', ...
        'particleCount',particleCount,'seed',seed, ...
        'targetEssFraction',contract.config.smcPilotTargetEssFraction, ...
        'kernelWeights',contract.config.kernelWeights, ...
        'initialPcnScale',contract.config.initialPcnScale, ...
        'maximumStageCount',contract.config.maximumStageCount, ...
        'moveSweeps',contract.config.pilotMoveSweeps, ...
        'finalMoveSweeps',contract.config.pilotFinalMoveSweeps);
    signature.runId=contract.config.runId;
    signature.samplingOptions=options;signature.moveReferenceHash=referenceHash;
    signature.entrySourceHash=sht_steady_model_uq_common('filehash',[mfilename('fullpath'),'.m']);
    signature.likelihood=step2.likelihood;
    signature.smcSourceHash=sht_steady_model_uq_common('filehash',which('sht_steady_model_uq_c_smc'));
    signature.proposal=step3.guidedProposal;
    if isfield(signature.proposal,'createdAt'),signature.proposal=rmfield(signature.proposal,'createdAt');end
    smc = local_load_checkpoint(checkpointFile,signature,resumePilot);
    if isempty(smc)
        if isfield(userCfg,'runControl'),options.runControl=userCfg.runControl;end
        smc = sht_steady_model_uq_c_smc(contract,step1.prior, ...
            step2.likelihood,step3.guidedProposal,options);
        checkpoint = struct('signature',signature,'smc',smc);
        save(checkpointFile,'checkpoint','-v7.3');
    end
    replicate(r).seed = seed;
    replicate(r).smc = smc;
    replicate(r).checkpointFile = checkpointFile;
    center(:,r) = smc.theta*smc.weights(:);
    finalScale(r,:) = smc.finalPcnScale;
    acceptance(r,:) = smc.kernelAcceptance;
end

centerDistance = zeros(replicateCount);
for i = 1:replicateCount
    for j = i+1:replicateCount
        delta = (center(:,i)-center(:,j))./step1.prior.sigma;
        centerDistance(i,j) = norm(delta)/sqrt(contract.parameterCount);
        centerDistance(j,i) = centerDistance(i,j);
    end
end
medianFinalScale = median(finalScale,1);
minimum = contract.config.minimumPcnScale;
maximum = contract.config.maximumPcnScale;
recommendedFormalScale = min(max(medianFinalScale,minimum),maximum);
allReachedPosterior = all(arrayfun(@(x) x.smc.finalBeta==1,replicate));
allDominantComponentsRetained = all(arrayfun( ...
    @(x) x.smc.dominantInitialTargetComponentRetained,replicate));
result = struct('replicate',replicate, ...
    'replicatePosteriorCenter',center, ...
    'replicateCenterDistancePriorScale',centerDistance, ...
    'maximumReplicateCenterDistancePriorScale',max(centerDistance(:)), ...
    'finalPcnScale',finalScale,'kernelAcceptance',acceptance, ...
    'medianFinalPcnScale',medianFinalScale, ...
    'recommendedFormalPcnScale',recommendedFormalScale, ...
    'pilotReplicateCount',replicateCount,'pilotSampleCount',particleCount, ...
    'checkpointEnabled',resumePilot,'allReachedPosterior',allReachedPosterior, ...
    'allDominantInitialTargetComponentsRetained', ...
    allDominantComponentsRetained, ...
    'truthRead',false,'testDataRead',false, ...
    'passed',allReachedPosterior && allDominantComponentsRetained);
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_c_io( ...
    'savestep',manifest,4,'block_pilot',result,runtime);

seed = reshape([replicate.seed],[],1);
stageCount = reshape(arrayfun(@(x) x.smc.stageCount,replicate),[],1);
ess = reshape(arrayfun( ...
    @(x) x.smc.diagnostic.effectiveSampleSize,replicate),[],1);
dllCount = reshape(arrayfun( ...
    @(x) x.smc.dllEvaluationCount,replicate),[],1);
resamplingCount = reshape(arrayfun( ...
    @(x) x.smc.resamplingCount,replicate),[],1);
uniqueAncestorCount = reshape(arrayfun( ...
    @(x) x.smc.uniqueAncestorCount,replicate),[],1);
initialTargetEss = reshape(arrayfun( ...
    @(x) x.smc.initialTargetImportanceEss,replicate),[],1);
initialBestToFinalBestGap = reshape(arrayfun( ...
    @(x) x.smc.initialToFinalBestLogTargetGap,replicate),[],1);
dominantComponentRetained = reshape(arrayfun( ...
    @(x) x.smc.dominantInitialTargetComponentRetained,replicate),[],1);
pilotTable = table(seed,stageCount,ess,resamplingCount, ...
    uniqueAncestorCount,initialTargetEss,initialBestToFinalBestGap, ...
    dominantComponentRetained,dllCount, ...
    acceptance(:,1),acceptance(:,2),acceptance(:,3), ...
    acceptance(:,4),acceptance(:,5), ...
    'VariableNames',{'seed','stage_count','effective_sample_size', ...
    'resampling_count','unique_ancestor_count', ...
    'initial_direct_target_ess','initial_to_final_best_log_target_gap', ...
    'dominant_initial_component_retained','dll_evaluation_count', ...
    'accept_compressor_burner', ...
    'accept_gt','accept_duct_pt_nozzle','accept_fuel_bias', ...
    'accept_global'});
writetable(pilotTable,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC04_pilot_summary.csv'));
fprintf(['[2.4UQ-C.4] 先导完成：%d组x%d粒子，中心最大先验尺度距离' ...
    '=%.3f，推荐正式步长=[%.3f %.3f %.3f %.3f %.3f]。\n'], ...
    replicateCount,particleCount,max(centerDistance(:)),recommendedFormalScale);
fprintf('[2.4UQ-C.4] 产物：%s\n',file);
result.manifest = manifest;
end

function options = local_smc_options( ...
        contract,geometry,count,seed,targetEss,moveSweeps,finalSweeps,scale)
options = struct('particleCount',count,'randomSeed',seed, ...
    'targetEssFraction',targetEss,'moveSweeps',moveSweeps, ...
    'finalMoveSweeps',finalSweeps, ...
    'maximumStageCount',contract.config.maximumStageCount, ...
    'kernelWeights',contract.config.kernelWeights, ...
    'initialPcnScale',scale,'blockIndex',{contract.parameterBlockIndex}, ...
    'blockBasis',{geometry.blockBasis}, ...
    'blockInformedRank',geometry.blockInformedRank, ...
    'globalBasis',geometry.globalBasis, ...
    'globalInformedRank',geometry.globalInformedRank, ...
    'useCache',contract.config.useCache,'verbose',contract.config.verbose);
end

function smc = local_load_checkpoint(file,signature,resumeEnabled)
smc = [];
if exist(file,'file') ~= 2, return; end
assert(resumeEnabled,'SHT:SteadyUQC:ExistingPilotCheckpoint', ...
    '已有先导检查点，禁用恢复时请使用新的runId：%s',file);
saved = load(file,'checkpoint');
if isfield(saved,'checkpoint') && ...
        isfield(saved.checkpoint,'signature') && ...
        isfield(saved.checkpoint,'smc') && ...
        isequaln(saved.checkpoint.signature,signature)
    smc = saved.checkpoint.smc;
else
    error('SHT:SteadyUQC:PilotCheckpointMismatch', ...
        '先导断点目标/采样/源码身份不一致，请使用新的runId，不覆盖旧状态：%s',file);
end
end

function value = local_option(options,name,defaultValue)
if isstruct(options) && isfield(options,name) && ~isempty(options.(name))
    value = options.(name);
else
    value = defaultValue;
end
end
