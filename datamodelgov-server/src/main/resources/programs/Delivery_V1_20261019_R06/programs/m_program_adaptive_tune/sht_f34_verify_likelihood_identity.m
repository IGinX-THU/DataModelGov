function sht_f34_verify_likelihood_identity(L,prepared)
% 核验已保存似然的源码、准备合同和选项；物理缓存不能替代这层身份检查。
% 只校验不改写，不给历史似然或算法检查点补签新身份。
required={'implementationSha256','preparedContractSha256','optionsSha256'};
assert(all(isfield(L,required)),'SHT:F34Entry:LikelihoodStale', ...
    '似然缺少完整身份，请用新runTag重新准备。');
hash=@(x)sht_f33_model_adapt_v2('fileHash',x);
identity=sht_f33_model_adapt_v2('structHash',prepared.contract);
assert(strcmp(L.implementationSha256,hash(which('sht_f34_likelihood')))&& ...
    strcmp(L.preparedContractSha256,identity)&& ...
    strcmp(L.optionsSha256,prepared.contract.optionsSha256), ...
    'SHT:F34Entry:LikelihoodStale', ...
    '似然源码/合同/选项改变，请使用新runTag；不得重签旧缓存。');
end
