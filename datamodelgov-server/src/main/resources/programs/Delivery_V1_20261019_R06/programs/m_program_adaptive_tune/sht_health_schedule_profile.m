function local_validate_anchor(anchor)
assert(isstruct(anchor) && isfield(anchor, 'normalizedNodes') && ...
    isfield(anchor, 'axes'), 'anchor缺少normalizedNodes或axes。');
z = anchor.normalizedNodes(:).';
assert(numel(z) == 6 && abs(z(1)) <= 1e-14 && ...
    abs(z(end) - 1) <= 1e-14 && all(diff(z) > 0), ...
    '归一化节点必须是从0到1严格递增的6节点向量。');
required = {'inlet_corrected_mass_flow', ...
    'burner_inlet_corrected_mass_flow', ...
    'gt_pt_duct_corrected_mass_flow', ...
    'pt_nozzle_duct_corrected_mass_flow', ...
    'ac_corrected_speed','cc_corrected_speed', ...
    'gt_total_pressure_ratio','pt_total_pressure_ratio'};
for i = 1:numel(required)
    assert(isfield(anchor.axes, required{i}), '缺少调度轴：%s。', required{i});
    axis = anchor.axes.(required{i});
    assert(numel(axis.nodes) == numel(z) && all(isfinite(axis.nodes)) && ...
        all(diff(axis.nodes) > 0), '调度轴%s必须有限且严格递增。', required{i});
end

lossAxes = {'inlet_corrected_mass_flow', ...
    'burner_inlet_corrected_mass_flow', ...
    'gt_pt_duct_corrected_mass_flow', ...
    'pt_nozzle_duct_corrected_mass_flow'};
for i = 1:numel(lossAxes)
    axis = anchor.axes.(lossAxes{i});
    assert(isfield(axis, 'operatingNodes') && ...
        numel(axis.operatingNodes) == 7 && ...
        all(isfinite(axis.operatingNodes)) && ...
        all(diff(axis.operatingNodes) > 0), ...
        '压损调度轴%s必须保留七个稳态参考换算流量。', ...
        lossAxes{i});
    assert(isfield(axis, 'connectedOperatingNodes') && ...
        numel(axis.connectedOperatingNodes) == 6 && ...
        all(isfinite(axis.connectedOperatingNodes)) && ...
        all(diff(axis.connectedOperatingNodes) > 0) && ...
        axis.connectedOperatingNodes(1) > 0, ...
        '压损调度轴%s必须保留六个负载接通换算流量。', ...
        lossAxes{i});
    tolerance = 1e-10 * max(1, axis.high);
    assert(any(abs(axis.operatingNodes - axis.idle) <= tolerance) && ...
        any(abs(axis.connectedOperatingNodes - axis.design) <= tolerance), ...
        '压损调度轴%s没有同时包含慢车参考和负载接通设计点。', ...
        lossAxes{i});
end
