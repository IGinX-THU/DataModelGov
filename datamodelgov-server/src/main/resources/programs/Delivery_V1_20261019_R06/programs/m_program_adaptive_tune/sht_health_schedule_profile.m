function schedule = local_curve_schedule(controlZ, controlRelativeIncrement, label)
% 六个非均匀工程节点直接构成分段线性曲线，不进行密采样。
controlZ = controlZ(:).';
controlRelativeIncrement = controlRelativeIncrement(:).';
assert(numel(controlZ) == numel(controlRelativeIncrement) && ...
    all(diff(controlZ) > 0) && all(isfinite(controlRelativeIncrement)), ...
    '%s的控制点无效。', label);
assert(abs(controlZ(1)) <= eps && abs(controlZ(end) - 1) <= eps && ...
    abs(controlRelativeIncrement(end)) <= 1e-14, ...
    '%s必须在设计点满足相对增量为0。', label);
schedule = struct('mode', 'table1d', 'kind', 'linear_increment_table', ...
    'interpolationMethod', 'linear', ...
    'controlNormalizedNodes', controlZ, ...
    'controlRelativeIncrementNodes', controlRelativeIncrement, ...
    'tableNormalizedNodes', controlZ, ...
    'tableRelativeIncrementNodes', controlRelativeIncrement, ...
    'zeroFlowAnchored', false, 'label', label);
end

function schedule = local_loss_curve_schedule(axis, idleFactor, label)
% 压损修正采用一个零流量锚点和六个负载接通工况节点。地面慢车点
% 仅用于确定工程趋势，不作为第八个节点。零节点的相对增量固定为-1，
% 因而对任意k_design都有Delta(0)=-k_design和K_eff(0)=0。
connectedRatio = axis.connectedOperatingNodes(:).' ./ axis.design;
referenceRatio = axis.operatingNodes(:).' ./ axis.design;
assert(numel(connectedRatio) == 6 && all(diff(connectedRatio) > 0) && ...
    connectedRatio(1) > 0, ...
    '%s必须由六个严格递增的负载接通工况换算流量比构成。', label);
assert(isscalar(idleFactor) && idleFactor > 0 && idleFactor < 1, ...
    '%s的慢车端形状因子必须位于(0,1)。', label);

progress = (referenceRatio - referenceRatio(1)) ./ ...
    (referenceRatio(end) - referenceRatio(1));
smoothProgress = 0.15 .* progress + 0.85 .* ...
    (3 .* progress.^2 - 2 .* progress.^3);
idleRatio = axis.idle / axis.design;
idleIndex = find(abs(referenceRatio - idleRatio) <= 1e-10, 1);
designIndex = find(abs(referenceRatio - 1) <= 1e-10, 1);
assert(~isempty(idleIndex) && ~isempty(designIndex) && ...
    idleIndex ~= designIndex, ...
    '%s的参考工况必须包含互异的慢车点和设计点换算流量。', label);
denominator = smoothProgress(designIndex) - smoothProgress(idleIndex);
assert(abs(denominator) > 1e-12, '%s的慢车/设计点坐标不可区分。', label);
factorReference = idleFactor + (1 - idleFactor) .* ...
    (smoothProgress - smoothProgress(idleIndex)) ./ denominator;
factorReference(idleIndex) = idleFactor;
factorReference(designIndex) = 1;
[matched, location] = ismembertol(connectedRatio, referenceRatio, 1e-10, ...
    'DataScale', 1);
