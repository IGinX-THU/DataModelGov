function parameter = local_parameter(dictionary, anchor, cIndex, ...
        designValue, activeTruth, schedule, axisName, rationale)
row = dictionary(dictionary.c_index == cIndex, :);
assert(height(row) == 1, '修正系数h%d未在权威字典中唯一找到。', cIndex);

parameter = local_empty_parameter();
parameter.cIndex = cIndex;
parameter.matlabHealthIndex = row.matlab_health_index;
parameter.matlabStepInIndex = row.matlab_step_in_index;
parameter.name = char(row.name);
parameter.scope = char(row.scope);
parameter.activeTruth = logical(activeTruth);
parameter.mode = schedule.mode;
parameter.scheduleKind = schedule.kind;
parameter.interpolationMethod = schedule.interpolationMethod;
parameter.designValue = designValue;
parameter.controlNormalizedNodes = schedule.controlNormalizedNodes;
parameter.controlRelativeIncrementNodes = ...
    schedule.controlRelativeIncrementNodes;
parameter.normalizedNodes = schedule.tableNormalizedNodes;
parameter.relativeIncrementNodes = schedule.tableRelativeIncrementNodes;
parameter.deltaNodes = designValue .* parameter.relativeIncrementNodes;
parameter.kNodes = designValue + parameter.deltaNodes;
parameter.zeroFlowAnchored = schedule.zeroFlowAnchored;
parameter.nonmonotonic = local_is_nonmonotonic(parameter.kNodes);
parameter.scheduleRange = max(parameter.kNodes) - min(parameter.kNodes);
parameter.rationale = rationale;

if ~strcmp(schedule.mode, 'constant')
    assert(isfield(anchor.axes, axisName), '缺少调度坐标定义：%s。', axisName);
    axis = anchor.axes.(axisName);
    parameter.axisName = axisName;
    parameter.axisLabel = axis.label;
    parameter.axisUnit = axis.unit;
    parameter.axisIdleValue = axis.idle;
    parameter.axisDesignValue = axis.design;
    if parameter.zeroFlowAnchored
        parameter.xNodes = axis.design .* parameter.normalizedNodes;
        parameter.normalizedCoordinateDefinition = ...
            'Wc/Wc_des; zero plus six load-connected operating points';
    else
        parameter.xNodes = axis.low + (axis.high - axis.low) .* ...
            parameter.normalizedNodes;
        parameter.normalizedCoordinateDefinition = ...
            '(x-x_idle)/(x_des-x_idle)';
    end
else
    parameter.axisName = '';
    parameter.axisLabel = '常值';
    parameter.axisUnit = '-';
    parameter.axisIdleValue = NaN;
    parameter.axisDesignValue = NaN;
    parameter.xNodes = parameter.normalizedNodes;
    parameter.normalizedCoordinateDefinition = 'constant';
end

assert(numel(parameter.xNodes) == numel(parameter.kNodes), ...
    'h%d的横坐标与修正系数节点数不一致。', cIndex);
assert(all(isfinite(parameter.kNodes)), 'h%d存在非有限节点。', cIndex);
if ~strcmp(schedule.mode, 'constant')
    tolerance = 1e-10 * max(1, abs(parameter.axisDesignValue));
    designIndex = find(abs(parameter.xNodes - parameter.axisDesignValue) <= ...
        tolerance, 1);
    assert(~isempty(designIndex), 'h%d调度节点没有包含设计点。', cIndex);
    parameter.designNodeIndex = designIndex;
    assert(abs(parameter.deltaNodes(designIndex)) <= 1e-14 && ...
        abs(parameter.kNodes(designIndex) - designValue) <= 1e-14, ...
        'h%d没有满足Delta_d=0和K_d=k_design。', cIndex);
    if parameter.zeroFlowAnchored
        assert(parameter.xNodes(1) == 0 && ...
            abs(parameter.deltaNodes(1) + designValue) <= 1e-14 && ...
            abs(parameter.kNodes(1)) <= 1e-14, ...
            'h%d没有满足Delta_0=-k_design和K(0)=0。', cIndex);
    end
end
end

