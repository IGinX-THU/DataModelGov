function profile = sht_health_schedule_profile(anchor)
%SHT_HEALTH_SCHEDULE_PROFILE 构造六部件稳态修正系数真值及一维调度表。
%
% 输入 anchor 由设计入口读取已确认的固定工程参考坐标，至少包含：
%   anchor.normalizedNodes              统一归一化插值节点；
%   anchor.axes.<axis>.nodes            对应旋转部件物理调度节点；
%   anchor.axes.<axis>.operatingNodes   七个稳态工况的实际坐标；
%   anchor.axes.<axis>.connectedOperatingNodes
%                                       六个负载接通工况的实际坐标。
%   anchor.axes.<axis>.label/unit       坐标名称和单位。
%
% 输出 profile.parameters 只包含六部件模式当前已经实现的64个稳态参数：
%   h0:h15、h16:h25、h30:h39、h44:h53、h71:h88。
% 其中31个参数具有一维查表调度能力，33个参数保持常值。当前真值启用
% 43个参数；10路K_PRec、9个压比修正、Burner_K_Wf 和
% Burner_K_eta 保持为0。
%
% 调度律统一写成
%       K_eff(x) = k_design + Delta(x)
% 本真值参考资产中，旋转部件的Delta(x)使用由七工况AC换算转速分布
% 生成的6个非均匀节点；四项压损修正使用“零流量锚点+六个负载接通
% 工况”共7个节点。6/7是本资产的设计选择，不是DLL接口固定节点数；
% 并令Delta(0)=-k_design，使K_eff随换算流量趋近0而连续趋近0。
% 所有参数共用分段线性插值，覆盖域外固定到最近端点。
%
% 重要边界：本函数只生成MATLAB侧真值和待初始化查表资产，不直接调用DLL。
% 仿真入口通过sht_health_schedule_initialize_dll一次装载Delta表；设计点
% 值仍由stepIn传入，DLL按实时局部状态计算K_eff，避免逐采样往返。

local_validate_anchor(anchor);

dictionary = sht_health_parameter_dictionary(1);
z = anchor.normalizedNodes(:).';

% 这些曲线是替代数据真值的工程先验，不宣称为某型发动机的实测规律。
% 非线性和非单调趋势只由显式控制点给出，插值器不额外制造高阶曲率。
schedule.constant = local_constant_schedule();
schedule.inletLoss = local_loss_curve_schedule( ...
    anchor.axes.inlet_corrected_mass_flow, 0.55, '进气道压损修正曲线');
schedule.burnerLoss = local_loss_curve_schedule( ...
    anchor.axes.burner_inlet_corrected_mass_flow, 0.72, ...
    '燃烧室压损修正曲线');
schedule.gtPtDuctLoss = local_loss_curve_schedule( ...
    anchor.axes.gt_pt_duct_corrected_mass_flow, 0.65, ...
    'GT-PT通道压损修正曲线');
schedule.ptNozzleDuctLoss = local_loss_curve_schedule( ...
    anchor.axes.pt_nozzle_duct_corrected_mass_flow, 0.60, ...
    'PT-喷管通道压损修正曲线');

schedule.hpcFlow = local_curve_schedule(z, ...
    [-0.48, -0.30, -0.18, -0.08, -0.03, 0.00], ...
    'HPC总体流量单调增量曲线');
schedule.hpcEfficiency = local_curve_schedule(z, ...
    [-0.52, -0.22, -0.32, 0.07, -0.04, 0.00], ...
    'HPC总体效率非单调增量曲线');
schedule.gtFlow = local_curve_schedule(z, ...
    [-0.38, -0.13, -0.24, 0.06, -0.05, 0.00], ...
    'GT总体流量非单调增量曲线');
schedule.gtEfficiency = local_curve_schedule(z, ...
    [-0.50, -0.31, -0.19, -0.09, -0.03, 0.00], ...
    'GT总体效率单调增量曲线');
schedule.ptFlow = local_curve_schedule(z, ...
    [-0.42, -0.18, -0.30, 0.08, -0.04, 0.00], ...
    'PT总体流量非单调增量曲线');
schedule.ptEfficiency = local_curve_schedule(z, ...
    [-0.54, -0.33, -0.20, -0.10, -0.04, 0.00], ...
    'PT总体效率单调增量曲线');

parameters = repmat(local_empty_parameter(), 0, 1);
% 参数字典按接口分组顺序追加，数量固定且规模很小；保留这种写法可使
% h0:h15、十路引气和六个局部部件的映射关系直接可读。
%#ok<*AGROW>

% h0:h15：总体部件及流道参数。所有压比修正以0为准；h6燃烧室
% 压损修正明确纳入本轮试车替代数据真值。
parameters(end + 1) = local_parameter(dictionary, anchor, 0, 0.0100, ...
    true, schedule.inletLoss, 'inlet_corrected_mass_flow', ...
    '进气道压损修正按七工况本地换算流量调度。');
parameters(end + 1) = local_parameter(dictionary, anchor, 1, 0.0150, ...
    true, schedule.hpcFlow, 'ac_corrected_speed', ...
    'HPC总体流量能力随AC进口相对换算转速按曲线变化。');
parameters(end + 1) = local_parameter(dictionary, anchor, 2, -0.0200, ...
    true, schedule.hpcEfficiency, 'ac_corrected_speed', ...
    'HPC总体效率采用带局部峰谷的非单调曲线。');
parameters(end + 1) = local_parameter(dictionary, anchor, 3, 0.0, ...
    false, schedule.hpcFlow, 'ac_corrected_speed', ...
    '保留调度接口，但本轮所有压比修正均不启用。');
parameters(end + 1) = local_parameter(dictionary, anchor, 4, 0.0, ...
    false, schedule.constant, '', ...
    '燃油计量修正本轮不作为发动机个体真值。');
parameters(end + 1) = local_parameter(dictionary, anchor, 5, 0.0, ...
    false, schedule.constant, '', ...
    '燃烧效率修正本轮不启用。');
parameters(end + 1) = local_parameter(dictionary, anchor, 6, -0.0100, ...
    true, schedule.burnerLoss, 'burner_inlet_corrected_mass_flow', ...
    '燃烧室压损修正按七工况本地换算流量调度。');
parameters(end + 1) = local_parameter(dictionary, anchor, 7, -0.0200, ...
    true, schedule.gtFlow, 'gt_total_pressure_ratio', ...
    'GT总体通流能力按未修正总物理压比作非单调曲线调度。');
parameters(end + 1) = local_parameter(dictionary, anchor, 8, -0.0180, ...
    true, schedule.gtEfficiency, 'gt_total_pressure_ratio', ...
    'GT总体效率按未修正总物理压比作曲线调度。');
parameters(end + 1) = local_parameter(dictionary, anchor, 9, 0.0, ...
    false, schedule.gtFlow, 'gt_total_pressure_ratio', ...
    '保留调度接口，但本轮所有压比修正均不启用。');
parameters(end + 1) = local_parameter(dictionary, anchor, 10, 0.0120, ...
    true, schedule.gtPtDuctLoss, 'gt_pt_duct_corrected_mass_flow', ...
    'GT-PT通道压损修正按七工况本地换算流量调度。');
parameters(end + 1) = local_parameter(dictionary, anchor, 11, 0.0120, ...
    true, schedule.ptFlow, 'pt_total_pressure_ratio', ...
    'PT总体通流能力按未修正总物理压比作非单调曲线调度。');
parameters(end + 1) = local_parameter(dictionary, anchor, 12, -0.0160, ...
    true, schedule.ptEfficiency, 'pt_total_pressure_ratio', ...
    'PT总体效率按未修正总物理压比作曲线调度。');
