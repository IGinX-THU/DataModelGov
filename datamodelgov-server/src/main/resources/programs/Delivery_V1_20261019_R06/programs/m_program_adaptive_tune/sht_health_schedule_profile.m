    false, schedule.ptFlow, 'pt_total_pressure_ratio', ...
    '保留调度接口，但本轮所有压比修正均不启用。');
parameters(end + 1) = local_parameter(dictionary, anchor, 14, 0.0100, ...
    true, schedule.ptNozzleDuctLoss, ...
    'pt_nozzle_duct_corrected_mass_flow', ...
    'PT-喷管通道压损修正按七工况本地换算流量调度。');
parameters(end + 1) = local_parameter(dictionary, anchor, 15, 0.0200, ...
    true, schedule.constant, '', ...
    '首轮将喷管有效面积差异视为几何常值。');

