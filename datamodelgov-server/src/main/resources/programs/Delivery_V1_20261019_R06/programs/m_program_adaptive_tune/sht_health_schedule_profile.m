for i = 1:10
    parameters(end + 1) = local_parameter(dictionary, anchor, 29 + i, ...
        flowFraction(i), true, schedule.constant, '', ...
        sprintf('%s流量占AC进口流量比例的加性修正。', branchNames{i}));
