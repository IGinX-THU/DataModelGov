function identity=sht_tc27_prepared_identity(route,method,options,preparedFile)
%SHT_TC27_PREPARED_IDENTITY Bind a TC27 preview to its actual inputs.
% Only the preprocessing settings below affect the selected records. Plotting,
% stop requests and output paths are deliberately not part of this identity.
assert(ismember(route,{'steady','transient_instant'})&&ismember(method,{'I','II'}), ...
    'TC27:Preview:Choice','Invalid route or method.');
assert(isfile(preparedFile),'TC27:Preview:Missing','Prepared MAT is missing.');
loaded=load(preparedFile,'result');prepared=loaded.result;
assert(isfield(prepared,'rangeIndex')&&prepared.rangeIndex.completeRangeCoverage&& ...
    isfield(prepared,'inputFiles')&&isfield(prepared,'testSets'), ...
    'TC27:Preview:Incomplete','Prepared data has incomplete source ranges.');

root=fileparts(mfilename('fullpath'));
package=sht_tc27_runtime_package();
settings=local_settings(options);
savedSettings=local_settings(prepared.options);
assert(isequaln(settings,savedSettings),'TC27:Preview:Settings', ...
    'Preprocessing settings changed after preview.');
train=char(string(options.trainingHistoryFile));
steady=char(string(options.steadyTrainingFile));
assert(strcmpi(prepared.inputFiles.trainingHistorySHA256,sht_tc27_file_identity(train))&& ...
    strcmpi(prepared.inputFiles.steadyTrainingSHA256,sht_tc27_file_identity(steady)), ...
    'TC27:Preview:TrainingChanged','Training input changed after preview.');
tests=[options.testPointFiles(:);options.testHistoryFiles(:)];
assert(numel(tests)==numel(prepared.testSets),'TC27:Preview:TestCount', ...
    'Test source count changed after preview.');
testHash=cell(numel(tests),1);
for j=1:numel(tests)
    file=char(string(tests{j}));testHash{j}=sht_tc27_file_identity(file);
    assert(strcmpi(testHash{j},prepared.testSets(j).sourceSHA256), ...
        'TC27:Preview:TestChanged','Test source changed after preview: %s',file);
end
files={'Start_TC27_05_DataPreparation.m','sht_tc27_segment_history.m', ...
    'sht_tc27_export_range_index.m','sht_tc27_estimation_options.m', ...
    'sht_tc27_prepared_identity.m'};
sourceHash=cellfun(@(f)sht_tc27_file_identity(fullfile(root,f)),files,'UniformOutput',false);
identity=struct('schema','TC27_PREPARED_IDENTITY_V1','route',route,'method',method, ...
    'upstreamSHA256',sht_tc27_file_identity(char(string(options.upstreamModelFile))), ...
    'steadyTrainingSHA256',sht_tc27_file_identity(steady), ...
    'trainingHistorySHA256',sht_tc27_file_identity(train), ...
    'testSHA256',{testHash},'preparationSettings',settings, ...
    'preparedSHA256',sht_tc27_file_identity(preparedFile), ...
    'sourceFiles',{files},'sourceSHA256',{sourceHash}, ...
    'runtimePackageId',package.id,'runtimePackageIdentity',package.identity, ...
    'groupCount',prepared.groupCount,'steadyCount',height(prepared.combinedSteady), ...
    'smallHistoryCount',numel(prepared.train.small));
end

function s=local_settings(options)
defaults=struct('minimumSteadyDuration_s',10,'minimumSmallDuration_s',10, ...
    'steadyGuard_s',1,'initializationExclusion_s',5,'screeningLevel','S3', ...
    'clusterSpan',.02,'exceedanceGap_s',.3,'smallAmplitudeLimit',.20, ...
    'eventLeadIn_s',10,'eventRecovery_s',30,'eventGap_s',1, ...
    'includeSmallHistory',true);
s=defaults;names=fieldnames(defaults);
for j=1:numel(names)
    if isfield(options,names{j}),s.(names{j})=options.(names{j});end
end
end
