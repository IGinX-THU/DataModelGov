function output=local_merge(base,user)
output=base;
names=fieldnames(user);
for i=1:numel(names),output.(names{i})=user.(names{i});end
end

function local_mkdir(folder)
if ~isfolder(folder),mkdir(folder);end
end

function local_check_owners(options,paths)
for file={paths.ownerFile,paths.reportOwnerFile}
    if ~isfile(file{1}),continue;end % 历史合同不补写或改签目录所有权。
    fid=fopen(file{1},'rb');assert(fid>=0,'无法读取批次目录合同。');
    cleanup=onCleanup(@()fclose(fid));
    owner=jsondecode(native2unicode(fread(fid,inf,'*uint8').','UTF-8'));
    clear cleanup;
    assert(strcmp(owner.runTag,options.runTag)&& ...
        strcmpi(owner.runDir,paths.runDir)&&strcmpi(owner.reportDir,paths.reportDir), ...
        'SHT:F34Contract:BatchCollision','计算/报告目录属于其他批次，请使用newRunOptions。');
    assert(strcmp(owner.implementationSha256,local_implementation_hash()), ...
        'SHT:F34Contract:PreparedStale', ...
        '此批次曾使用不同源码；保留失败记录，用newRunOptions建立新批次。');
end
end

function local_reserve_paths(options,paths)
local_check_owners(options,paths);
folders={paths.runDir,paths.reportDir};files={paths.ownerFile,paths.reportOwnerFile};
% 两个目录均预检后才写入，不让部分预检失败污染另一方。
for k=1:2
    if isfolder(folders{k})&&~isfile(files{k})
        entries=dir(folders{k});entries=entries(~ismember({entries.name},{'.','..'}));
        assert(isempty(entries),'SHT:F34Contract:UnownedOutput', ...
            '准备合同缺失但目录已有文件，不能覆盖。请用newRunOptions建立新批次：%s',folders{k});
    end
end
owner=struct('schema','F34_RUN_OWNER_V1','runTag',options.runTag, ...
    'runDir',paths.runDir,'reportDir',paths.reportDir, ...
    'implementationSha256',local_implementation_hash());
for k=1:2
    local_mkdir(folders{k});
    if ~isfile(files{k})
        fid=fopen(files{k},'w','n','UTF-8');assert(fid>=0,'不能写新批次目录合同。');
        cleanup=onCleanup(@()fclose(fid));
        fwrite(fid,unicode2native(jsonencode(owner),'UTF-8'),'uint8');clear cleanup;
    end
end
end

function hash=local_implementation_hash()
folder=fileparts(mfilename('fullpath'));
files={[mfilename('fullpath'),'.m'],fullfile(folder,'sht_f34_prior.m'), ...
    fullfile(folder,'sht_f33_model_adapt_v2.m'), ...
    fullfile(folder,'sht_f33_thermal_equilibrium.m'), ...
    fullfile(folder,'sht_f32_replay_history.m')};
dependencies={'sht_thermal_equilibrium_solve.m','sht_tc27_thermal_reuse.m', ...
    'sht_f3_current_contract.m','sht_f33_transient_delivery.m','sht_f34_io.m', ...
    'sht_engine_derivative.m','sht_engine_open.m','sht_lookup_clearance_reference.m', ...
    'sht_health_schedule_initialize_dll.m','sht_exhaust_backpressure.m', ...
    'sht_f33_schedule_parameterization.m','sht_f34_deployment.m','sht_f34_node_prior.m', ...
    'sht_f34_bounded_condition.m','sht_tc24_uq_box_normal.m', ...
    'sht_steady_model_adapt_v2_common.m', ...
    'sht_sobol_points.m','sht_normal_probability.m'};
for j=1:numel(dependencies)
    file=fullfile(folder,dependencies{j});
    assert(isfile(file),'概率/物理依赖不存在：%s',file);files{end+1}=file; %#ok<AGROW>
end
identity=struct('file',strings(numel(files),1),'sha256',strings(numel(files),1));
for i=1:numel(files)
    identity.file(i)=string(files{i});
    identity.sha256(i)=string(sht_f33_model_adapt_v2('fileHash',files{i}));
end
hash=sht_f33_model_adapt_v2('structHash',identity);
end

function local_verify_implementation(contract)
if ~isfield(contract,'implementationSha256')|| ...
        ~strcmp(contract.implementationSha256,local_implementation_hash())
    error('SHT:F34Contract:PreparedStale', ...
        ['源码或数值后端身份已变化，原检查点保持只读，不能直接续算或重签。' ...
        '读取旧结果请用sht_f34_deployment/read或sht_f34_method_d_artifacts/read。' ...
        '新计算先用sht_f34_contract(''newRunOptions'',原配置,''新的独立批次名'')，' ...
        '同时重建outputRoot/reportRoot及内部缓存；不要重复默认步骤01。']);
end
end

function local_verify_frozen_file(fileName,expectedHash,label)
if ~isfile(fileName)||~strcmpi( ...
        sht_f33_model_adapt_v2('fileHash',fileName),expectedHash)
    error('SHT:F34Contract:PreparedStale', ...
        '%s已缺失或变化。先核对来源，再用newRunOptions创建独立批次，不在旧目录重建。',label);
end
