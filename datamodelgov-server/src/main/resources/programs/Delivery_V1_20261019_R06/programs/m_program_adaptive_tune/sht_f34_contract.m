if isfile(paths.preparedFile)
    prepared=local_load_prepared(options);
    return;
end
local_reserve_paths(options,paths);
if ~isfile(options.referenceResultFile)
    error('SHT:F34Contract:Reference','3.3 R1冻结结果不存在：%s。', ...
        options.referenceResultFile);
end

fprintf('\n3.4.1 冻结R1物理与证据合同……\n');
started=tic;
if strcmp(options.referenceKind,'model_excel_and_observations')
    q=options.modelObservationOptions;
    assert(isstruct(q)&&isfield(q,'priorWorkbook')&& ...
        strcmp(q.priorWorkbook,options.referenceResultFile), ...
        'SHT:F34Contract:ModelReference','独立模型评估必须显式绑定同一个模型Excel。');
    q.outputRoot=paths.contextRoot;q.reportRoot=paths.contextReportRoot;
    q.comparisonCacheDirectory=fullfile(paths.contextRoot,'physical_cache');
    q.resultTag=options.runTag;
    [context,contextMetadata]=sht_f33_model_adapt_v2('prepareModelUqContext',q);
else
    assert(strcmp(options.referenceKind,'frozen_fit'),'SHT:F34Contract:ReferenceKind','未知参考类型。');
