function options=local_new_run_options(template,newTag)
old=local_default_options(template);previous=local_paths(old);
assert(~strcmp(old.runTag,char(newTag)),'SHT:F34Contract:SameBatch', ...
    '新计算不能使用原runTag。冻结Excel读取不需要创建新计算。');
options=old;options.runTag=char(newTag);
% 清除旧的显式目录覆盖，所有工作/缓存路径重新从新批次派生。
options.outputRoot='';options.reportRoot='';
paths=local_paths(options);
for target={paths.runDir,paths.reportDir}
    assert(~local_overlap(target{1},previous.runDir)&& ...
        ~local_overlap(target{1},previous.reportDir),'SHT:F34Contract:BatchCollision', ...
        '新批次仍与旧目录交叠，不能在原批次上计算。');
    assert(~isfolder(target{1})&&~isfile(target{1}),'SHT:F34Contract:BatchExists', ...
        '新批次路径已经存在，请选一个从未使用的批次名：%s',target{1});
end
fprintf('只生成配置，尚未开始计算。\nrunTag=%s\noutput=%s\nreport=%s\ncontext=%s\n', ...
    options.runTag,paths.runDir,paths.reportDir,paths.contextRoot);
end

function yes=local_overlap(a,b)
a=lower(local_absolute_path(a));
b=lower(local_absolute_path(b));
yes=strcmp(a,b)||startsWith(a,[b filesep])||startsWith(b,[a filesep]);
end

function value=local_absolute_path(value)
% MATLAB的cd不保证同步JVM的工作目录；相对路径先按MATLAB当前目录展开。
value=char(value);
if ~java.io.File(value).isAbsolute(),value=fullfile(pwd,value);end
value=char(java.io.File(value).getCanonicalPath());
end

function prepared=local_prepare(user)
options=local_default_options(user);
