end

function prepared=local_load_prepared(user)
options=local_default_options(user);
paths=local_paths(options);
if ~isfile(paths.preparedFile)
    error('SHT:F34Contract:Prepared','缺少准备结果，请先运行步骤01：%s。', ...
        paths.preparedFile);
end
loaded=load(paths.preparedFile,'stored');
if ~isfield(loaded,'stored')
    error('SHT:F34Contract:PreparedSchema','准备文件结构无效。');
end
prepared=loaded.stored;
if ~strcmp(prepared.options.runTag,options.runTag)
    error('SHT:F34Contract:BatchCollision', ...
        '此目录属于%s，不是%s。只改标签但保留outputRoot会写回旧批次；请使用newRunOptions。', ...
        prepared.options.runTag,options.runTag);
end
local_check_owners(options,paths);
local_verify_implementation(prepared.contract);
if ~strcmp(prepared.contract.optionsSha256, ...
        sht_f33_model_adapt_v2('structHash',options))
    error('SHT:F34Contract:OptionsChanged', ...
        '当前配置与冻结配置不同。用newRunOptions建立新批次，不能在本目录重复步骤01。');
end
local_verify_frozen_file(options.referenceResultFile, ...
    prepared.contract.referenceResultSha256,'3.3 R1参考结果');
local_verify_frozen_file(prepared.contextMetadata.trainingWorkbook, ...
    prepared.contract.trainingEvidenceSha256,'3.3训练证据');
local_verify_frozen_file(prepared.contextMetadata.stage32File, ...
    prepared.contract.stage32Sha256,'3.2测量对象先验');
local_verify_frozen_file(prepared.prior.sourceWorkbook, ...
    prepared.contract.sourcePosteriorSha256,'上游后验');
if options.modelMode==0,engineConfiguration=sht_f3_three_component_assets('config');
else,engineConfiguration=sht_default_config(struct('engine',struct('modelMode',1)));end
currentArtifacts=sht_engine_artifact_identity(engineConfiguration.engine);
currentArtifactHash=sht_f33_model_adapt_v2('structHash',currentArtifacts);
if ~isfield(prepared.contract,'engineArtifactIdentitySha256')|| ...
        ~strcmp(currentArtifactHash,prepared.contract.engineArtifactIdentitySha256)
    error('SHT:F34Contract:PreparedStale', ...
        '引擎资产身份变化；先核对物理合同，再用newRunOptions建立新批次，不在旧目录重建。');
end
context=prepared.context;
context.thermalSession=sht_f33_thermal_equilibrium('open', ...
    context.replayAssets,context.uqThermalBranch,context.steadyData, ...
    context.options.modelRoute);
prepared.context=context;
prepared.paths=paths;
end

function local_close(prepared)
if isstruct(prepared)&&isfield(prepared,'context')
    sht_f33_model_adapt_v2('closeUqContext',prepared.context);
end
end

function local_validate_options(options)
if ~options.inputCrossCovarianceAssumedZero
    error('SHT:F34Contract:CrossCovariance', ...
        '本轮跨传感器交叉协方差按独立先验为零；非零合同需显式实现，不可仅改标记。');
end
if ~ismember(options.sourceStage,{'2p4','2p7','previous_flight'})
    error('SHT:F34Contract:SourceStage','sourceStage无效。');
end
if ~ismember(options.transitionMode,{'bench_to_flight','flight_to_flight'})
    error('SHT:F34Contract:Transition','transitionMode无效。');
end
if strcmp(options.sourceStage,'previous_flight') && ...
        ~strcmp(options.transitionMode,'flight_to_flight')
    error('SHT:F34Contract:Transition','上一架次来源必须使用flight_to_flight。');
end
if ~strcmp(options.sourceStage,'previous_flight') && ...
        ~strcmp(options.transitionMode,'bench_to_flight')
    error('SHT:F34Contract:Transition', ...
        '2.4/2.7试车后验到首次飞行必须使用bench_to_flight。');
end
qFields={'benchToFlightHealthSigma','flightToFlightHealthSigma', ...
    'benchToFlightShapeSigma','flightToFlightShapeSigma', ...
    'firstFlightKdistSigma','firstFlightFuelSigma_kgps', ...
    'firstFlightFuelShapeSigma_kgps','flightToFlightFuelShapeSigma_kgps', ...
    'flightToFlightKdistSigma','flightToFlightFuelSigma_kgps'};
for i=1:numel(qFields)
    value=options.(qFields{i});
    if any(~isfinite(value(:)))||any(value(:)<=0)
        error('SHT:F34Contract:ProcessCovariance', ...
            '%s必须由有限正标准差构成。',qFields{i});
    end
end
if ~(isscalar(options.benchToFlightHealthSigma)|| ...
        numel(options.benchToFlightHealthSigma)==7)|| ...
        ~(isscalar(options.flightToFlightHealthSigma)|| ...
        numel(options.flightToFlightHealthSigma)==7)|| ...
        ~(isscalar(options.benchToFlightShapeSigma)|| ...
        numel(options.benchToFlightShapeSigma)==7)|| ...
        ~(isscalar(options.flightToFlightShapeSigma)|| ...
        numel(options.flightToFlightShapeSigma)==7)
    error('SHT:F34Contract:ProcessCovariance', ...
        '健康幅值及形状Q标准差必须为标量或7元素向量。');
end
if numel(options.modelDiscrepancyFraction)~=4 || ...
        any(~isfinite(options.modelDiscrepancyFraction(:)))|| ...
        any(options.modelDiscrepancyFraction<=0)
    error('SHT:F34Contract:ModelDiscrepancy','模型差异尺度必须给出4个正数。');
end
if ~isscalar(options.modelDiscrepancyCorrelation)|| ...
        ~isfinite(options.modelDiscrepancyCorrelation)|| ...
        options.modelDiscrepancyCorrelation<0||options.modelDiscrepancyCorrelation>=1
    error('SHT:F34Contract:ModelDiscrepancy', ...
        '模型差异任务内相关系数必须在[0,1)内。');
end
if ~isscalar(options.inputDifferenceScale)||options.inputDifferenceScale<=0|| ...
        ~isscalar(options.shapeDifferenceScale)||options.shapeDifferenceScale<=0
    error('SHT:F34Contract:DifferenceScale','似然差分尺度必须为正标量。');
end
if options.nuisanceFuelMaximumRank>options.nuisanceMaximumRank || ...
        options.nuisanceMaximumRank<1
    error('SHT:F34Contract:NuisanceRank','条件干扰低秩维数配置无效。');
end
if options.methodCParticleCount<32 || ...
        options.methodCParticleCount~=round(options.methodCParticleCount)
    error('SHT:F34Contract:ParticleCount','方法C粒子数至少为32。');
end
if options.methodCConditionalEssFraction<=0|| ...
        options.methodCConditionalEssFraction>=1|| ...
        options.methodCResampleFraction<=0||options.methodCResampleFraction>=1|| ...
        options.methodCDefensivePriorFraction<=0|| ...
        options.methodCDefensivePriorFraction>=1|| ...
        options.methodCMaximumStages<1|| ...
        options.methodCMaximumStages~=round(options.methodCMaximumStages)|| ...
        options.methodCMoveSweeps<0|| ...
        options.methodCMoveSweeps~=round(options.methodCMoveSweeps)|| ...
        options.predictionRepresentativeCount<1|| ...
        options.predictionRepresentativeCount~=round(options.predictionRepresentativeCount)
    error('SHT:F34Contract:SolverOptions','方法C或预测资源配置无效。');
end
if any(options.processCovarianceSensitivityMultiplier<=0) || ...
        ~any(abs(options.processCovarianceSensitivityMultiplier-1)<eps)
    error('SHT:F34Contract:QSensitivity','Q敏感性倍率必须为正且包含1。');
end
end

