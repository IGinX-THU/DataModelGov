    'prepareUqContext',options.referenceResultFile,struct( ...
    'outputRoot',paths.contextRoot,'reportRoot',paths.contextReportRoot, ...
    'comparisonCacheDirectory','','progressFile','','runControl',[], ...
    'resultTag',options.runTag));
end
if strcmp(options.sourceStage,'previous_flight')
    previous=sht_f34_io('readPosterior',options.sourcePosteriorFile);
    context=sht_f34_deployment('inheritGeometry',context,previous,options);
end
cleanup=onCleanup(@()sht_f33_model_adapt_v2('closeUqContext',context)); %#ok<NASGU>
if options.modelMode==0,engineConfiguration=context.replayAssets.configuration;
else,engineConfiguration=sht_default_config(struct('engine',struct('modelMode',1)));end
engineArtifactIdentity=sht_engine_artifact_identity(engineConfiguration.engine);
context.uqEngineArtifactIdentity=engineArtifactIdentity;
fprintf('3.4.2 导入上游后验并传播到当前飞行……\n');
prior=sht_f34_prior('build',context,options);

contract=struct('schemaVersion','SHT_F34_R1_CONTRACT_V1', ...
    'createdAt',datestr(now,31),'engineId',options.engineId, ...
    'sortieId',options.sortieId,'parentPosteriorId',options.parentPosteriorId, ...
    'parameterization','R1_STEADY_STEADY_ONLY_SET1_FAMILY_AMPLITUDE', ...
    'observationChannels',{{'Np','Ng','Pt3_eq','Tt45'}}, ...
    'observationCount',4*height(context.steadyData), ...
    'trainingWindowCount',height(context.steadyData), ...
    'trainingEvidenceSha256',context.uqTrainingSourceSha256, ...
    'referenceResultSha256',context.uqReferenceFileSha256, ...
    'stage32Sha256',context.uqStage32FileSha256, ...
    'engineArtifactIdentitySha256',sht_f33_model_adapt_v2( ...
        'structHash',engineArtifactIdentity), ...
    'sourcePosteriorSha256',prior.sourceWorkbookSha256, ...
    'testDataAccessed',false,'truthDataAccessed',false, ...
    'processCovarianceCalibrated',false, ...
    'processCovarianceStatus', ...
        'ENGINEERING_ASSUMPTION_REQUIRES_FUTURE_LONGITUDINAL_STUDY');
contract.parameterDictionarySha256=sht_f33_model_adapt_v2( ...
    'structHash',context.parameterContract);
contract.modelMode=options.modelMode;
contract.referenceKind=options.referenceKind;
if isfield(context.priorSchedule,'fixedTransient')
    contract.fixedTransient=context.priorSchedule.fixedTransient;
    contract.uqScope='steady_parameters_conditional_on_fixed_13_transient';
end
contract.taskSourceIdentity=options.taskSourceIdentity;
if options.modelMode==0,contract=rmfield(contract,'createdAt');end
contract.parameterization=[upper(context.options.modelRoute),'_STEADY_ONLY_SET1_', ...
    upper(context.options.scheduleParameterization)];
if strcmp(context.options.modelRoute,'transient_instant')
    contract.observationChannels={'Pt3_eq','Tt45','dNp_dt','dNg_dt'};
end
contract.priorSummarySha256=sht_f33_model_adapt_v2( ...
    'structHash',prior.summary);
contract.optionsSha256=sht_f33_model_adapt_v2('structHash',options);
contract.implementationSha256=local_implementation_hash();

prepared=struct('schemaVersion','SHT_F34_R1_PREPARED_V1', ...
    'options',options,'paths',paths,'contract',contract, ...
    'context',context,'contextMetadata',contextMetadata,'prior',prior, ...
    'runtime_s',toc(started));

% containers.Map只用于单次MATLAB进程的物理缓存，不写入阶段合同。
stored=prepared;
if isfield(stored.context,'thermalSession')
    stored.context=rmfield(stored.context,'thermalSession');
end
save(paths.preparedFile,'stored','-v7.3');
writetable(prior.summary,fullfile(paths.reportDir,'prior_parameter_summary.csv'));
fprintf('准备完成：%d维显式参数，%d维条件干扰，耗时 %.1f s。\n', ...
    height(prior.parameterTable),prior.shape.retainedRank,prepared.runtime_s);
