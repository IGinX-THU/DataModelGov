function varargout=sht_f34_contract(action,varargin)
%SHT_F34_CONTRACT 3.4 R1运行合同、路径和冻结上下文。
%
% 本模块只负责冻结输入和配置，不执行后验采样。正式推断只能通过这里
% 固定的3.3 R1训练证据、2.4上游后验、模型资产及误差假设启动；测试集
% 和3.1隐藏真值不进入该合同。

switch lower(char(action))
    case 'defaultoptions'
        varargout{1}=local_default_options(local_first(varargin));
    case 'paths'
        options=local_default_options(local_first(varargin));
        varargout{1}=local_paths(options);
    case 'reserve'
        % 仅登记原路径所有权；打开控制目录前调用，不建立DLL或概率目标。
        options=local_default_options(local_first(varargin));
        paths=local_paths(options);local_reserve_paths(options,paths);
        varargout{1}=paths;
    case 'newrunoptions'
        % 只构造新批次配置和检查路径，不启动DLL、准备、似然或采样。
        varargout{1}=local_new_run_options(varargin{:});
    case 'prepare'
        varargout{1}=local_prepare(local_first(varargin));
    case 'loadprepared'
        varargout{1}=local_load_prepared(local_first(varargin));
    case 'implementationhash'
        varargout{1}=local_implementation_hash();
    case 'verifyimplementation'
        % 直接调用C/D也须验证实际数值后端，不能绕过文件入口的续算保护。
        local_verify_implementation(varargin{1});
    case 'close'
        local_close(varargin{1});
    otherwise
        error('SHT:F34Contract:Action','未知合同动作：%s。',char(action));
end
end

