function quantile = local_weighted_quantile(value,weight,probability)
weight = weight(:)/sum(weight);
probability = probability(:).';
quantile = zeros(size(value,1),numel(probability));
for row = 1:size(value,1)
    [sortedValue,index] = sort(value(row,:));
    sortedWeight = weight(index);
    cumulative = cumsum(sortedWeight);
    cumulative(end) = 1;
    for p = 1:numel(probability)
        first = find(cumulative>=probability(p),1,'first');
        quantile(row,p) = sortedValue(first);
    end
end
end

function value = local_positive_integer(options,name,defaultValue)
value = local_option(options,name,defaultValue);
if ~isscalar(value) || ~isnumeric(value) || ~isfinite(value) || ...
        value < 1 || value ~= floor(value)
    error('SHT:SteadyUQC:BadPositiveInteger','%s必须为正整数。',name);
end
value = double(value);
end

function value = local_option(options,name,defaultValue)
if isstruct(options) && isfield(options,name) && ~isempty(options.(name))
    value = options.(name);
else
    value = defaultValue;
end
