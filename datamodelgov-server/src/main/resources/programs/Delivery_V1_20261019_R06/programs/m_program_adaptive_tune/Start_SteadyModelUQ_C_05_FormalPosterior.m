function result = Start_SteadyModelUQ_C_05_FormalPosterior(userCfg)
%START_STEADYMODELUQ_C_05_FORMALPOSTERIOR 生成方法C正式后验并输出诊断。
if nargin < 1, userCfg = struct(); end
timer = tic;
manifest = sht_steady_model_uq_c_io('resolvewritable',userCfg);
step1 = sht_steady_model_uq_c_io('loadstep',manifest,1);
step2 = sht_steady_model_uq_c_io('loadstep',manifest,2);
step3 = sht_steady_model_uq_c_io('loadstep',manifest,3);
step4 = sht_steady_model_uq_c_io('loadstep',manifest,4);
contract = step1.contract;
checked=sht_steady_model_uq_c_common('defaultconfig',contract.config);
count = local_positive_integer(userCfg,'formalSampleCount', ...
    contract.config.formalSampleCount);
seed = contract.config.randomSeed+5001;
% 独立复算只更改采样种子，不能连带更改误差传播或附加参数参考。
seed=local_option(userCfg,'cSamplingSeed',checked.cSamplingSeed);
initialScale = step4.recommendedFormalPcnScale;
options = struct('particleCount',count,'randomSeed',seed, ...
    'targetEssFraction',contract.config.smcFormalTargetEssFraction, ...
    'moveSweeps',contract.config.formalMoveSweeps, ...
    'finalMoveSweeps',contract.config.formalFinalMoveSweeps, ...
    'maximumStageCount',contract.config.maximumStageCount, ...
    'kernelWeights',contract.config.kernelWeights, ...
    'initialPcnScale',initialScale, ...
    'blockIndex',{contract.parameterBlockIndex}, ...
    'blockBasis',{step3.blockBasis}, ...
    'blockInformedRank',step3.blockInformedRank, ...
    'globalBasis',step3.globalBasis, ...
    'globalInformedRank',step3.globalInformedRank, ...
    'useCache',contract.config.useCache,'verbose',contract.config.verbose);
profile='legacy_reference';if contract.modelMode==0,profile='quality';end
options.samplerProfile=char(local_option(userCfg,'cSamplerProfile',checked.cSamplerProfile));
options.conditionalEssFraction=local_option(userCfg,'cConditionalEssFraction',checked.cConditionalEssFraction);
options.resampleEssFraction=local_option(userCfg,'cResampleEssFraction',checked.cResampleEssFraction);
options.referenceShrinkage=local_option(userCfg,'cReferenceShrinkage',checked.cReferenceShrinkage);
options.referenceEigenvalueFloor=local_option(userCfg,'cReferenceEigenvalueFloor',checked.cReferenceEigenvalueFloor);
options.globalSingularValues=zeros(contract.parameterCount,1);
options.globalSingularValues(1:numel(step3.globalSingularValue))=step3.globalSingularValue;
referenceHash='';
if strcmp(options.samplerProfile,'quality')
    referenceHash=sht_steady_model_uq_common('filehash',which('sht_tc27_uq_move_reference'));
end

checkpointFile = sht_steady_model_uq_c_io( ...
    'runfile',manifest,'formal_posterior_checkpoint.mat');
signature = struct('contractHash',contract.contractHash, ...
    'samplerSchemaVersion','steady_model_uq_method_c_smc_v6_quality', ...
    'particleCount',count,'seed',seed,'initialScale',initialScale, ...
    'kernelWeights',contract.config.kernelWeights, ...
    'targetEssFraction',contract.config.smcFormalTargetEssFraction, ...
    'maximumStageCount',contract.config.maximumStageCount, ...
    'moveSweeps',contract.config.formalMoveSweeps, ...
    'finalMoveSweeps',contract.config.formalFinalMoveSweeps);
signature.runId=contract.config.runId;
signature.samplingOptions=options;
signature.entrySourceHash=sht_steady_model_uq_common('filehash',[mfilename('fullpath'),'.m']);
signature.moveReferenceHash=referenceHash;
signature.likelihood=step2.likelihood;
signature.smcSourceHash=sht_steady_model_uq_common('filehash',which('sht_steady_model_uq_c_smc'));
signature.proposal=step3.guidedProposal;
if isfield(signature.proposal,'createdAt'),signature.proposal=rmfield(signature.proposal,'createdAt');end
formal = local_load_checkpoint(checkpointFile,signature, ...
    logical(local_option(userCfg,'resumeFormal',true)));
if isempty(formal)
    if isfield(userCfg,'runControl'),options.runControl=userCfg.runControl;end
    formal = sht_steady_model_uq_c_smc(contract,step1.prior, ...
        step2.likelihood,step3.guidedProposal,options);
    checkpoint = struct('signature',signature,'formal',formal);
    save(checkpointFile,'checkpoint','-v7.3');
end
reconstructedLatent = sht_steady_model_uq_sampler( ...
    'thetatolatent',step1.prior,formal.theta);
recomputedLogPriorLatent = sht_steady_model_uq_b_proposal( ...
    'logpriorlatent',reconstructedLatent);
recomputedLogQ = sht_steady_model_uq_b_proposal( ...
    'logdensity',step3.guidedProposal,reconstructedLatent, ...
    formal.initialProposalDensityWeight);
recomputedLogLikelihood = sht_steady_model_uq_likelihood( ...
    'evaluate',step2.likelihood,formal.exact.residual,formal.exact.valid);
recomputedLogPrior = sht_steady_model_uq_sampler( ...
    'logprior',step1.prior,formal.theta);
bridgeAudit = struct( ...
    'maximumLogPriorLatentDifference', ...
    max(abs(recomputedLogPriorLatent-formal.logPriorLatent)), ...
    'maximumLogQDifference',max(abs(recomputedLogQ-formal.logQ)), ...
    'maximumLogLikelihoodDifference', ...
    max(abs(recomputedLogLikelihood-formal.logLikelihood)), ...
    'maximumPhysicalLogPriorDifference', ...
    max(abs(recomputedLogPrior-formal.logPrior)), ...
    'directVsSmcLogEvidenceDifference', ...
    formal.logEvidenceEstimate-formal.initialDirectLogEvidenceEstimate);
bridgeAudit.passed = ...
    bridgeAudit.maximumLogPriorLatentDifference<=1e-10 && ...
    bridgeAudit.maximumLogQDifference<=1e-10 && ...
    bridgeAudit.maximumLogLikelihoodDifference<=1e-10 && ...
    bridgeAudit.maximumPhysicalLogPriorDifference<=1e-10;
formal.latent = reconstructedLatent;
formal.bridgeAudit = bridgeAudit;
formal.method = ...
    'method_c_proposal_to_posterior_bridge_five_kernel_smc';
formal.logRawWeight = log(max(formal.weights,realmin));
formal.logProposal = nan(size(formal.weights));
formal.exactCandidateCount = count+sum(formal.kernelAttempted);
formal.newDllReplayCount = formal.dllEvaluationCount;

minimumEss = max(contract.config.minimumEffectiveSampleSize, ...
    contract.config.minimumEffectiveSampleFraction*count);
maximumWeight = max(formal.weights);
distinctFraction = local_distinct_fraction(formal.theta,contract.priorSigma);
allKernelCovered = all(formal.kernelAttempted > 0);
budgetPassed = all([formal.stage.proposal_budget_expected] == ...
    [formal.stage.proposal_budget_actual]);
singlePopulationPassed = formal.populationCount==1 && ...
    formal.singleGlobalWeightVector && ~formal.postHocPosteriorPoolingUsed;
genealogyCollapsed = formal.resamplingCount>0 && ...
    formal.uniqueAncestorCount==1;
dominantComponentRetained = ...
    formal.dominantInitialTargetComponentRetained;
effectiveInformationDimension = max(1,step3.globalInformedRank);
referenceLogTargetGapLimit = local_option(userCfg, ...
    'maximumReferenceLogTargetGap', ...
    local_reference_log_target_gap_limit(effectiveInformationDimension));
bestReferenceLogTargetLatent = max([step3.anchorLogTargetLatent(:); ...
    formal.initialBestLogTargetLatent]);
bestFormalLogTargetLatent = max(formal.logTargetLatent);
referenceLogTargetGap = max(0, ...
    bestReferenceLogTargetLatent-bestFormalLogTargetLatent);
referenceRegionVisited = referenceLogTargetGap <= referenceLogTargetGapLimit;
betaPassed = formal.finalBeta==1;
essPassed = formal.diagnostic.effectiveSampleSize>=minimumEss;
maximumWeightPassed = ...
    maximumWeight<=contract.config.maximumNormalizedWeight;
distinctPassed = distinctFraction>=0.25;
finiteMeanPassed = all(isfinite(formal.theta*formal.weights(:)));
bridgeIntegrityPassed = bridgeAudit.passed;
passed = betaPassed && essPassed && maximumWeightPassed && ...
    distinctPassed && allKernelCovered && budgetPassed && ...
    singlePopulationPassed && dominantComponentRetained && ...
    referenceRegionVisited && finiteMeanPassed && bridgeIntegrityPassed;
formal.passed = passed;
% passed仅表示既有数值/物理诊断通过，不自动宣称独立精度或区间校准。
formal.statisticalCalibrationEstablished=false;
formal.repeatabilityStatus='REQUIRES_INDEPENDENT_SEEDS';
formal.maximumNormalizedWeight = maximumWeight;
formal.distinctParticleFraction = distinctFraction;
formal.proposalBudgetPassed = budgetPassed;
formal.allKernelCovered = allKernelCovered;
formal.genealogyCollapsed = genealogyCollapsed;
formal.referenceLogTargetGapLimit = referenceLogTargetGapLimit;
formal.bestReferenceLogTargetLatent = bestReferenceLogTargetLatent;
formal.bestFormalLogTargetLatent = bestFormalLogTargetLatent;
formal.referenceLogTargetGap = referenceLogTargetGap;
formal.referenceRegionVisited = referenceRegionVisited;

weights = formal.weights(:)/sum(formal.weights);
summaryTable = sht_steady_model_uq_sampler( ...
    'summary',formal.theta,weights,contract);
summaryTable.c_index = contract.parameterTable.c_index;
summaryTable.group_kind = contract.parameterTable.group_kind;
summaryTable.kernel_name = local_parameter_kernel_name(contract);
posteriorMean = formal.theta*weights;
centered = formal.theta-posteriorMean;
normalizer = max(1-sum(weights.^2),eps);
posteriorCovariance = (centered.*sqrt(weights.'))* ...
    (centered.*sqrt(weights.')).'/normalizer;
posteriorCovariance = 0.5*(posteriorCovariance+posteriorCovariance.');
posteriorStd = sqrt(max(diag(posteriorCovariance),0));
posteriorCorrelation = posteriorCovariance ./ ...
    max(posteriorStd*posteriorStd.',eps);
[observation,observationLabel,observationUnit] = ...
    sht_steady_model_uq_common('observation',contract.baseContract, ...
    contract.trainingData);
posteriorPrediction = observation+formal.exact.residual;
posteriorPredictionMean = posteriorPrediction*weights;
posteriorPredictionQuantile = local_weighted_quantile( ...
    posteriorPrediction,weights,[0.025,0.5,0.975]);
outputFitTable = table((1:numel(observation)).',observationLabel, ...
    observationUnit,observation,posteriorPredictionMean, ...
    posteriorPredictionQuantile(:,2),posteriorPredictionQuantile(:,1), ...
    posteriorPredictionQuantile(:,3), ...
    observation>=posteriorPredictionQuantile(:,1) & ...
    observation<=posteriorPredictionQuantile(:,3), ...
    'VariableNames',{'index','label','unit','measurement', ...
    'posterior_model_mean','posterior_model_median', ...
    'posterior_model_q025','posterior_model_q975', ...
    'measurement_inside_parameter_95_interval'});
[bestLogLikelihood,bestIndex] = max(formal.logLikelihood);
bestResidual = formal.exact.residual(:,bestIndex);
% 与采样似然保持同一口径，包含边缘化干扰的非零均值漂移。
[~,bestDetail]=sht_steady_model_uq_likelihood( ...
    'evaluate',step2.likelihood,bestResidual,true);
bestMahalanobisSquared=bestDetail.mahalanobisSquared;
[bestLogTargetLatent,bestTargetIndex] = max(formal.logTargetLatent);

proposalComponent = (1:numel(formal.initialTargetComponentMass)).';
initialTargetMass = formal.initialTargetComponentMass(:);
finalAncestorMass = formal.finalAncestorComponentMass(:);
isDominantInitialComponent = proposalComponent == ...
    formal.dominantInitialTargetComponent;
componentCoverageTable = table(proposalComponent,initialTargetMass, ...
    finalAncestorMass,isDominantInitialComponent, ...
    'VariableNames',{'proposal_component','initial_direct_target_mass', ...
    'final_ancestor_mass','is_dominant_initial_component'});
referenceName = [string(step3.anchorName(:));"best_initial_proposal"; ...
    "best_formal_particle"];
referenceLogTarget = [step3.anchorLogTargetLatent(:); ...
    formal.initialBestLogTargetLatent;bestFormalLogTargetLatent];
referenceGapFromBest = max(referenceLogTarget)-referenceLogTarget;
referenceTable = table(referenceName,referenceLogTarget, ...
    referenceGapFromBest,'VariableNames', ...
    {'reference','latent_log_target','gap_from_best_reference'});
criterion = ["beta_reached_one";"effective_sample_size"; ...
    "maximum_normalized_weight";"distinct_particle_fraction"; ...
    "all_five_kernels_attempted";"proposal_budget_exact"; ...
    "single_global_population";"dominant_initial_component_retained"; ...
    "reference_region_visited";"finite_posterior_mean"; ...
    "bridge_numerical_integrity"];
observed = [formal.finalBeta;formal.diagnostic.effectiveSampleSize; ...
    maximumWeight;distinctFraction;double(allKernelCovered); ...
    double(budgetPassed);double(singlePopulationPassed); ...
    double(dominantComponentRetained);double(referenceLogTargetGap); ...
    double(finiteMeanPassed);double(bridgeIntegrityPassed)];
required = [1;minimumEss;contract.config.maximumNormalizedWeight;0.25; ...
    1;1;1;1;referenceLogTargetGapLimit;1;1];
comparison = ["==";">=";"<=";">=";"==";"==";"==";"==";"<=";"==";"=="];
criterionPassed = [betaPassed;essPassed;maximumWeightPassed; ...
    distinctPassed;allKernelCovered;budgetPassed;singlePopulationPassed; ...
    dominantComponentRetained;referenceRegionVisited;finiteMeanPassed; ...
    bridgeIntegrityPassed];
acceptanceTable = table(criterion,observed,comparison,required, ...
    criterionPassed,'VariableNames',{'criterion','observed','comparison', ...
    'required','passed'});

kernelTable = table(string(formal.kernelNames(:)), ...
    formal.kernelAttempted(:),formal.kernelAccepted(:), ...
    formal.kernelAcceptance(:),formal.kernelNormalizedEsjd(:), ...
    'VariableNames',{'kernel_name','attempted','accepted', ...
    'acceptance','normalized_esjd'});
acceptanceCriteria = struct('minimumEss',minimumEss, ...
    'maximumNormalizedWeight',contract.config.maximumNormalizedWeight, ...
    'minimumDistinctFraction',0.25,'allFiveKernelsAttempted',true, ...
    'exactProposalBudgetPerSweep',true,'singleGlobalPopulation',true, ...
    'dominantInitialTargetComponentRetained',true, ...
    'maximumReferenceLogTargetGap',referenceLogTargetGapLimit, ...
    'bridgeNumericalIntegrityRequired',true, ...
    'singleAncestorIsReportedWarningNotStandaloneFailure',true);
result = struct('formal',formal,'summaryTable',summaryTable, ...
    'posteriorMean',posteriorMean, ...
    'posteriorCovariance',posteriorCovariance, ...
    'posteriorCorrelation',posteriorCorrelation, ...
    'trainingOutputFitTable',outputFitTable, ...
    'kernelTable',kernelTable,'bestSampleIndex',bestIndex, ...
    'bestLogLikelihood',bestLogLikelihood, ...
    'bestMahalanobisSquared',bestMahalanobisSquared, ...
    'bestTargetSampleIndex',bestTargetIndex, ...
    'bestLogTargetLatent',bestLogTargetLatent, ...
    'componentCoverageTable',componentCoverageTable, ...
    'referenceTable',referenceTable, ...
    'acceptanceTable',acceptanceTable, ...
    'bridgeAudit',bridgeAudit, ...
    'effectiveInformationDimension',effectiveInformationDimension, ...
    'referenceLogTargetGap',referenceLogTargetGap, ...
    'referenceLogTargetGapLimit',referenceLogTargetGapLimit, ...
    'referenceRegionVisited',referenceRegionVisited, ...
    'dominantInitialTargetComponentRetained',dominantComponentRetained, ...
    'acceptanceCriteria',acceptanceCriteria, ...
    'truthRead',false,'testDataRead',false,'passed',passed);
runtime = toc(timer);
[manifest,file] = sht_steady_model_uq_c_io( ...
    'savestep',manifest,5,'formal_posterior',result,runtime);
writetable(summaryTable,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC05_parameter_posterior.csv'));
writetable(kernelTable,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC05_five_kernel_diagnostics.csv'));
writetable(componentCoverageTable,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC05_proposal_component_coverage.csv'));
writetable(referenceTable,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC05_reference_log_target.csv'));
writetable(acceptanceTable,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC05_acceptance_criteria.csv'));
if contract.modelMode == 0
    % 推断残差单列诊断，不作为独立新试车的稳态预测区间交付。
    writetable(outputFitTable,sht_steady_model_uq_c_io( ...
        'reportfile',manifest,'UQC05_inference_residual_fit_diagnostic.csv'));
else
    writetable(outputFitTable,sht_steady_model_uq_c_io( ...
        'reportfile',manifest,'UQC05_training_output_posterior.csv'));
end
result.plotAudit(1)=sht_steady_model_uq_common('optionalplot',contract.config, ...
    @()local_plot_intervals(summaryTable,contract,manifest));
result.plotAudit(2)=sht_steady_model_uq_common('optionalplot',contract.config, ...
    @()local_plot_correlation(posteriorCorrelation,contract,manifest));
result.plotAudit(3)=sht_steady_model_uq_common('optionalplot',contract.config, ...
    @()local_plot_smc(formal,contract,manifest));
if contract.modelMode ~= 0
    result.plotAudit(4)=sht_steady_model_uq_common('optionalplot',contract.config, ...
        @()local_plot_training_output(outputFitTable,contract,manifest));
end
plotAudit=result.plotAudit; %#ok<NASGU>
save(sht_steady_model_uq_c_io('runfile',manifest,'step05_plot_audit.mat'),'plotAudit');
fprintf(['[2.4UQ-C.5] 正式后验：N=%d，stage=%d，ESS=%.1f，' ...
    'maxW=%.4f，distinct=%.1f%%，pass=%d。\n'], ...
    count,formal.stageCount,formal.diagnostic.effectiveSampleSize, ...
    maximumWeight,100*distinctFraction,passed);
fprintf(['[2.4UQ-C.5] 五核接受率=[%.1f %.1f %.1f %.1f %.1f]%%，' ...
    '预算检查=%d，精确候选=%d，DLL新计算=%d，DLL计时=%.1f s。\n'], ...
    100*formal.kernelAcceptance,budgetPassed,formal.exactCandidateCount, ...
    formal.dllEvaluationCount,formal.dllRuntime_s);
fprintf(['[2.4UQ-C.5] 条件重采样次数=%d，保留初始祖先=%d/%d，' ...
    '单祖先退化=%d。\n'],formal.resamplingCount, ...
    formal.uniqueAncestorCount,count,genealogyCollapsed);
fprintf(['[2.4UQ-C.5] 初始直接目标ESS=%.2f，分量质量=[%s]，' ...
    '最终祖先质量=[%s]，主导分量保留=%d。\n'], ...
    formal.initialTargetImportanceEss, ...
    strtrim(sprintf('%.4f ',formal.initialTargetComponentMass)), ...
    strtrim(sprintf('%.4f ',formal.finalAncestorComponentMass)), ...
    dominantComponentRetained);
fprintf(['[2.4UQ-C.5] 高密度参考差=%.3f，典型集门限=%.3f，' ...
    '参考区域到达=%d。\n'],referenceLogTargetGap, ...
    referenceLogTargetGapLimit,referenceRegionVisited);
fprintf(['[2.4UQ-C.5] 桥接数值复算=%d，SMC与初始直接IS对数证据差=' ...
    '%.6g（后者ESS=%.2f，仅作诊断）。\n'],bridgeIntegrityPassed, ...
    bridgeAudit.directVsSmcLogEvidenceDifference, ...
    formal.initialTargetImportanceEss);
fprintf('[2.4UQ-C.5] 产物：%s\n',file);
if ~passed
    failed = acceptanceTable.criterion(~acceptanceTable.passed);
    warning('SHT:SteadyUQC:FormalDiagnosticNotPassed', ...
        '方法C后验已完整保存，但以下诊断未通过：%s。', ...
        strjoin(cellstr(failed),', '));
end

if genealogyCollapsed
    warning('SHT:SteadyUQC:SingleInitialAncestor', ...
        ['方法C最终粒子只保留一个初始祖先。该指标不计入后续MCMC移动产生的' ...
        '数值多样性，因此作为路径退化警告报告，不单独否决静态后验。']);
end
result.manifest = manifest;
end

function limit = local_reference_log_target_gap_limit(dimension)
% 对d维标准高斯局部近似，等密度面相对模态的对数密度差为chi2_d/2。
% 采用99.9%典型集外缘作为宽松的遗漏高密度区域报警门限；它只用于
% 发现采样路径退化，不把真实后验强制近似为高斯或单峰。
try
    limit = gammaincinv(0.999,0.5*dimension);
catch
    z = 3.09023230616781;
    chiSquareQuantile = dimension*(1-2/(9*dimension) + ...
        z*sqrt(2/(9*dimension)))^3;
    limit = 0.5*chiSquareQuantile;
end
limit = max(12,limit);
end

function names = local_parameter_kernel_name(contract)
names = strings(contract.parameterCount,1);
for k = 1:4
    names(contract.parameterBlockIndex{k}) = ...
        string(contract.parameterBlockTable.kernel_name(k));
end
end

function fraction = local_distinct_fraction(theta,scale)
normalized = theta./max(scale(:),eps);
rounded = round(normalized*1e9)/1e9;
[~,index] = unique(rounded.','rows','stable');
fraction = numel(index)/size(theta,2);
end

function formal = local_load_checkpoint(file,signature,resumeEnabled)
formal = [];
if exist(file,'file') ~= 2, return; end
assert(resumeEnabled,'SHT:SteadyUQC:ExistingFormalCheckpoint', ...
    '已有正式检查点，禁用恢复时请使用新的runId：%s',file);
saved = load(file,'checkpoint');
if isfield(saved,'checkpoint') && ...
        isfield(saved.checkpoint,'signature') && ...
        isfield(saved.checkpoint,'formal') && ...
        isequaln(saved.checkpoint.signature,signature)
    formal = saved.checkpoint.formal;
else
    error('SHT:SteadyUQC:FormalCheckpointMismatch', ...
        '正式检查点目标/采样/源码身份不一致，请使用新的runId，不覆盖旧状态：%s',file);
end
end

function local_plot_intervals(tbl,contract,manifest)
figureHandle = figure('Visible',contract.config.figureVisible, ...
    'Name','Method C posterior intervals','Position',[100,100,1280,760]);
isFuel = contains(string(tbl.name),'Wf_bias');
for panel = 1:2
    subplot(2,1,panel);
    if panel == 1
        use = find(~isFuel); titleText = '方法C无量纲参数95%可信区间';
        yText = '参数值';
    else
        use = find(isFuel); titleText = '方法C燃油偏置95%可信区间';
        yText = '燃油偏置 (kg/s)';
    end
    x = 1:numel(use); hold on;
    for i = 1:numel(use)
        plot([x(i),x(i)],[tbl.q025(use(i)),tbl.q975(use(i))], ...
            'Color',[0.18,0.45,0.75],'LineWidth',1.2);
    end
    plot(x,tbl.posterior_mean(use),'ko','MarkerFaceColor','k', ...
        'MarkerSize',3); yline(0,'--'); grid on;
    xlabel('参数序号'); ylabel(yText); title(titleText);
    xlim([0.5,numel(use)+0.5]);
end
saveas(figureHandle,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC05_parameter_intervals.png'));
close(figureHandle);
end

