title(sprintf('方法C %d维后验相关矩阵',contract.parameterCount));
saveas(figureHandle,sht_steady_model_uq_c_io( ...
    'reportfile',manifest,'UQC05_posterior_correlation.png'));
close(figureHandle);
end

function local_plot_smc(formal,contract,manifest)
figureHandle = figure('Visible',contract.config.figureVisible, ...
    'Name','Method C SMC diagnostics','Position',[100,100,1150,760]);
beta = [formal.stage.beta];
ess = [formal.stage.ess_before_resample];
ancestor = [formal.stage.unique_ancestor_count];
subplot(2,1,1); yyaxis left;
hBeta = plot(beta,'o-'); ylabel('\beta');
yyaxis right;
hEss = plot(ess,'s-'); hold on;
hAncestor = plot(ancestor,'^-');
ylabel('ESS / unique ancestors'); grid on;
xlabel('SMC层');
legend([hBeta,hEss,hAncestor],{'\beta','ESS','unique ancestors'}, ...
    'Location','best');
title('温度推进、重采样前ESS与初始祖先谱系');
