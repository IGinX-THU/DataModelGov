function c=sht_tc27_uq_contract(user,readOnly)
%SHT_TC27_UQ_CONTRACT TC27独立C/D合同：实际节点、公开先验和训练测量。
% 2.4仅提供参数字典及工程先验规则，不读取其后验。确定性Excel只给出
% 固定节点、提议参考点与预测选根表。测试数据与隐藏真值不进入本合同。
if nargin<1,user=struct();end
if nargin<2,readOnly=false;end
o=struct('tag','R007','integrationStep_s',.025,'outputBatch','', ...
    'modelFile','','modelIdentityFile','','upstreamModelFile','', ...
    'steadyTrainingFile','','trainingHistoryFile','','testPointFiles',{{}}, ...
    'testHistoryFiles',{{}},'preparedFile','','preparationOptions',struct(), ...
    'outputDirectory','','route','','modelMethod','', ...
    'measurementSamples',32,'surrogateTrainingCount',160,'blindCount',24, ...
    'exactCorrectionCount',256,'particleCount',512,'maxRefinementRounds',2, ...
    'randomSeed',20260912,'localSampleCount',512,'dMaxIterations',10,'plot',true, ...
    'observationMode','points_and_histories','predictionHistoriesEnabled',true, ...
    'errorModel','legacy_R007','nuisanceAnchorMode','two_anchor', ...
    'historyDiscrepancy','none','historyCorrelationTime_s',5, ...
    'curveCorrelationLengthScale',1,'deliveryTag','', ...
    'cBoundedNuisance',false,'cBoxIntegrationCount',512,'cConditionalDrawCount',8, ...
    'cSurrogateMode','legacy_lis_gp','cFinalMoveSweeps',512, ...
    'cDirectMoveSweeps',2,'cDirectFinalMoveSweeps',8, ...
    'steadyCBackend','direct_dll','thermalReuseEnabled',false,'cBridgeParticles',256, ...
    'cBridgeMoveSweeps',2,'cBridgeFinalSweeps',4,'cBridgeMaximumStages',16, ...
    'cBridgeBypassProbability',.1,'cSurrogateLikelihoodPower',.8,'cBridgeRefinementCount',128, ...
    'cSamplingSeed',[],'cSamplerProfile','legacy_reference', ...
    'cConditionalEssFraction',.8,'cResampleEssFraction',.55);
f=fieldnames(user);for k=1:numel(f),assert(isfield(o,f{k}),'未知UQ配置%s。',f{k});o.(f{k})=user.(f{k});end
% 直接合同调用同样前置保护；默认512和共享D数值后端的128下限均不改变。
validateattributes(o.localSampleCount,{'numeric'}, ...
    {'scalar','real','finite','integer','>=',128},mfilename,'options.localSampleCount');
assert(~isempty(o.outputDirectory)&&~isempty(o.modelFile), ...
    'TC27:UQ:ExplicitInputs','必须显式提供所选模型Excel和独立输出目录。');
package=sht_tc27_runtime_package();
