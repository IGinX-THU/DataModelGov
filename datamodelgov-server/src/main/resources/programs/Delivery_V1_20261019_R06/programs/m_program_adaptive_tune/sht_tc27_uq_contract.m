    common=.6;ell=.35;if c.parameterTable.group_kind(q(1))=="fuel_bias",common=.8;ell=.4;end
    ell=ell*o.curveCorrelationLengthScale;
    R=.95*(common+(1-common)*exp(-.5*((x-x.')/ell).^2))+.05*eye(numel(q));
    c.priorCorrelation(q,q)=R;
end
c.priorCovariance=c.priorCorrelation.*(c.priorSigma*c.priorSigma.');
c.prior=sht_steady_model_uq_sampler('buildprior',c,c.priorType);
v=input.prepared;
c.trainingData=v.combinedSteady;c.source=v.source;c.histories=v.train.small;
% 仅删除历程似然块，不改变有效稳态窗口、参数节点、独立先验和热模型。
if strcmp(o.observationMode,'steady_points'),c.histories=c.histories([]);end
c.observationMode=o.observationMode;
c.trainingWindows=v.train.windows;
c.sampleCount=c.trainingData.sample_count;assert(all(c.sampleCount>1),'必须保留完整有效段实际样本数。');
c.outputNames={'Np','Ng','Ptb3','Ttb3','Pt45','Tt45','Pt6','Tt6','Wa2'};
if strcmp(d.route,'transient_instant'),c.outputNames(1:2)={'dNp_dt','dNg_dt'};end
c.historyNames={'Np','Ng','Ptb3','Ttb3','Pt45','Tt45','Pt6','Tt6','Wa2'};
c.observed=sht_tc27_uq_data_vector(c.trainingData,c.histories,d.route);
c.nuisance=local_nuisance(p.runtime);c.modelMode=0;c.thermalMode=3;
c.runtimeDirectory=p.runtime;c.runtimeIdentity=package.identity;
c.transientHealth=zeros(13,1);c.route=d.route;c.method=d.method;
c.inputContract=rmfield(input,{'prepared'});c.testSets=v.testSets;
c.npBranchModel=d.npBranchModel;c.options=o;
c.config=sht_steady_model_uq_c_common('defaultconfig',struct('modelMode',0, ...
    'route',d.route,'formalSampleCount',o.particleCount,'randomSeed',o.randomSeed));
ci=c.parameterTable.c_index;
c.parameterBlockIndex={find(ismember(ci,[0,1,2,6])),find(ismember(ci,[7,8])), ...
    find(ismember(ci,[10,11,12,14,15])),find(ci==-1),(1:c.parameterCount).'};
assert(numel(unique(vertcat(c.parameterBlockIndex{1:4})))==c.parameterCount,'采样块必须覆盖全部节点。');
code={'sht_tc27_uq_contract.m','sht_tc27_uq_input_contract.m', ...
    'sht_tc27_uq_check_prepared_data.m','sht_tc27_uq_data_vector.m','sht_tc27_uq_evaluator.m', ...
    'sht_tc27_replay_histories.m','sht_tc27_paths.m', ...
    'sht_tc27_replay.m','sht_tc27_thermal_reuse.m','sht_tc27_schedule_profile.m','sht_tc27_config.m', ...
    'sht_lookup_clearance_reference.m','sht_prepare_clearance_reference_lookup.m', ...
    'sht_clearance_hull_projection.m','sht_tc24_measurement_specification.m', ...
    'sht_tc27_uq_contract.m','sht_tc27_uq_hash.m','sht_tc27_uq_data_vector.m', ...
    'sht_tc27_uq_covariance.m','sht_tc27_uq_point_error.m','sht_tc24_meter_input_sensitivity.m', ...
    'sht_tc27_uq_history_discrepancy.m','sht_tc27_uq_base_transform.m', ...
    'sht_tc27_uq_whiten.m','sht_tc27_uq_method_c.m','sht_tc27_uq_direct_c.m','sht_tc27_uq_exact_correction.m', ...
    'sht_tc27_uq_bounded_target.m','sht_tc27_normal_box.m','sht_tc27_uq_shared_gp.m', ...
    'sht_tc27_uq_surrogate_bridge.m','sht_tc27_uq_da_bridge.m','sht_tc27_uq_energy_gp.m', ...
    'sht_tc27_uq_empirical_summary.m','sht_tc24_uq_measurement.m', ...
    'sht_steady_model_uq_common.m','sht_steady_model_uq_c_common.m', ...
    'sht_steady_model_uq_b_proposal.m','sht_steady_model_uq_likelihood.m', ...
    'sht_tc27_uq_surrogate.m','sht_tc27_uq_smc.m','sht_tc27_uq_move_reference.m','sht_tc27_uq_proposal_identity.m','sht_tc27_uq_spectral_pcn.m','sht_steady_model_uq_sampler.m', ...
    'sht_tc24_uq_method_d.m','sht_tc24_uq_d_difference.m', ...
    'sht_tc24_uq_d_curvature.m','sht_tc24_uq_d_truncated_normal.m', ...
    'Start_TC27_09_UncertaintyAssessment.m'};
physicsCode={'sht_tc27_uq_evaluator.m','sht_tc27_replay.m','sht_tc27_schedule.m','sht_tc27_replay_histories.m', ...
    'sht_tc27_schedule_profile.m','sht_tc27_config.m','sht_default_config.m', ...
    'sht_engine_derivative.m','sht_engine_open.m','sht_thermal_equilibrium_solve.m','sht_tc27_thermal_reuse.m', ...
