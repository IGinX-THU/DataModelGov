function t=local_nuisance(root)
ci=[3;5;9;13;(30:39).';(44:53).'];dict=sht_health_parameter_dictionary(0);
[found,k]=ismember(ci,dict.c_index);assert(all(found));
lo=[repmat(-.025,4,1);repmat(-.0028,10,1);repmat(-.05,10,1)];hi=-lo;
sigma=[repmat(.006,4,1);repmat(.001,10,1);repmat(.015,10,1)];
mdl=fileread(fullfile(root,'Turboshaft-TS.mdl'));
q=regexp(mdl,'(?m)^\s*burnerEfficiency\s*=\s*([^\r\n]+)','tokens','once');
eff=str2double(strtrim(q{1}));hi(2)=min(hi(2),1/eff-1);
q=regexp(mdl,'(?m)^\s*fractionalBleedsEnthalpyVec\s*=([^\r\n]+)','tokens','once');
z=sscanf(q{1},'%f');map=[1,2,3,2,3,4,5,6,7,6,7,8,9,10];assert(numel(z)==14);
for j=1:10,a=z(map==j);lo(14+j)=max(lo(14+j),-min(a));hi(14+j)=min(hi(14+j),1-max(a));end
[mu,var]=sht_steady_model_uq_c_common('truncatedmoments',zeros(24,1),sigma,lo,hi);
t=table(ci,dict.name(k),lo,hi,sigma,mu,var,'VariableNames', ...
    {'c_index','name','lower','upper','sigma','mean','variance'});
end
