assert(ismember(o.observationMode,{'steady_points','points_and_histories'}), ...
    'observationMode仅允许steady_points或points_and_histories。');
assert(strcmp(o.observationMode,'steady_points'), ...
    'TC27:UQ:HistoriesNotValidated','新模型UQ首轮仅验收steady_points，不允许旧历程代理合同。');
validateattributes(o.predictionHistoriesEnabled,{'logical'},{'scalar'});
assert(ismember(o.errorModel,{'legacy_R007','tc24_engineering'}),'未知误差合同。');
assert(ismember(o.nuisanceAnchorMode,{'two_anchor','reference'}),'未知附加参数线性化方式。');
assert(ismember(o.historyDiscrepancy,{'none','correlated_engineering'}),'未知历程模型差异方式。');
validateattributes(o.historyCorrelationTime_s,{'numeric'},{'scalar','finite','positive'});
validateattributes(o.curveCorrelationLengthScale,{'numeric'},{'scalar','finite','positive'});
assert(isempty(o.deliveryTag)||~isempty(regexp(o.deliveryTag,'^[A-Za-z0-9_]+$','once')), ...
    '交付标签只能包含字母、数字和下划线。');
assert(strcmp(o.historyDiscrepancy,'none')||strcmp(o.errorModel,'tc24_engineering'), ...
    '相关历程模型差异必须与TC24工程误差口径配套。');
assert(ismember(o.integrationStep_s,[.025,.05,.1]),'积分步长仅允许已定义的对照值。');
assert(o.measurementSamples>=16&&o.exactCorrectionCount>=32&&o.particleCount>=24);
validateattributes([o.measurementSamples,o.surrogateTrainingCount,o.blindCount, ...
    o.exactCorrectionCount,o.particleCount,o.localSampleCount,o.dMaxIterations], ...
    {'numeric'},{'integer','positive','finite'});
validateattributes(o.maxRefinementRounds,{'numeric'},{'scalar','integer','nonnegative','finite'});
validateattributes(o.cBoundedNuisance,{'logical'},{'scalar'});
validateattributes([o.cBoxIntegrationCount,o.cConditionalDrawCount,o.cFinalMoveSweeps, ...
    o.cDirectMoveSweeps,o.cDirectFinalMoveSweeps], ...
    {'numeric'},{'integer','positive','finite'});
assert(ismember(o.cSurrogateMode,{'legacy_lis_gp','full_latent_shared_matern'}));
assert(ismember(o.steadyCBackend,{'direct_dll','surrogate_bridge','legacy_surrogate'}));
validateattributes(o.thermalReuseEnabled,{'logical'},{'scalar'});
assert(ismember(o.cSamplerProfile,{'quality','legacy_reference'}),'未知C采样配置。');
validateattributes([o.cConditionalEssFraction,o.cResampleEssFraction], ...
    {'numeric'},{'real','finite','>',0,'<',1});
if ~isempty(o.cSamplingSeed)
    validateattributes(o.cSamplingSeed,{'numeric'}, ...
        {'scalar','real','finite','integer','>=',0,'<=',2^32-1});
end
assert(~o.thermalReuseEnabled||strcmp(o.observationMode,'steady_points'), ...
    '热平衡复用首轮只允许仅稳态模式。');
validateattributes([o.cBridgeParticles,o.cBridgeMoveSweeps,o.cBridgeFinalSweeps, ...
    o.cBridgeMaximumStages,o.cBridgeRefinementCount],{'numeric'},{'integer','positive','finite'});
validateattributes(o.cSurrogateLikelihoodPower,{'numeric'},{'scalar','positive','<=',1});
validateattributes(o.cBridgeBypassProbability,{'numeric'},{'scalar','>=',0,'<=',1});
file=char(string(o.modelFile));
d=sht_tc27_delivery('read',[],file);
assert(d.modelMode==0&&d.thermalMode==3&& ...
    ismember(d.route,{'steady','transient_instant'})&&ismember(d.method,{'I','II'}), ...
    'TC27:UQ:ModelRoute','所选Excel不是可用的三部件TC27正式模型。');
assert((isempty(o.route)||strcmp(o.route,d.route))&& ...
    (isempty(o.modelMethod)||strcmp(o.modelMethod,d.method)), ...
    'TC27:UQ:ModelChoice','用户选择的路线/方法与模型Excel不一致。');
sht_tc27_uq_input_contract(o,d,struct('runtime',package.directory),true);
p=sht_tc27_paths(o);
input=sht_tc27_uq_input_contract(o,d,p);
tc24=char(string(o.upstreamModelFile));
a=sht_load_2p4_deterministic_delivery(d.route,tc24,'formal');
nodeOptions=a.model.options;nodeOptions.stageDTikhonovPriorScale=1;nodeOptions.stageDDifferenceStepScale=1;
c=sht_steady_model_adapt_v2_common('m3nodecontract',d.finalSchedule, ...
    a.model.parameterDefinition,d.finalSchedule.fuelBias.wfDesign,nodeOptions);
c.parameterTable.name=c.parameterTable.node_id;c.parameterTable.point_estimate=c.centerVector;
c.thetaHat=c.centerVector;c.priorMean=zeros(c.parameterCount,1);
c.priorType='gaussian_copula_truncated_normal';c.priorCorrelation=zeros(c.parameterCount);
% 与TC24 C相同的独立零中心相关截断先验；燃油与发动机参数分块。
for g=unique(c.parameterTable.group_index).'
